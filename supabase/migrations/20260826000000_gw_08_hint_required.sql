-- خمّن الكلمة — المعنى إجباريّ (م٠ز)
-- طُبِّق ٢٠٢٦-٠٨-٢٦ بإذن المالك.
--
-- ## العلّة
-- كان المعنى اختياريًّا (`hint text` بلا `not null`). وأثرُه أنّ المضيفَ قد يقف في
-- القاعة أمام كلمةٍ لا مرجعَ لها، فيحكم على إجابةٍ أصابت المعنى من ذاكرته وحدها —
-- وهو عينُ ما بُني الحقلُ ليمنعه.
--
-- **وقرارُ المالك ٢٠٢٦-٠٨-٢٦: يُرَدّ ما لا معنى له.** فيصير القيدُ في القاعدة لا في
-- الشاشة وحدَها: شاشةٌ تُلزِم وقاعدةٌ تتساهل تعني أنّ بابًا آخر (لصقٌ جماعيّ · نداءٌ
-- مباشر · ترحيلٌ قادم) يُدخِل كلمةً عرجاء.
--
-- ## ولا صفَّ يُكسَر
-- البنكُ خالٍ (صفرُ صفوفٍ لحظةَ التطبيق — فُحِص)، فلا `update` تمهيديّ ولا قيمةَ
-- افتراضيّةٌ كاذبةٌ تُحشى في صفوفٍ قائمة.
--
-- ## وما يبقى بلا معنًى عمدًا
-- **كلماتُ الغرفة الخاصّة** (`p_custom_words` في `gw_create_session`) تذهب إلى
-- `guess_word_words` لا إلى البنك، وتبقى بلا معنى: كتبها المضيفُ لحظتَها فهو يعرفها،
-- ولا تُحفَظ لموسمٍ قادمٍ يُنسى فيه.

alter table public.guess_word_bank
  drop constraint if exists guess_word_bank_hint_check;

alter table public.guess_word_bank
  alter column hint set not null;

alter table public.guess_word_bank
  add constraint guess_word_bank_hint_check
  check (length(btrim(hint)) between 1 and 200);

comment on column public.guess_word_bank.hint is
  'معنى الكلمة — إجباريّ (قرار المالك ٢٠٢٦-٠٨-٢٦). مرجعُ المضيف وقتَ الحكم، ولا يبلغ لاعبًا أبدًا.';
