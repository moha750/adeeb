-- عطبٌ يُغلق البابَ (٥٠٣)، فلا يُترك حذفُه ممكنًا من متصفّح.
grant select on public.deebo_persona to anon, authenticated;
grant update on public.deebo_persona to authenticated;

drop trigger if exists deebo_persona_touch on public.deebo_persona;
create trigger deebo_persona_touch
  before update on public.deebo_persona
  for each row execute function public.set_updated_at_now();

