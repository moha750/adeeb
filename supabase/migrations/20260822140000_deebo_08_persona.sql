  -- «من أنت» — صيغةُ الحديث عن نفسه، وقصّةُ اسمه، وجوابُ «هل أنت إنسان؟».
  identity            text not null check (length(btrim(identity)) between 2 and 2000),
  tone                text not null check (length(btrim(tone)) between 2 and 1200),
  -- «حدودك» — ما عدا البند الأوّل، فهو سقالةٌ في الكود.
  boundaries          text not null check (length(btrim(boundaries)) between 2 and 4000),
  -- «ما لا تفعله أبدًا» — سطرٌ لكلّ محظور.
  prohibitions        text[] not null default '{}',
  unknown_answer      text not null check (length(btrim(unknown_answer)) between 2 and 400),
  -- الأسئلةُ المقترَحة: **زينةُ شاشةٍ لا توجيه**، فالرقمُ فيها لا يضرّ.
  suggested_questions text[] not null default '{}',
  -- كم منها يُعرض في الشاشة الفارغة. كان قرارًا معلّقًا في ورقة الهويّة (بابُ «ج»)،
  -- فصار رقمًا يقوله المالك بيده لا سطرًا في الكود ينتظر كلمتَه.
  shown_questions     smallint not null default 4 check (shown_questions between 0 and 12),
  updated_by          uuid references auth.users(id) on delete set null,
  updated_at          timestamptz not null default now()
);

-- ═══ (٢) لا رقمَ فيما يدخل التوجيه ══════════════════════════════════════════
-- لاتينيّةٌ وعربيّةٌ وفارسيّة: النموذجُ يقرؤها كلَّها عددًا، والحارسُ يبيحها كلَّها.
alter table public.deebo_persona drop constraint if exists deebo_persona_no_digits;
alter table public.deebo_persona add constraint deebo_persona_no_digits check (
  identity       !~ '[0-9٠-٩۰-۹]'
  and tone       !~ '[0-9٠-٩۰-۹]'
  and boundaries !~ '[0-9٠-٩۰-۹]'
  and unknown_answer !~ '[0-9٠-٩۰-۹]'
  -- والمحظوراتُ تُقرأ نصًّا واحدًا: الاستعلامُ الفرعيّ ممنوعٌ في القيد (0A000).
  and array_to_string(prohibitions, ' ') !~ '[0-9٠-٩۰-۹]'
);

comment on constraint deebo_persona_no_digits on public.deebo_persona is
  'حارسُ الأرقام يبيح للجواب كلَّ عددٍ ورد في التوجيه — فرقمٌ يُكتب في الطبع يُسقط الحارسَ صامتًا.';

-- ═══ (٣) الحراسة ════════════════════════════════════════════════════════════
-- القراءةُ للعموم: ديبو يُسأل من غير جلسة، والشاشةُ العلنيّة تعرض أسئلتَه المقترَحة.
-- وليس في الصفّ ما يُخفى — هذا ما يقوله ديبو لكلّ سائل.
alter table public.deebo_persona enable row level security;

drop policy if exists deebo_persona_read on public.deebo_persona;
create policy deebo_persona_read on public.deebo_persona
  for select to anon, authenticated using (true);

drop policy if exists deebo_persona_write on public.deebo_persona;
create policy deebo_persona_write on public.deebo_persona
  for update to authenticated
  using (check_user_permission((select auth.uid()), 'manage_deebo'))
  with check (check_user_permission((select auth.uid()), 'manage_deebo'));

