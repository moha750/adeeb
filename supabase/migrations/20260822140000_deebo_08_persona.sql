--
-- ⚠️ مكتوبٌ ينتظر إذن المالك. لا يُنفَّذ إلّا بكلمته (قاعدةُ DDL).
--
-- ## تتمّةُ م٧
-- نزلت الوقائعُ إلى `deebo_knowledge` فصار ما **يعرفه** ديبو يُحرَّر من اللوحة، وبقي ما
-- **هو**: نبرتُه وحدودُه ومحظوراتُه في `lib/deebo/persona.ts`. سأل المالك ٢٠٢٦-٠٨-٢٢:
-- «هل هذا يجعلني أستغني عن تدريبه بالمحادثة معك؟» — لا، ما دام طبعُه نصًّا في ملفٍّ
-- يُنشَر. فهذا بيتُه: صفٌّ واحدٌ (`id = 1`) تملؤه شاشةُ `‎/dashboard/deebo/persona`‎،
-- وتصير ورقةُ `المتطلبات/ديبو-الهويّة.md` شاشةً لا ملفًّا يُنقَل منه بيدي.
--
-- ## ولا رقمَ في طبعه — قيدًا لا نصيحة
-- حارسُ `lib/deebo/guard.ts` يبيح لجواب ديبو **كلّ عددٍ ورد في نصّ توجيهه**. فرقمٌ يُكتب
-- ههنا للزينة يصير رقمًا مأذونًا في كلّ جواب، ويسقط الحارسُ كلُّه بلا صوت. ولذلك قيدُ
-- `no_digits` على كلّ عمودٍ يدخل التوجيه، وشاشةُ اللوحة تمنع الحفظ قبل أن تبلغ القاعدة.
-- (والمحظوراتُ شُرَطٌ لا قائمةٌ مرقَّمة للعلّة نفسِها.)
--
-- ## وما بقي في الكود سقالةٌ لا طبع
-- سطرُ الافتتاح، والعناوينُ الخمسة، وبندُ «لا تجيب إلّا ممّا في معرفتك» (بجملة «لا أعرف»
-- من هذا الجدول)، وموضعُ سطرِ التعريف بصاحب الجلسة. تلك بنيةُ التوجيه لا ذوقُه، وتبديلُها
-- يكسر التخزينَ المؤقّت والحارسَ معًا. **والبذرةُ أدناه منقولةٌ عن `persona.ts` حرفًا بحرف**
-- (استُخرجت من نصّ التوجيه المبنيّ نفسِه لا من الذاكرة)، فلا يتبدّل بهذا الترحيل حرفٌ
-- ممّا يقوله ديبو اليوم.

begin;

-- ═══ (١) الصفُّ الواحد ══════════════════════════════════════════════════════
create table if not exists public.deebo_persona (
