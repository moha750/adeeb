-- ════════════════════════════════════════════════════════════════════
-- الجوّال: رفع ٤٣ رقمًا إلى profiles — الخطوة الأولى نحو مصدرٍ واحد
-- ════════════════════════════════════════════════════════════════════
-- المشكلة: الجوّال مكتوب في دفترين — profiles.phone و member_details.phone —
--          ولا شيء يزامنهما. وبين أبريل ومايو كان نموذج التسجيل يكتب الثاني
--          ولا يكتب الأوّل، فسقط ٤٣ عضوًا جوّالهم في دفترٍ واحد وحده.
--
-- شاهده: مُطلِق الاكتمال (check_member_details_completion) يقرأ profiles.phone
--        فيراه فارغًا، فيسم أصحابه «ناقصين» وهم كاملون. ولا عضو واحد في القاعدة
--        بلا جوّال — النقص وسمٌ لا واقع.
--
-- الجرح مغلق لا نازف: الفجوة أبريل–مايو وحدها (٤١ نشطًا + ٢ موقوفَين). وما قبلها
--        وما بعدها — فبراير–مارس ويونيو–يوليو — profiles.phone مملوء فيها كلّها.
--        فالنموذج اليوم يكتبه صحيحًا، وهذا ترميمُ ماضٍ لا سدُّ تسرّب.
--
-- المنقول قيمةٌ لا تتبدّل: نسخُ ما في member_details.phone إلى عمودٍ فارغ. لا
--        تصحيحَ رقمٍ هنا، ولا ترجيحَ دفترٍ على دفتر — من امتلأ عموداه تُرك كما هو.
--
-- المتروك عمدًا: من اختلف دفتراه يُترك لإنسان. منار احمد المليفي: ٠٥٣٠٤٤٨٦١٨ في
--        profiles و ٠٥٣٠٤٤٨٩١٨ في member_details — رقمٌ واحد يفرق، وأحدهما غلط،
--        ولا خوارزمية تعرف أيّهما. الشرط (p.phone IS NULL) يستثنيها من تلقاء نفسه.
--
-- الحارس: trg_guard_terminated_membership_profile يمنع تحرير بيانات المنتهية،
--        و phone خارج قائمة سماحه — فيحجب الموقوفَين من الـ٤٣. يُعطَّل هنا وحده
--        وللحظة: الحارس يمنع **تبديل** بيانات العضو، وهذا نقلُ قيمةٍ لا تتبدّل
--        من عمودٍ إلى عمود — فقصدُه مرعيٌّ لا منتهَك. والتعطيل داخل معاملة الترحيل:
--        إن سقط الترحيل عاد الحارس معه، ولا يبقى الباب مفتوحًا بعد الخروج.
--
-- ما بعدها (ليست في هذا الترحيل): توجيه القرّاء والكتّاب إلى profiles.phone، ثمّ
--        إعدام member_details.phone. ولا يُعدَم قبل هذا الرفع — فيه ٤٣ رقمًا وحيدًا.
--
-- ملاحظة: idempotent — شرط (p.phone IS NULL) يجعل الإعادة بلا أثر.

-- ─────────────────────────────────────────────
-- 1) تعطيل الحارس — للموقوفَين وحدهما، وداخل المعاملة
-- ─────────────────────────────────────────────
ALTER TABLE public.profiles DISABLE TRIGGER trg_guard_terminated_membership_profile;

-- ─────────────────────────────────────────────
-- 2) الرفع — العمود الفارغ وحده يُملأ
-- ─────────────────────────────────────────────
UPDATE public.profiles p
SET phone = md.phone
FROM public.member_details md
WHERE md.user_id = p.id
  AND p.phone IS NULL
  AND md.phone IS NOT NULL;

-- ─────────────────────────────────────────────
-- 3) إعادة الحارس
-- ─────────────────────────────────────────────
ALTER TABLE public.profiles ENABLE TRIGGER trg_guard_terminated_membership_profile;

-- ─────────────────────────────────────────────
-- 4) حارس الترحيل نفسه — لا يمرّ صامتًا إن بقي جوّالٌ يتيم
--    (الصيغة محروسة بـ profiles_phone_check، فلا حاجة لفحصها هنا)
-- ─────────────────────────────────────────────
DO $$
DECLARE
    v_orphans INTEGER;
BEGIN
    SELECT count(*) INTO v_orphans
    FROM public.member_details md
    JOIN public.profiles p ON p.id = md.user_id
    WHERE p.phone IS NULL AND md.phone IS NOT NULL;

    IF v_orphans > 0 THEN
        RAISE EXCEPTION 'بقي % جوّالًا في member_details بلا نظيرٍ في profiles — الرفع لم يتمّ.', v_orphans;
    END IF;
END;
$$;
