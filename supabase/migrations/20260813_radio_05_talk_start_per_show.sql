-- إذاعة أدِيب: بدايةُ الحديث تنتقل من المحطّة إلى البرنامج
--
-- كان الرقمُ واحدًا للإذاعة كلِّها ترثه الحلقات. وذلك صحيحٌ ما دام البرنامجُ
-- واحدًا، **ويكذب صامتًا عند الثاني**: برنامجٌ مقدّمتُه سبعُ ثوانٍ سيرث عشرًا،
-- فيبدأ مستمعُ النسخة المجرّدة متأخّرًا في منتصف جملة، ولا عطبَ يظهر ولا أحدَ
-- يشتكي. وأخبثُ الخطأ ما لا يصرخ.
--
-- فلكلّ برنامجٍ رقمُه **إلزاميًّا**: من أنشأ برنامجًا يُسأل متى تنتهي مقدّمتُه
-- ولا يرث رقمًا ليس له. وتبقى في الحلقة خانةُ تجاوزٍ اختياريّة لليوم الذي
-- تُقصّ فيه مقدّمةُ حلقةٍ بعينها على غير مقاس برنامجها.
--
-- والقيمةُ القائمة تنتقل إلى البرامج قبل إسقاط عمود المحطّة، فلا يُفقد شيء.
-- ══════════════════════════════════════════════════════════════════════

alter table public.radio_shows
  add column talk_starts_at numeric(6,3) not null default 0;

-- ما كان على جدار المحطّة يُعلَّق على باب كلّ برنامجٍ قائم.
update public.radio_shows s
set talk_starts_at = (select talk_starts_at from public.radio_station where id = 1);

alter table public.radio_shows
  add constraint radio_shows_talk_start_check
    check (talk_starts_at >= 0 and talk_starts_at < 600);

comment on column public.radio_shows.talk_starts_at is
  'ثانيةُ بدء الحديث في هذا البرنامج (طولُ مقدّمته الموسيقيّة). ترثها حلقاتُه ما لم تُصرّح بغيرها.';

alter table public.radio_station drop column talk_starts_at;
