-- ## اللغمُ نفسُه، وقد وقع فينا
-- منح م٠ب البنكَ لـ`authenticated` صراحةً، وظُنّ ذلك كافيًا. وفحصُ الامتيازات بعد
-- التطبيق أظهر أنّ **`anon` يملك على `guess_word_bank`**: `INSERT` و`UPDATE`
-- و`DELETE` و`TRUNCATE`. لم يمنحها أحد — بل هي **الامتيازاتُ الافتراضيّة** التي
-- تُسندها Supabase لكلّ جدولٍ جديدٍ في `public` (`alter default privileges`).
--
-- ولا ضررَ واقعٌ اليوم: RLS مُفعَّلة، وسياستا البنك `to authenticated` وحدها، فنداءُ
-- المجهول يُردّ عند الصفّ. لكنّ هذا **بعينه** ما حذّر منه م٠أ في ثغرته الثالثة:
-- امتيازٌ قائمٌ بلا سياسةٍ تستعمله لغمٌ ينتظر سياسةً تُضاف غدًا لسببٍ وجيه.
--
-- **والدرسُ يُكتب هنا كي لا يتكرّر: `grant … to authenticated` لا ينفي `anon`.**
-- كلُّ جدولٍ جديدٍ في هذا المستودع يُتبَع بنزعٍ صريح، ويُفحَص بعد التطبيق لا قبله.
--
-- و`TRUNCATE` تُنزَع عن `authenticated` أيضًا: الغرفةُ تحذف صفًّا صفًّا بسياستها،
-- ولا حاجةَ لمن يُفرِغ الجدولَ كلَّه بأمرٍ واحدٍ يتخطّى RLS.

revoke all on table public.guess_word_bank from anon;
revoke truncate on table public.guess_word_bank from authenticated;

-- ودالّةُ الختم (trigger) لا تُنادى نداءً مباشرًا أصلًا، ومنحُها بابٌ بلا غرفة.
revoke all on function public.gw_bank_touch() from public, anon, authenticated;
