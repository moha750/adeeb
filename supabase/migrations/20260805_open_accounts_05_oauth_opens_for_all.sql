-- م٣ — بابُ قوقل وأبل يُفتح لغير الأعضاء
--
-- كُتب الخطّافُ يومَ كان الحسابُ لا يُفتح إلّا لعضو، فكان معناه: **امنع الإنشاء**. ومن له
-- حسابٌ قائمٌ لا يبلغه أصلًا (تطابقُ البريد المؤكَّد **يربط** الهويّة بحسابه ولا يُنشئ)، فكان
-- الردُّ يقع على الغرباء وحدهم — وهم يومَها ليسوا من أهل الباب.
--
-- وقد صار الحسابُ للجميع (م١–م٢)، فانقلب المعنى: **الغريبُ ضيفٌ لا دخيل**، ومن دخل بقوقل
-- يُنشأ له صفُّ مصادقةٍ ثمّ يُكمل بياناته في `/me` — بلا تاريخِ انضمام، فحسابٌ لا عضويّة.
--
-- **وبقي منعٌ واحدٌ لا يُرفع**: بريدُ أبل المُخفى (`privaterelay.appleid.com`). وليس تشدّدًا:
-- ذلك عنوانُ تحويلٍ لا يبقى، فحسابٌ عليه حسابٌ لا يُبلَغ صاحبُه — لا شهادةً ولا تذكيرًا
-- بفعاليّةٍ ولا استعادةَ دخول. والردُّ عليه صريحٌ يُترجَم في الشاشة، لا صمتٌ يُحيّره.
--
-- **والاسمُ لم يُغيَّر عمدًا** وإن ضاق بمعناه: اسمُ الدالّة مكتوبٌ في إعداد المصادقة
-- (`hook_before_user_created_uri`)، فإسقاطُها لإعادة تسميتها يترك الإعدادَ يشير إلى عدمٍ —
-- **فينكسر إنشاءُ كلّ مستخدمٍ** حتّى يُعاد ضبطُ الإعداد. اسمٌ ضيّقٌ أهونُ من بابٍ مكسور.
-- ══════════════════════════════════════════════════════════════════════════════

create or replace function public.hook_block_oauth_signup(event jsonb)
returns jsonb
language plpgsql
set search_path to ''
as $function$
declare
  provider text := event -> 'user' -> 'app_metadata' ->> 'provider';
  email    text := lower(coalesce(event -> 'user' ->> 'email', ''));
begin
  -- ما ليس دخولًا اجتماعيًّا يمرّ (بريدٌ برمز · كلمةُ مرورٍ يُنشئها الإداريّ)
  if provider is null or provider not in ('google', 'apple') then
    return '{}'::jsonb;
  end if;

  -- بريدٌ لا يُبلَغ صاحبُه لا يصلح هويّةً في أديب
  if email like '%@privaterelay.appleid.com' then
    return jsonb_build_object(
      'error', jsonb_build_object('http_code', 403, 'message', 'adeeb_oauth_hidden_email')
    );
  end if;

  -- وسِواه يُنشأ: صاحبُ حسابٍ لا عضو — والعضويّةُ تُطلَب وتُنال، لا تُؤخذ ببابِ دخول
  return '{}'::jsonb;
end;
$function$;

comment on function public.hook_block_oauth_signup(jsonb) is
  'خطّافُ ما‑قبل‑الإنشاء: يفتح الدخول الاجتماعيّ لكلّ أحد (حسابًا لا عضويّة)، ويردّ بريدَ أبل المُخفى وحدَه. الاسمُ من عهدٍ كان المنعُ فيه هو الأصل — أُبقي لأنّه مكتوبٌ في إعداد المصادقة.';
