-- مفتاحُ ساعةِ الرسالة — لسقفِ الإنفاق اليوميّ.
--
-- صار سقفُ اليوم (lib/deebo/limits.ts) يُحسب من `deebo_messages` لا من
-- `deebo_conversations` بعد ٢٠٢٦-٠٨-٢١، لعلّتين: ثمنُ الرمز يتبدّل بالساعة عند
-- المزوّد فيلزم أن تُسعَّر كلُّ رسالةٍ بساعتها، ومحادثةٌ بدأت أمسِ واستمرّت
-- اليوم كانت تفلت من السقف كلَّها.
--
-- والجدولُ اليومَ صغير فالمسحُ لا يُحسّ به، لكنّه ينمو برسالةٍ لكلّ سؤال. وهذا
-- المفتاحُ يجعل «رسائلُ اليوم» قراءةَ مدًى لا مسحًا كاملًا، وقيدُ الدور يُبقيه
-- ضيّقًا ويطابق ما يسأل عنه الحارسُ حرفًا: صفوفُ الزائر لا رموزَ لها أصلًا.
create index if not exists deebo_msg_at_idx
  on public.deebo_messages using btree (at desc)
  where role = 'assistant';
