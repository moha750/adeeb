-- شرطٌ يقارن العمودَ بنفسِه فيصدق أبدًا: بابُ الاشتراك في النشرة مقفولٌ بمفتاحٍ مكسور.
--
-- العيبُ كما هو مكتوبٌ في القاعدة اليوم (`pg_policies` على `newsletter_subscribers`، سياسةُ
-- الإدراج `newsletter_subscribers_insert_public`):
--
--   ((NOT (EXISTS ( SELECT 1
--      FROM newsletter_subscribers newsletter_subscribers_1
--     WHERE ((newsletter_subscribers_1.email = newsletter_subscribers_1.email)
--            AND (newsletter_subscribers_1.status = 'active'))))) AND (email IS NOT NULL))
--
-- المقصودُ بيّنٌ من شكله: «امنعْ إن كان في الجدول مشتركٌ **نشطٌ ببريدِ الصفّ الجديد**».
-- والمكتوبُ غيرُه: الاسمُ المستعارُ الداخليّ `newsletter_subscribers_1` ظلَّل الجدولَ
-- الخارجيّ، فصار طرفا المقارنة **عمودًا واحدًا من الصفّ الداخليّ نفسِه**. والارتباطُ
-- بالصفّ الجديد سقط، فبقي `email = email` — وهو صادقٌ عن كلّ صفٍّ بريدُه ليس فارغًا.
-- فالشرطُ لا يسأل عن بريدٍ بعينه، بل يسأل: «أفي الجدول مشتركٌ نشطٌ واحدٌ؟» — فإن كان،
-- مُنع كلُّ اشتراكٍ جديدٍ إلى الأبد.
--
-- **وفي العيب وجهٌ ثانٍ**: سياسةٌ على جدولٍ تستعلم عن **الجدول نفسِه**. فأمّا أن يردّها
-- بوسترغرس بـ«تعاودٌ لا نهائيّ في سياسة العلاقة» (42P17) وأمّا أن يمرّرها فتقرأ بعينِ
-- المُدرِج (وهو زائرٌ لا يرى شيئًا، إذ سياسةُ القراءة هنا للمدير وحده) فتصدق من طريقٍ آخر.
-- وأيًّا كان الوجهان فالشرطُ **لا يفعل ما كُتب لأجله**، وهذا هو الحكم.
--
-- **والعلاجُ جذرٌ لا رقعة**: لا يُعاد كتابةُ الاستعلامِ المرتبط، بل يُحذَف. فمنعُ تكرار
-- البريد ليس شغلَ سياسةٍ أصلًا، **بل شغلُ قيد** — وهو قائمٌ في الجدول منذ نشأته:
--
--   newsletter_subscribers_email_key  UNIQUE (email)
--
-- فالقيدُ يمنع البريدَ المكرَّر مرّةً واحدةً لكلّ طريقٍ يكتب، والسياسةُ تعود إلى شغلها:
-- **مَن يُدرِج**، لا **أصحيحٌ ما يُدرِج**. وهذا هو التوزيعُ الذي في بقيّة القاعدة.
--
-- ما لم يتغيّر: الدورُ (`public`) والأمرُ (INSERT) وكونُها متساهلة (PERMISSIVE)، فبابُ
-- الاشتراك يبقى مفتوحًا للزائر كما أُريد له.
--
-- **سؤالٌ يبقى لك، ولم يُجتهَد فيه هنا**: من اشترك ثمّ ألغى (`status = 'unsubscribed'`)
-- صفُّه باقٍ ببريده، فالقيدُ الفريدُ يردّ إدراجَه ثانيةً — وعودتُه **تحديثٌ** لا إدراج،
-- والتحديثُ في هذا الجدول للمدير وحده. فإمّا أن يُقبل هذا (لا عودةَ ذاتيّة) وإمّا أن
-- يُفتَح لها بابٌ صريح، وذاك قرارٌ لا يُدَسّ في ترحيلِ إصلاح.
--
-- ملحوظة: لا يستهلك V2 هذا الجدولَ اليوم — `grep` على `newsletter` في `v2/apps/web/src`
-- و`v2/packages` صفرُ نتائج. فالإصلاحُ يُصحّح القاعدة قبل أن يُبنى عليها باب.
--
-- الترحيلُ قابلٌ للرجوع: نصُّ السياسة القديمة مكتوبٌ في رأس هذا الملفّ حرفًا بحرف.

drop policy if exists newsletter_subscribers_insert_public on public.newsletter_subscribers;

create policy newsletter_subscribers_insert_public
  on public.newsletter_subscribers
  as permissive
  for insert
  to public
  with check (email is not null);
