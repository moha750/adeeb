-- سدُّ ثغرةِ الأعمدة في `profiles` — **الصفُّ لك، ولا كلُّ ما فيه**
--
-- كانت `profiles_update_own` تقول `USING (id = auth.uid())` ولا تقول أكثر. وRLS
-- يحرس **الصفوف** لا الأعمدة، فمن ملك صفَّه ملك كلَّ ما فيه: يقلب `account_status`
-- من `suspended` إلى `active` فيفكّ إيقافَ نفسه، ويزوّر `joined_date` فيتقدّم في
-- الأقدميّة، ويكتب `termination_reason`.
--
-- والعلاجُ ليس سياسةً أخرى — RLS لا يبلغ الأعمدة أصلًا. العلاجُ هو الآلةُ المصنوعةُ
-- لهذا: **صلاحيّاتُ الأعمدة**. ولمّا كانت كلُّ كتابةٍ في `profiles` في V2 تمرّ بمفتاح
-- الخدمة (فحصتُ المواضع الستّة: `/complete` والملفّ الشخصيّ وبيانات الاعتماد
-- و`memberData` ومقعدُ المعاينة) فالمتصفّحُ لا يحتاج إذنَ كتابةٍ هنا اليوم.
--
-- والسياستان تبقيان: هما تقولان **أيَّ صفٍّ** يمسّ، والصلاحيّةُ تقول **أيَّ عمود** —
-- طبقتان لسؤالين، ويومَ يحتاج المتصفّح عمودًا يُمنحه وحدَه.
-- ══════════════════════════════════════════════════════════════════════════════

-- ١) لا كتابةَ من المتصفّح في `profiles`
revoke update on public.profiles from anon, authenticated;

-- ٢) و`anon` لا شأن له بهذا الجدول أصلًا بعد أن قُصرت القراءةُ على المصادَقين
revoke insert, update, delete on public.profiles from anon;

comment on policy profiles_update_own on public.profiles is
  'أيُّ صفٍّ يمسّ (صفُّه). وأيُّ عمودٍ يكتب تقوله صلاحيّاتُ الأعمدة — ولا عمودَ ممنوحٌ اليوم.';
comment on policy profiles_update_admin on public.profiles is
  'أيُّ صفٍّ يمسّ (من في سلطته). والكتابةُ الإداريّة تجري بمفتاح الخدمة من اللوحة.';
