-- المسحاتُ تبقى: لا تنظيفَ بعد سنة (م١١)
--
-- ## العلّة، بكلمة المالك
-- «لا تنظّف بل تبقى موجودة» (٢٠٢٦-٠٩-٠٦). التنظيفُ الشهريّ وُضع في التحصين (م١) سقفًا
-- لنموّ الجدول، والمالكُ يريد التفصيلَ محفوظًا: الملصقُ يعيش سنوات، وسؤالُ «كيف كانت
-- حركتُه في موسم القبول قبل عامين؟» سؤالٌ يُسأل.
--
-- ## وما يترتّب عليه
-- · **المهمّةُ تُنزَع ولا تُبطَأ**: مهمّةٌ مجدولةٌ لا تعمل خيرٌ منها موجودةً تنتظر خطأً.
-- · **والدالّةُ تبقى** (`qr_purge_scans`) بلا جدول: إن نما الجدولُ يومًا نُوديت بيدٍ عارفة،
--   ولا تُنفَّذ من تلقائها. وهي محجوبةٌ عن `authenticated` أصلًا.
-- · **وسقفُ القراءة باقٍ في التطبيق** (‏٢٠ ألف صفٍّ لكلّ عرض): حفظُ الصفوف شيءٌ، وجلبُها
--   كلَّها إلى المتصفّح شيءٌ آخر. والشاشةُ تقول حين تبلغ سقفَها إنّ المعروض أحدثُ ما فيه.

begin;

select cron.unschedule('qr-scans-purge')
where exists (select 1 from cron.job where jobname = 'qr-scans-purge');

comment on function public.qr_purge_scans(integer) is
  'حذفُ صفوف المسح الأقدم من المدّة. **غيرُ مجدولة منذ ٢٠٢٦-٠٩-٠٦ بأمر المالك**: المسحات تُحفظ ولا تُنظَّف، وتبقى الدالّةُ لنداءٍ يدويٍّ عند الحاجة.';

commit;
