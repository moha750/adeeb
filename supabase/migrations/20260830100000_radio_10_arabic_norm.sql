-- ══════════════════════════════════════════════════════════════════════════════
-- إذاعة أدِيب م١٠: تطبيعُ العربيّة في القاعدة
--
-- ⚠️ مكتوبٌ ينتظر إذنَ المالك. لا يُنفَّذ إلّا بكلمته.
--
-- ## لماذا
-- بحثٌ عربيٌّ بلا تطبيعٍ **معطوبٌ لا ناقص**: من كتب «المنعطف» لا يجد «منعطف»،
-- ومن كتب «اسطورة» لا يجد «أسطورة»، ومن كتب «حياه» لا يجد «حياة». وهو ينصرف
-- ولا يعود، ولا يبلّغ عن عطل.
--
-- ## ولماذا هذا الملفُّ وحدَه بلا أعمدةٍ ولا فهارس
-- إنشاءُ الدالّة **مجّانيٌّ**: لا يمسّ صفًّا ولا يقفل جدولًا. أمّا الأعمدةُ
-- المولَّدةُ المخزَّنة فتعيد كتابةَ الجدول تحت `ACCESS EXCLUSIVE`، وذلك عملٌ
-- يُجدوَل. ففُصلا ملفَّين كي يُطبَّق الأوّلُ اليومَ ويُختار وقتُ الثاني.
--
-- ## ومطبٌّ أوقع فاحصَين
-- صنفُ التشكيل في جافاسكربت مكتوبٌ بحروفٍ عربيّةٍ حرفيّة، **ويُقرأ معكوسًا في
-- المحرّر**. فمن أعاد كتابتَه بيده خرج بمدًى آخرَ (‏`064B-0670` بدل
-- `064B-065F`) يبتلع `٪` و`٫` و`٬`، فظنّ التوأمين مفترقين وهما متطابقان.
-- **لا يُعاد التعبيرُ العربيُّ كتابةً؛ يُقرأ بالمهارب.** وقِيس المدى في الملفّ
-- فعلًا: `[U+064B-U+065F][U+0670][U+0640]` — وهو مدى SQL أدناه حرفًا بحرف.
--
-- ## والتوأمُ في جافاسكربت
-- `v2/apps/web/src/lib/radio/arabicSearch.ts` يفعل هذا بعينه في المتصفّح.
-- والخطرُ الحقيقيُّ ليس افتراقًا قائمًا — قِيسا معًا على اثنتي عشرةَ حالةً
-- فتطابقتا — بل **افتراقٌ يقع يومًا** حين يُعدَّل أحدُهما وحدَه. فيربطهما جدولُ
-- `TWINS` في `v2/apps/web/src/lib/radio/__tests__/arabicSearch.test.ts`:
-- توقُّعاتٌ **حرفيّة** لا مقارنةُ طرفين ببعضهما (تلك تنجح ولو تبدّل التطبيعُ
-- كلُّه). والحالاتُ نفسُها في تعليق الدالّة أدناه، فمن غيّر أحدَهما سقط عنده
-- الاختبارُ أو خالف الجدولَ المكتوب.
-- ══════════════════════════════════════════════════════════════════════════════

begin;

/* ══ ١) التطبيع ═══════════════════════════════════════════════════════════════
   خطواتُه بالترتيب، وترتيبُها مقصود:
     ١. الأرقامُ العربيّةُ والفارسيّةُ إلى اللاتينيّة (توأمُ `toLatinDigits`).
        **قبل** نزع التشكيل، لأنّ مدى `\0660-\0669` يقع داخل جوار التشكيل،
        فلو نُزع أوّلًا لضاعت الأرقامُ نفسُها.
     ٢. نزعُ التشكيل والتطويل: `\0640` تطويلٌ، و`\064B-\065F` حركات، و`\0670`
        ألفٌ خنجريّة. ولا يُنزَع `\066A` (‏٪) ولا `\066B` ولا `\066C`.
     ٣. توحيدُ الهمزات والتاء المربوطة والألف المقصورة.
     ٤. اللاتينيُّ إلى الصغير.
     ٥. المسافاتُ تُجمَع وتُقصّ. والصنفُ صنفُ `\s` في جافاسكربت حرفًا بحرف،
        وفيه المسافةُ غيرُ الفاصلة والعلامةُ الصفريّة — وهما ما يأتي به النسخُ
        من وورد، ولو بقيا لالتصقت الكلمةُ بجارتها في الفهرس.

   و`immutable` صادقةٌ حقًّا: لا تقرأ جدولًا ولا وقتًا ولا إعدادًا، وكلُّ ما
   تناديه ثابتٌ بذاته. وهذا شرطُ العمود المولَّد. */
create or replace function public.arabic_norm(p_text text)
returns text
language sql
immutable
parallel safe
set search_path = pg_catalog, public
as $$
  select btrim(
    regexp_replace(
      lower(
        translate(
          regexp_replace(
            translate(coalesce(p_text, ''),
              U&'\0660\0661\0662\0663\0664\0665\0666\0667\0668\0669'
                '\06F0\06F1\06F2\06F3\06F4\06F5\06F6\06F7\06F8\06F9',
              '01234567890123456789'),
            U&'[\0640\064B-\065F\0670]', '', 'g'),
          U&'\0623\0625\0622\0671\0629\0649\0624\0626',
          U&'\0627\0627\0627\0627\0647\064A\0648\064A')),
      U&'[\0009-\000D\0020\00A0\1680\2000-\200A\2028\2029\202F\205F\3000\FEFF]+',
      ' ', 'g'),
    ' ')
$$;

comment on function public.arabic_norm(text) is
  'تطبيعُ نصٍّ عربيٍّ للبحث: توأمُ normalizeArabic في v2/apps/web/src/lib/radio/arabicSearch.ts. يُفهرَس به ويُستعلَم به معًا، فلو استُعمل في أحدهما دون الآخر لم يجد أحدٌ شيئًا وبدا البحثُ سليمًا.';

/* ══ ٢) «ال» التعريف عند المطابقة وحدَها ══════════════════════════════════════
   لا تُنزَع في التطبيع نفسِه: لو نُزعت لصار «العلم» و«علم» شيئًا واحدًا في
   التخزين، وهما كلمتان. وإنّما تُتجاوَز حين تُقارَن كلمةُ بحثٍ بنصّ. */
create or replace function public.arabic_strip_al(p_word text)
returns text
language sql
immutable
parallel safe
set search_path = pg_catalog, public
as $$
  select case
    when length(coalesce(p_word, '')) > 3 and p_word like U&'\0627\0644%'
      then substring(p_word from 3)
    else coalesce(p_word, '')
  end
$$;

comment on function public.arabic_strip_al(text) is
  'تُسقط «ال» التعريف من طرف كلمةٍ عند المطابقة لا عند التخزين. توأمُ stripAl في arabicSearch.ts.';

/* ══ ٣) تهريبُ محارف LIKE ═════════════════════════════════════════════════════
   من كتب `%` أو `_` في مربّع البحث كتب حرفًا لا نمطًا. وبلا تهريبٍ يصير
   استعلامُ `%` مسحًا كاملًا للجدول يفتحه أيُّ مجهول، وهو بابُ إنهاكٍ لا خطأُ
   نتائج. والشرطةُ المائلةُ هي حرفُ التهريب، فتُهرَّب أوّلًا وإلّا هرّبت نفسَها. */
create or replace function public.like_escape(p_text text)
returns text
language sql
immutable
parallel safe
set search_path = pg_catalog, public
as $$
  select replace(replace(replace(coalesce(p_text, ''), '\', '\\'), '%', '\%'), '_', '\_')
$$;

comment on function public.like_escape(text) is
  'يهرّب \ و% و_ قبل بناء نمط LIKE من مُدخَل مستخدِم: بدونه يصير «%» مسحًا كاملًا يفتحه أيُّ مجهول.';

/* ══ ٤) جدولُ الحالات الذي يربط التوأمين ══════════════════════════════════════
   تعليقٌ لا جدولٌ حقيقيّ: هذه الحالاتُ نفسُها مكتوبةٌ في اختبار جافاسكربت،
   فمن عدّل أحدَ التوأمين ولم يعدّل الآخر سقط عنده الاختبار. وقد قِيست الأزواجُ
   الآتيةُ في الاثنين معًا (٢٠٢٦-٠٨-٣٠) فتطابقت. */
comment on function public.arabic_norm(text) is
  'تطبيعُ نصٍّ عربيٍّ للبحث: توأمُ normalizeArabic في v2/apps/web/src/lib/radio/arabicSearch.ts. '
  'جدولُ التوأمين (TWINS في arabicSearch.test.ts)، قِيس في الاثنين فتطابق: '
  '۹۹٪←99٪ · ٩٩٪←99٪ · المنعطف←المنعطف · أسطورة←اسطوره · حياة←حياه · مُنعَطَف←منعطف · '
  '50%←50% · على←علي · ســلام←سلام · ١٬٢٠٠←1٬200 · ٣٫٥←3٫5 · إذاعة←اذاعه.';

commit;
