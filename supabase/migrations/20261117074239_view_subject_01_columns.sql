-- **موضوعُ الزيارة: الصفحةُ تقول ما تعرضه، ولا يُخمَّن من رابطها** (٢٠٢٦-١١-١٧).
--
-- **العلّة التي فتحت الباب:** خبرُ «للقهوة أصول وللأجيال حكاية» عرض صفرَ مشاهدات وقد فتحه ٤٣ إنسانًا.
-- كان العدّادُ (`news_views_from_pageview`) يستنتج الخبرَ من شكل الرابط: يبحث عن ستّة أحرفٍ سداسيّةٍ
-- تسبقها شَرطةٌ في ذيل المسمّى. ومسمّى هذا الخبر وُلِّد تلقائيًّا (`news-<المعرّف بلا شَرطات>`) فلا شَرطةَ
-- قبل ذيله، فرُصدت كلُّ فتحةٍ وضاعت. وتحت العلّة علّتان أخريان كُشفتا بالقياس:
--   · دالّةُ الحافّة تقصّ المسارَ عند ٥٠٠ حرف، والمسمّى العربيُّ الطويل يُرمَّز فوقها، فالمسارُ المحفوظ
--     لا يدلّ على خبرٍ بالمطابقة التامّة (٣٦ زيارةً مقصوصة).
--   · الكتبُ والاستبيانات تُعدّ بآلتين أخريين لا تعرفان الروبوتَ ولا التطوير: نداءٌ من المتصفّح
--     (`library_increment_views`، مفتوحٌ لـ anon بلا حدّ) وعدٌّ في تصيير الخادم (`increment_survey_views`،
--     تعدّه معاينةُ واتساب وكلُّ تحديث).
--
-- **والعلاجُ الجذريّ:** الصفحةُ التي صيّرت الخبرَ أو الكتابَ أو الاستبيان هي وحدها التي تعرف ما صيّرته،
-- فهي تُعلنه (`<ViewSubject>`)، والمتتبّعُ يحمله مع الزيارة، والقاعدةُ تعدّه بمُشغِّلٍ واحد. فلا رابطَ
-- يُحلَّل، ولا مسمّى يُطابَق، ولا آلةَ عدٍّ ثانية: إن صُيِّر الموضوعُ عُدّ، وإن لم يُصيَّر لم يُعدّ.
--
-- هذا الملفُّ أوّلُ ثلاثة، ويُطبَّق **قبل** نشر دالّة الحافّة الجديدة (التي تكتب في هذين العمودين):
--   ٠١ الأعمدة ← نشرُ الدالّة ← ٠٢ العدّادُ الواحد وتصحيحُ ما مضى ← رفعُ الموقع ← ٠٣ هدمُ الآلتين القديمتين.
-- وكلُّ خطوةٍ منها لا تكسر ما قبلها: العميلُ القديم يعمل في كلّ مرحلة.

alter table public.site_pageviews
  add column if not exists subject_kind text,
  add column if not exists subject_id   text;

comment on column public.site_pageviews.subject_kind is
  'ما عرضته الصفحةُ في هذه الزيارة، بإعلانها هي لا باستنتاجٍ من رابطها: news | book | survey. فارغٌ لصفحةٍ بلا موضوع.';
comment on column public.site_pageviews.subject_id is
  'معرّفُ الموضوع: uuid للخبر والكتاب، ورقمُ الاستبيان. يُكتب مرّةً ولا يتبدّل.';

-- الشكلُ يُفرض هنا لا في الدالّة وحدها: النوعُ من قائمةٍ مغلقة، والمعرّفُ بشكل نوعه، والاثنان معًا أو لا شيء.
-- (فالمُشغِّلُ في ٠٢ يحوّل المعرّفَ إلى نوعه بلا خوفٍ من نصٍّ فاسد.)
alter table public.site_pageviews drop constraint if exists site_pageviews_subject_shape;
alter table public.site_pageviews add constraint site_pageviews_subject_shape check (
  (subject_kind is null and subject_id is null)
  or (subject_kind in ('news', 'book')
      and subject_id ~ '^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$')
  or (subject_kind = 'survey' and subject_id ~ '^[0-9]{1,9}$')
);

-- لإحصاءات الموضوع الواحد (أكثرُ الأخبار قراءةً، زوّارُ كتابٍ بعينه) بلا مسحٍ للجدول كلّه.
create index if not exists site_pageviews_subject_idx
  on public.site_pageviews (subject_kind, subject_id)
  where subject_kind is not null;
