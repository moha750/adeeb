--
-- صفٌّ يحمل دورًا له إدارةٌ أمّ (`roles.home_committee_id`) على لجنةٍ غيرها: شكلٌ صار
-- محرَّمًا في `assign_position` — فلا يجوز أن يبقى منه أثرٌ في الجدول ولو ميّتًا.
--
-- ولا يُفقد به شيء: الحيّ منه صار انتماءً وإشرافًا (الملفّ 03)، والميّت منه إشرافٌ منتهٍ
-- لا منصبٌ مضى. وبقاؤه يكذب في موضعين: «مسيرتي» تعرضه محطّةً في تاريخ المناصب، وأيّ
-- قارئٍ للتاريخ يظنّ العضو كان **في** تلك اللجنة. تاريخ الإشراف موضعُه جدول الإشراف.
--
-- حذفٌ صلبٌ آمن: لا مفتاح أجنبيّ يشير إلى `user_roles`، وتريغر سحب الترشّح على UPDATE لا DELETE.

delete from user_roles ur
using roles r
where r.id = ur.role_id
  and r.home_committee_id is not null
  and ur.committee_id is distinct from r.home_committee_id;
