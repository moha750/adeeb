-- رمزٌ يُختار لا يُقرَع: `‎/q/majles` بدل `‎/q/f9e6efk` (م٣)
--
-- ## العلّة
-- الرمزُ يُطبَع على ملصقٍ ويُملى بالصوت أحيانًا («افتح أديب سلاش كيو سلاش…»). والعشوائيُّ
-- يُقرأ حرفًا حرفًا ولا يُحفظ، والمختارُ يُقال كلمةً واحدة.
--
-- ## وحدُّه
-- · **حروفٌ لاتينيّةٌ صغيرةٌ وأرقامٌ وشرطة**، من ٣ إلى ٣٢: ما يُكتب في شريط العنوان بلا لبس.
-- · **ولا يُبدَّل بعد الإنشاء**: امتيازُ التحديث لا يشمل عمودَ `code` (ترحيل م١)، فالمختارُ
--   يُقال مرّةً واحدةً يومَ يُولَد. وتغييرُه بعد الطباعة يقتل ملصقًا في الشارع.
-- · **والمولَّدُ يبقى على أبجديّته**: سبعةُ محارفَ بلا ملتبِس (لا 0/o ولا 1/l) — القيدُ
--   يتّسع للمختار ولا يُرخي المولِّد.
-- · **والمحجوزُ محجوز**: `unavailable` صفحةٌ قائمةٌ تحت `‎/q`، فلو اتُّخذ رمزًا حجب صفحةَ
--   «غير متاح» عن كلّ باركودٍ موقوف.

begin;

alter table public.qr_links drop constraint if exists qr_links_code_check;

alter table public.qr_links add constraint qr_links_code_check
  check (
    code ~ '^[a-z0-9]([a-z0-9-]{1,30})[a-z0-9]$'
    and code not in ('unavailable', 'new', 'admin', 'api', 'q')
  );

comment on column public.qr_links.code is
  'رمزُ الرابط ‎/q/<code>. المولَّدُ سبعةُ محارفَ من أبجديّةٍ بلا ملتبِس، والمختارُ حروفٌ صغيرةٌ وأرقامٌ وشرطةٌ من ٣ إلى ٣٢. ولا يُبدَّل بعد الإنشاء: امتيازُ التحديث لا يشمله.';

commit;
