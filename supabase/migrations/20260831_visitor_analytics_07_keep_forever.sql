-- إحصائيّاتُ الزوّار: الحفظُ للأبد
--
-- قرارُ المالك 2026-08-31. كانت مهمّةٌ شهريّة (`site-visits-monthly-cleanup`، أوّلَ كلّ شهرٍ
-- الساعةَ ٤ صباحًا UTC) تحذف من `site_pageviews` كلَّ صفٍّ تجاوز ١٨٠ يومًا، فتبقى الخلاصةُ
-- اليوميّة ويضيع التفصيل. وشاشةُ الإحصائيّات تقرأ الخامَ وحدَه (`get_visitor_analytics`)،
-- فمعنى المسح أن تختفي من اللوحة كلُّ فترةٍ أقدمَ من ستّة أشهر.
--
-- عُرِضت عليه ثلاثةُ خيارات (إبقاء الحدّ · نزعُ الهويّة بعد سنةٍ مع الحفظ الأبديّ · الحفظُ
-- الكامل) فاختار الثالث: يبقى كلُّ شيءٍ بتفصيله وربطِه بالحساب. والحجمُ ليس مانعًا: ٤٧٧٧ صفًّا
-- في أربعة أشهرٍ = ٣.٦ ميغابايت، أي نحو ١١ ميغابايت في السنة.
--
-- لا يُحذف هنا صفٌّ ولا عمود: يُنزع الجدولُ الزمنيّ وحده. والدالّةُ `cleanup_pageviews_older_than`
-- تبقى قائمةً (ممنوعةً على العموم) كي يُستدعى الحذفُ يدويًّا إن عاد الرأي يومًا.
-- والتجميعُ اليوميّ (`site-visits-daily-aggregate`) يبقى كما هو.

do $$
begin
    perform cron.unschedule('site-visits-monthly-cleanup');
exception when others then null;
end $$;

comment on function public.cleanup_pageviews_older_than(integer) is
    'حذفُ الزيارات الأقدم من p_days. غيرُ مجدولةٍ منذ 2026-08-31 بقرار الحفظ للأبد: تُستدعى يدويًّا فقط.';
