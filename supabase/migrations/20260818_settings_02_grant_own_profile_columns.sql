-- **عمودان يملكهما صاحبُهما** — نبذتُه العلنيّة وقبولُه رسائلَ النادي.
--
-- **الحال قبل هذا الملفّ**: سياسةُ `profiles_update_own` (‏`id = auth.uid()`) قائمةٌ منذ
-- زمن، لكنّ دورَ `authenticated` **لا يملك `UPDATE` على `profiles` أصلًا** — فالسياسةُ
-- لا تُبلَغ، ويردّ الخادمُ `permission denied for table profiles` قبل أن يُنظَر فيها.
-- ولذلك يكتب «الملفّ الشخصيّ» بمفتاح الخدمة، وتبعه تبويبُ الإعدادات مضطرًّا.
--
-- **وهذا جذرُه**: إذنٌ **بالعمود لا بالجدول**. فيصير الحدّان كلاهما في القاعدة — أيَّ صفٍّ
-- (سياسةُ RLS) وأيَّ عمودٍ (هذا المنح) — ولا يبقى للتطبيق إلّا أن ينادي بجلسة صاحبه.
--
-- ولمَ هذان دون غيرهما؟ لأنّهما وحدهما مِلكُ العضو في `profiles`: الاسمُ والحالةُ والبريدُ
-- والسبيكةُ والانضمامُ تملكها الإدارةُ أو تُشتقّ بمُطلِقات، ومنحُ الجدول كلِّه كان يفتحها
-- كلَّها لأنّ السياسةَ بلا `with check` تُجيز كلَّ عمودٍ في الصفّ.
--
-- **وبعد تطبيقه**: يعود كاتبا `updateMyBio` و`setMyMarketing` في
-- `app/dashboard/settings/actions.ts` إلى عميل الجلسة، ويسقط `service()` منه.
grant update (bio, accepts_marketing) on public.profiles to authenticated;

comment on column public.profiles.bio is
  'نبذةٌ علنيّةٌ يكتبها صاحبُها من تبويب الإعدادات، وتُقرأ في /m/<slug> وفي وصف مشاركتها. ممنوحةٌ لـauthenticated بالعمود، ومحصورةٌ بصفّها بسياسة profiles_update_own.';
comment on column public.profiles.accepts_marketing is
  'قبولُ رسائل النادي (لا رسائل الحساب). يضبطه صاحبُه من تبويب الإعدادات. ممنوحةٌ لـauthenticated بالعمود، ومحصورةٌ بصفّها بسياسة profiles_update_own.';
