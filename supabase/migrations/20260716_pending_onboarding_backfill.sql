-- ════════════════════════════════════════════════════════════════════
-- «قيد الإكمال»: إسكان العشرين حالتَهم — الحالة موجودة والتبويب مبنيّ، والسكّان تائهون
-- ════════════════════════════════════════════════════════════════════
-- المشكلة: عشرون عضوًا account_status='active' ولا سجلّ member_details لهم — أي
--          «نشط» لم يسجّل قطّ. والحالة المصنوعة لهم (pending_onboarding) عدد سكّانها صفر،
--          والتبويب «قيد الإكمال» مبنيٌّ في اللوحة (MembersView.tsx) ينتظر فارغًا.
--
-- الجذر: بابا القبول اختلف حكمهما — create-member-directly يكتب 'pending_onboarding'،
--        و migrate-accepted-member كان يكتب 'active' فيقفز بالعضو من الطلب إلى النشاط
--        رأسًا. أُصلح البابُ في الدالّة، وهذا الترحيل يلمّ من مرّ منه قبل الإصلاح.
--
-- من يُنقل: كلّ نشطٍ بلا سجلّ member_details. وهم صنفان يجمعهما أنّهما لم يسجّلا:
--        أربعةٌ وصلهم رابطٌ فانتهت صلاحيته (تهاني · محمد · آيات · بيان)،
--        وستّة عشر من استيراد يناير/أبريل لم يصلهم رابطٌ قطّ — سبقوا نظام التوكن نفسه.
--        وحكم المالك أنّهما سواء: من لم يسجّل فهو قيد الإكمال، عمل أم لم يعمل.
--
-- من لا يُنقل: الموقوفون الثمانية بلا بيانات — عضويّتهم منتهية لا معلّقة، ولا رابط يُرسل
--        لمن انتهت عضويّته. (والحارس guard_terminated_membership_profile يمنعهم أصلًا.)
--
-- الأثر المعلوم — يُقال ولا يُكتَم: خمس دوالّ تشترط account_status='active':
--        survey_is_active_member · assign_activity_coordinator · search_members_for_coordinator
--        · get_board_members · (و find_pending_member_duplicates تقرؤه ولا تحرس به).
--        فالعشرون يخرجون من الاستبانات ومن ترشيح منسّقي الأنشطة. وواحدةٌ تخرج من قائمة
--        المجلس: آيات مصطفى ال سنان (qa_admin_member · مستوى ٧ · تسع لجان) — قُبلت ولم
--        تسجّل، فخروجها من القائمة وصفٌ صادق لحالها لا حرمانٌ لها.
--        ولا سياسة RLS تحرس account_status، ولا تسجيل الدخول — فلا أحد يُقفل عليه بابه.
--
-- المقاعد لا تُمسّ: user_roles تبقى كما هي (is_active على حالها). النقل يصف موقع العضو
--        في دورة حياته، ولا يعزله عن لجنته — والهيكل يُقرأ من user_roles لا من الحالة.
--
-- ملاحظة: idempotent — الشرط نفسه لا يطابق أحدًا بعد النقل.

-- ─────────────────────────────────────────────
-- 1) النقل
-- ─────────────────────────────────────────────
UPDATE public.profiles p
SET account_status = 'pending_onboarding'
WHERE p.account_status = 'active'
  AND NOT EXISTS (
      SELECT 1 FROM public.member_details md WHERE md.user_id = p.id
  );

-- ─────────────────────────────────────────────
-- 2) حارس الترحيل — لا يمرّ صامتًا إن بقي «نشطٌ لم يسجّل»
-- ─────────────────────────────────────────────
DO $$
DECLARE
    v_left INTEGER;
BEGIN
    SELECT count(*) INTO v_left
    FROM public.profiles p
    WHERE p.account_status = 'active'
      AND NOT EXISTS (SELECT 1 FROM public.member_details md WHERE md.user_id = p.id);

    IF v_left > 0 THEN
        RAISE EXCEPTION 'بقي % عضوًا نشطًا بلا سجلّ تسجيل — النقل لم يتمّ.', v_left;
    END IF;
END;
$$;
