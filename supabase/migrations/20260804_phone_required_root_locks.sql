-- الجوّال إجباريّ — القفل في القاعدة لا في التطبيق (قرار المالك ٢٠٢٦-٠٨-٠٤).
--
-- كان الرقم يُلزَم على بابَي الالتحاق (`/join` و`/onboarding`) ثمّ يُفرَّغ بعدهما: تعديلُ
-- الإدارة كان يقبل الفارغ، و«الملف الشخصي» الجديد كان سيقبله. أُلزم في طبقة التطبيق كلّها
-- (`lib/memberData` مَعبرُ كلّ تحرير)، وهذا الترحيل يُنزل الحكمَ إلى القاعدة نفسها — فلا
-- يلتفّ عليه سكربتٌ ولا دالّةُ حافةٍ جديدة ولا تحريرٌ يدويّ في لوحة Supabase.
--
-- ولا استثناء في القيد: الصفّ الوحيد الذي كان بلا رقم ليس عضوًا بل **دُمية المعاينة**
-- (`preview@adeeb.local`) — مُنحت رقمًا محجوزًا موثَّقًا (`0500000000`) ومُنشِئُها في V2
-- (`lib/preview-seat.ts` — الثابت `PREVIEW_PHONE`) يكتبه، فبقي القيدُ صُلبًا بلا بندٍ يقول
-- «إلّا الخاملين» (وذاك بابٌ يفتحه من يضبط الحالة).
--
-- وأثرٌ ثالث مقصود خارج هذا الملفّ: دالّة الحافة `create-member-directly` كانت تُدرج ملفًّا
-- بلا جوّال، فأُوقفت بشاهد قبرٍ يردّ 410 (بقاياها من V1، وV2 لا يناديها).

-- ١) الملفّ — الصيغة كانت محروسة بـ`profiles_phone_check`، وبقي الوجود
alter table public.profiles alter column phone set not null;

-- ٢) طلب العضويّة — منه يُنسَخ الرقم عند ترحيل المقبول (`migrate-accepted-member`)،
--    فكان طلبٌ بلا رقمٍ يُنتج عضوًا بلا رقم.
--
--    ولهذا القفل أثرٌ ثانٍ مقصود: تريغر `auto_normalize_phone` يمرّر المُدخَل على
--    `normalize_phone`، وهي **تردّ NULL لما تعجز عن تطبيعه**. فكان الرقم المعطوب يُخزَّن
--    عدمًا **صامتًا**؛ وصار الآن يُردّ صراحةً عند الكتابة.
alter table public.membership_applications alter column phone set not null;

-- والصيغة تُحرَس كما تُحرَس في `profiles` — نظيرُ `profiles_phone_check` حرفًا بحرف،
-- فلا يفترق الجدولان إن سقط التريغر يومًا.
alter table public.membership_applications
  add constraint membership_applications_phone_check check (phone ~ '^05[0-9]{8}$');
