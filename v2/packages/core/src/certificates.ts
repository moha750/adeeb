// شهادةُ الخبرة: ما يعرفه الطرفان — **مصدرٌ واحدٌ للويب والجوّال**.
//
// الورقةُ نفسُها تُرسَم على قماش المتصفّح ولا تعبر إلى الأصيل، فما يعبر هو **عنوانُها**:
// صفحةُ تحقّقٍ علنيّةٌ برقمٍ لا يُخمَّن بالعدّ، يفتحها صاحبُ الشهادة ومن بيده الورقة سواء.

export const VERIFY_HOST = "adeeb.club";

/**
 * ما يحمله الباركود، وما يفتحه زرُّ «تحقَّق» في التطبيق: عنوانٌ يفتح صفحة التحقّق
 * **بالرقم مملوءًا** — فمن مسحه أو ضغطه رأى الجواب بلا كتابة.
 */
export const verifyUrl = (serial: string): string =>
  `https://${VERIFY_HOST}/verify?code=${encodeURIComponent(serial)}`;

/** سطرُ الوثيقة الصغير: رقمُها المرجعيّ وحده — يُقرأ بالعين ويُكتب باليد إن تعذّر المسح. */
export const verifyLine = (serial: string): string => `الرقم المرجعيّ ${serial}`;
