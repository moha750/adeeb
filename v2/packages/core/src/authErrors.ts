/**
 * رسائلُ الدخول الاجتماعيّ — **مشتركةٌ بين الويب والجوّال**.
 *
 * رموزُها ترفعها دالّةُ القاعدة `hook_block_oauth_signup` (خطّافُ before-user-created)،
 * فهي لغةُ القاعدة لا لغةُ منصّة. والويبُ والتطبيقُ يمرّان بالخطّاف نفسِه، فجملةٌ تُصلَح
 * في أحدهما دون الآخر تجعل الشخصَ يقرأ جوابين لمنعٍ واحد.
 */

/**
 * **وأبل لا تعيد السؤال:** تحفظ اختيار «إخفاء بريدي» للتطبيق مرّةً واحدة ثمّ تُكمل به
 * أبدًا، ولا معاملَ يُجبرها على إعادة عرضه. فمن أخفى بريده مرّةً حُبس خارج الباب برسالةٍ
 * تقول له «أعِد المحاولة واختر المشاركة» وهو خيارٌ لن يُعرَض عليه — فيُدَلّ على مكان
 * النقض لا غير.
 */
export const OAUTH_HIDDEN_EMAIL =
  'أخفيتَ بريدك فتعذّر أن نعرف حسابك، وأبل لا تعيد سؤالك. أزِل «نادي أديب» من «تسجيل الدخول باستخدام Apple» في appleid.apple.com ثمّ أعِد المحاولة، أو ادخل بكلمة المرور.';

/**
 * رمزُ «لا حساب لك» **مات ولم يُحذف**: فُتح البابُ لكلّ أحد (٢٠٢٦-٠٨-٠٥) فلم تعد
 * الدالّةُ تردّه. ويبقى نصُّه لأنّ حذفَه لا يربح شيئًا، ولو عاد المنعُ يومًا وجد لسانَه.
 */
export const OAUTH_NO_ACCOUNT =
  'لا يوجد حساب عضوية في نظام أديب بهذا البريد، راجع البريد الذي استخدمته أو تواصل معنا.';

export const OAUTH_FAILED = 'تعذّر إتمام الدخول عبر المزوّد. أعِد المحاولة أو ادخل بكلمة المرور.';

/** يترجم خطأَ دخولٍ اجتماعيًّا، ويردّ `null` لما ليس منه. */
export function socialAuthError(raw: string | null | undefined): string | null {
  const m = (raw ?? '').toLowerCase();
  if (m.includes('adeeb_oauth_hidden_email')) return OAUTH_HIDDEN_EMAIL;
  if (m.includes('adeeb_oauth_no_account')) return OAUTH_NO_ACCOUNT;
  if (m.includes('oauth_failed') || m.includes('unsupported provider')) return OAUTH_FAILED;
  return null;
}
