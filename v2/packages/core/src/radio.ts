/**
 * **مراتبُ الموسيقى الثلاث** — أقرّها المالك ٢٠٢٦-٠٨-١٨ بديلًا عن المِزلاق.
 *
 * كانت الأداةُ مِزلاقًا متّصلًا (‏٠ إلى ١) وبجواره مبدّلٌ يفعل ما تفعله أطرافُه،
 * فبابان لفعلٍ واحد. وسقطت جولةُ تسميةٍ كاملة لأنّ العلّة لم تكن في الاسم:
 * المِزلاقُ **يُخفي مداه بطبيعته**، ولا سابقةَ لهذه الميزة في أيّ مشغّلٍ فيستند
 * إليها المستمع، فيُقرأ مِزلاقًا عامًّا («صوتٌ مرّةً أخرى») ويُتجاوَز.
 *
 * والمراتبُ تعرض المدى كلَّه دفعةً وكلُّ موضعٍ يحمل اسمَه، فلا يُخمَّن الحال.
 * وهي **أداةٌ واحدةٌ** تُغني عن المبدّل، فماتت ازدواجيّةُ البابين في أصلها.
 *
 * **والثمنُ المقبول:** يسقط الضبطُ الدقيق. وقد قِيس السلوكُ الحقيقيّ قبل القرار
 * فكان ثنائيًّا (‏٢ من ١٦ استماعةً اختارت المجرّدة، ولا شيء بينهما)، وزيادةُ
 * مرتبةٍ رابعةٍ يومًا سطرٌ واحدٌ ههنا بخلاف الرجوع من مِزلاقٍ إلى مراتب.
 *
 * و«خافتة» ‏٠٫٣٥ لا ٠٫٥: السريرُ الموسيقيُّ عند النصف ما زال ينازع الكلام،
 * وعند الثلث يصير خلفيّةً تُحَسّ ولا تُنصَت.
 *
 * ولا تُستعمل هذه المراتبُ في حلقات المكس القديم: تلك ملفّان لا يُمزَجان،
 * فليس فيها ما يُخفَت — يبقى لها المبدّلُ بطرفيه.
 */
export const MUSIC_STOPS: { level: number; label: string }[] = [
  { level: 1, label: 'كاملة' },
  { level: 0.35, label: 'خافتة' },
  { level: 0, label: 'بلا' },
];

/**
 * أقربُ مرتبةٍ إلى مقدارٍ محفوظ. تلزم لأنّ أجهزةَ من جرّب المِزلاقَ تحمل قيمًا
 * بينيّة (‏٠٫٥٥ مثلًا)، فلولاها لبدت المجموعةُ بلا مضغوطٍ كأنّها معطوبة.
 * ولا يُكتَب المحفوظُ من جديد: قيمةُ المستمع تبقى حتّى يختار هو.
 */
export const nearestStop = (level: number): number =>
  MUSIC_STOPS.reduce((a, b) => (Math.abs(b.level - level) < Math.abs(a.level - level) ? b : a)).level;

