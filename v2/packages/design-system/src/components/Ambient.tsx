import { cn } from "../lib/cn";

/**
 * الشفق المحيط — خلفيّة الصفحة كلّها في طبقةٍ واحدة خلف كلّ شيء.
 * تُوضَع **مرّةً** أوّلَ حاوية المحتوى الموسومة `amb-host` (وهي `<main>` عادةً) فتخدمها
 * بطولها؛ لا تُكرَّر في قسمٍ ولا شاشة، ولا يُلَفّ بها محتوًى.
 *
 * **ولا تُعلَّق على `body`:** ارتفاعُه يشمل ما ليس من الصفحة — كالقصّة الافتتاحيّة التي
 * تشغل آلاف البكسلات حين تعمل وتُخفى عند التخطّي — فتتبدّل تركيبةُ البؤر بين الحالين.
 *
 * ثلاثُ طبقاتٍ لا رابع: **الضوء** · **الشبكة الكامنة** فوقه (تربيعاتٌ مقنَّعةٌ بالبلاطة
 * نفسها فلا تظهر إلا حيث يقع الضوء) · **الحبيبات** تكسر التشريط. ومقاسُ البلاطة
 * النافذةُ لا الحاوية، فالخلفيّة **واحدةٌ في كلّ صفحة** مهما طالت أو قصرت.
 *
 * **والطبقة `fixed` بمقاس النافذة** (٢٠٢٦-٠٧-٣١): كانت `absolute` بطول المحتوى،
 * فكان كلُّ تغييرِ تخطيطٍ في الصفحة يُبطل رسمَها — حتى صار فتحُ أكورديونٍ يتقطّع.
 * وثمنُ الإصلاح مقبولٌ بقرار المالك: **الضوء يمشي مع القارئ** بدل أن يمرّ به.
 * (القياسُ والبدائل المجرَّبة كلّها في `components.css` فوق `.amb`.)
 *
 * **بلا JS ولا حالة ولا مستمعِ تمرير** — مكوّنٌ خادميّ، لا `use client` ولا
 * جافاسكربت تُشحَن معه.
 */
export function Ambient({ className }: { className?: string }) {
  return (
    <div className={cn("amb", className)} aria-hidden>
      <div className="amb-rib" />
      <div className="amb-mesh" />
      <div className="amb-grain" />
    </div>
  );
}
