/**
 * وحدةُ العدّ في المخطّطات — **مصدرٌ واحد** لقائمة الأشرطة والحلقة معًا.
 *
 * الرقمُ وحده غامض، ورقمان متلاصقان (عددٌ ونسبة) يُقرآن كتلةً واحدة. فالوحدةُ توضّح وتفصل.
 * وتُصرَّف عربيًّا بـ`Intl.PluralRules` لا تُلصَق كلمةً واحدة: «زيارة» للواحد، و«زيارتان»
 * للاثنين، و«زيارات» للثلاث إلى العشر، ثمّ يعود المفرد (١١ فأكثر).
 */
export type ChartUnit = {
  one: string;
  two: string;
  few: string;
  /** تمييزُ ١١ إلى ٩٩ منصوبًا حين يختلف رسمُه عن المفرد: «٢٦ عضوًا» لا «٢٦ عضو».
   *  اختياريّ: كلمةٌ مؤنّثة («زيارة») لا يتغيّر رسمُها، فتبقى على `one`. (٢٠٢٦-١٠-٠٩) */
  many?: string;
  /** جنسُ الكلمة حين يخالف رسمَها (المؤنّثُ بلا تاء مربوطة)، لوصف الواحد: «… واحدة». الافتراضُ من الرسم. */
  fem?: boolean;
};

const AR_PLURAL = new Intl.PluralRules("ar");

/** الصيغةُ المناسبة لعددٍ بعينه (والصفر مع الجمع: «لا زيارات»). */
export function unitWord(n: number, unit?: ChartUnit): string | null {
  if (!unit) return null;
  const c = AR_PLURAL.select(n);
  if (c === "many" && unit.many) return unit.many;
  return c === "two" ? unit.two : c === "few" || c === "zero" ? unit.few : unit.one;
}

/**
 * الجملةُ كاملةً: عددٌ وكلمتُه — **إلّا في الواحد والمثنّى فيسقط العدد.**
 *
 * «٢ استماعتان» حشوٌ: صيغةُ المثنّى تحمل العددَ في نفسها، فالعربيّةُ تقول «استماعتان».
 * **والواحدُ يُوصَف ولا يُعدّ** (محمد ٢٠٢٦-١١-٢٢: «عضو واحد» لا «1 عضو»): الكلمةُ ثمّ «واحد» أو «واحدة» بجنسها،
 * والجنسُ من رسمها — ما خُتم بتاء مربوطة مؤنّث («حلقة واحدة»، «لجنة واحدة»)، وما سواه مذكّر («عضو واحد»).
 * وما خالف رسمَه يقوله صراحةً بـ`fem`. والتنوينُ في آخر الكلمة يسقط («فترةً» ← «فترة واحدة»).
 * وما سواهما يُكتب عددًا وكلمةً: «١٢ استماعة» و«٣ استماعات».
 *
 * وهي هنا لا في كلّ مستدعٍ، فلا يتفرّق الجوابُ عن سؤالٍ واحد.
 */
export function countPhrase(n: number, unit: ChartUnit): string {
  const word = unitWord(n, unit)!;
  if (word === unit.two) return word;
  if (n === 1) {
    const bare = unit.one.replace(/[\u064B-\u0652]+$/, "");
    const fem = unit.fem ?? bare.endsWith("\u0629");
    return `${bare} ${fem ? "واحدة" : "واحد"}`;
  }
  return `${n} ${word}`;
}
