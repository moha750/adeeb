/**
 * مطابقة البحث — **المصدر الوحيد** لكلّ شريط بحثٍ في اللوحة ولبحث المنسدلة.
 *
 * المطابقة الخام (`includes`) تسأل الباحث أن يكتب النصّ حرفًا بحرف كما خُزّن:
 * «احمد» لا تجد «أحمد»، و«فعالية» لا تجد «فعاليّة»، و«2026» لا تجد «٢٠٢٦».
 * الحلّ أن يمرّ الطرفان — المكتوب والمخزون — على تسويةٍ واحدة قبل المقارنة.
 *
 * كلّ نطاقات المحارف تُكتب بترميز `\u` لا بمحارف صريحة (كطقم المحارف في `charset.ts`):
 * المحرف العربيّ الصريح داخل صنف محارف يصعب تدقيقه في ملفّ ثنائيّ الاتّجاه، وبعضه غير مرئيّ أصلًا.
 */

/**
 * علامات تُحذف: التشكيل العربيّ وعلامات الهمزة (U+064B–U+065F) · الألف الخنجريّة (U+0670) ·
 * علامات المصحف (U+06D6–U+06ED) · التطويل (U+0640) · علامات اللاتينيّة المركّبة (U+0300–U+036F).
 */
const MARKS = /[\u0300-\u036F\u064B-\u065F\u0670\u06D6-\u06ED\u0640]/g;
/** محارف صفريّة العرض وعلامات الاتّجاه — تتسلّل مع اللصق فتكسر المطابقة بلا أثرٍ مرئيّ. */
const INVISIBLE = /[\u200B-\u200F\u061C\u2066-\u2069\uFEFF]/g;
/** أرقام عربيّة‑هنديّة (U+0660–U+0669) وفارسيّة (U+06F0–U+06F9) — تُردّ إلى اللاتينيّة. */
const DIGITS = /[\u0660-\u0669\u06F0-\u06F9]/g;
/** ألف مقصورة ← ياء · تاء مربوطة ← هاء · همزة مفردة تُحذف · كاف وياء فارسيّتان ← عربيّتان. */
const LETTERS: Array<[RegExp, string]> = [
  [/\u0649/g, "\u064A"],
  [/\u0629/g, "\u0647"],
  [/\u0621/g, ""],
  [/[\u06A9\u06AA]/g, "\u0643"],
  [/[\u06CC\u06D0]/g, "\u064A"],
];

/**
 * تسوية نصٍّ للمقارنة.
 *
 * التفكيك `NFKD` وحده يحلّ أشكال الهمزة: أ إ آ تصير ألفًا + علامةً تُحذف، وكذلك ؤ ← و و ئ ← ي،
 * ومعه تُردّ أشكال العرض (U+FB50–U+FEFF) إلى أصولها. يبقى ما لا تفكيك له فيُرَدّ يدويًّا في `LETTERS`.
 *
 * والمسافة تُحذف حذفًا — ليست حرفًا في البحث: «عبد الله» و«عبدالله» اسمٌ واحد يُكتب بالوجهين
 * في الجدول نفسه، فحسابُ المسافة يُخفي الاسم عمّن كتبه بالوجه الآخر. ثمنه مطابقةٌ عابرةٌ
 * لحدّ الكلمتين في الاستعلام القصير جدًّا — وهو صفٌّ زائد نادر، أهون من صفٍّ غائب.
 */
export function foldSearch(text: string): string {
  let out = text.normalize("NFKD").toLowerCase().replace(MARKS, "").replace(INVISIBLE, "");
  for (const [re, to] of LETTERS) out = out.replace(re, to);
  return out.replace(DIGITS, (d) => String(d.charCodeAt(0) & 0xf)).replace(/\s+/g, "");
}

/**
 * هل يُطابِق أحد الحقول نصّ البحث؟ استعلامٌ فارغ يُطابِق كلّ شيء (لا بحث = لا تصفية).
 * الحقول الفارغة (`null`/`undefined`) تُتخطّى.
 *
 * الاستعلام يُقرأ **كلماتٍ لا كتلةً**: كلّ كلمةٍ تُطلب في الصفّ، بأيّ ترتيب وبينها ما بينها.
 * وبهذا يجد الثنائيُّ الثلاثيَّ («محمد المطر» ← محمد إسماعيل المطر)، ويجد المقلوبُ صاحبَه.
 *
 * والكلمة تُطلب في **أيّ حقل** لا في حقلٍ واحد: هكذا يبحث الناس فعلًا حين تحمل الصفوف حقولًا كثيرة
 * («قائد التسويق» — الدور من هنا واللجنة من هناك). ثمنه مطابقةٌ باسمٍ من حقلٍ ورقمٍ من آخر، وهي مقصودة.
 */
export function matchesSearch(query: string, ...fields: Array<string | null | undefined>): boolean {
  const terms = query.split(/\s+/).map(foldSearch).filter(Boolean);
  if (terms.length === 0) return true;
  const hay = fields.filter(Boolean).map((f) => foldSearch(f as string));
  return terms.every((t) => hay.some((h) => h.includes(t)));
}
