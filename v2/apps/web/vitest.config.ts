import { fileURLToPath } from "node:url";
import { defineConfig } from "vitest/config";

/**
 * مِعيارُ المنطق النقيّ — لا متصفّح ولا قاعدة ولا شبكة.
 *
 * الاسمُ المستعار `@/` يُحلّ هنا كما يُحلّه `tsconfig.json` حرفًا بحرف (`./src/*`)، فلا
 * تفترق قراءةُ المِعيار عن قراءة البناء. ولا نستعمل حزمةً تقرأ `tsconfig` نيابةً عنّا:
 * سبيلٌ واحدٌ مكتوبٌ خيرٌ من سبيلين قد يختلفان.
 *
 * والبيئةُ `node` لأنّ كلَّ ما يُختبَر ههنا حسابٌ لا DOM: أسماءٌ تُقسَم، وأقفالٌ تُسأل،
 * وصيغٌ تُطابَق، ومحرّكُ انتخابٍ يُشغَّل في الذاكرة.
 */
export default defineConfig({
  resolve: {
    alias: {
      "@": fileURLToPath(new URL("./src", import.meta.url)),
    },
  },
  test: {
    environment: "node",
    include: ["src/**/*.test.ts"],
    // ساعةُ المِعيار ثابتةٌ لا ساعةُ الجهاز: تواريخُ أديب تُنسَّق بتوقيت الرياض دائمًا،
    // فلو تغيّرت منطقةُ المُشغِّل لتغيّر ما نقيسه عليه.
    env: { TZ: "UTC" },
  },
});
