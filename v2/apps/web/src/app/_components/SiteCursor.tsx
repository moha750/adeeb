"use client";

import { usePathname } from "next/navigation";
import { Cursor } from "@adeeb/design-system";

/**
 * مؤشّرُ أدِيب على الموقع كلِّه — **بلا استثناءٍ حتى اللوحة** (قرار المالك ٢٠٢٦-٠٨-٠٤،
 * ناقضًا ما كان مكتوبًا من استثنائها).
 *
 * ويُركَّب هنا لا في التخطيط الجذر مباشرةً لسببين: **الجذرُ خادميّ** والمؤشّرُ عميليّ،
 * فلو رُكِّب فيه لصار التخطيطُ كلُّه عميليًّا ولذهبت فائدةُ رسمه على الخادم؛ و**معرضُ
 * المكوّنات** يُستثنى، والاستثناءُ يحتاج قراءةَ المسار وهي عميليّة.
 *
 * **والمعرضُ وحدَه مستثنًى** (`/ui`): هو منزلُ عملٍ تُفحَص فيه المكوّناتُ مفردةً،
 * ولمؤشّرِه صفحتُه الخاصّة (`/ui/cursor`) تُركّبه بنفسها — فلو عمَّ المعرضَ لزاحم
 * كلَّ مكوّنٍ يُفحَص.
 *
 * ══ وللإذاعة مؤشّرُها: هالةٌ وحدَها ══
 * اختارها المالك ٢٠٢٦-٠٩-١٨ بعد أن عُرضت عليه أشكالُ سنٍّ ثمّ أفعالٌ (أثرٌ موجيّ ·
 * نقرةٌ تُصدر موجة · هالةٌ تقرأ تقدّمَ ما تحتها · هالةٌ تتنفّس بسَعةِ ما يُذاع)،
 * فقال: «أعتمد هالة فقط». وأُعدم ما سواها من المكتبة والمختبر.
 *
 * **ومعها قرصُ تصويبٍ صغير** (٢٠٢٦-٠٩-١٩): الهالةُ وحدَها تقول «أنت هنا تقريبًا»،
 * فاختار المالك القرصَ من أربعِ إجاباتٍ عُرضت عليه حيّةً.
 *
 * **وحجّةُ الهالة عزلُ الهويّة لا الذوقَ وحدَه** (القاعدة ١، وقد وسّعها المالك إلى «كلّ
 * شيء بلا استثناء»): الريشةُ علامةُ نادي أدِيب، فبقاؤها في المحطّة يُبقي علامةَ
 * النادي تتبع اليدَ في كلّ شاشة. والهالةُ شكلٌ لا يحمل علامةَ أحد، وتلبس عنّابيَّ
 * المحطّة من `--cur-ink` على جذرها.
 */
export function SiteCursor() {
  const path = usePathname();
  /* **المطابقةُ على المسار كاملًا أو مقطعًا** لا على بادئة الحروف: `startsWith("/ui")`
     وحدَها تبتلع كلَّ مسارٍ يبدأ بهذين الحرفين — `/uikit` أو `/university` — فتُطفئ
     المؤشّرَ في صفحةٍ لا علاقة لها بالمعرض يوم تُضاف. */
  if (path === "/ui" || path?.startsWith("/ui/")) return null;
  /* **والمفتاحُ يتغيّر بتغيّر الصيغة** كي يُعاد بناءُ المؤشّر لا يُرقَّع: طبقاتُه
     تُركَّب وتُرفَع مع `nib`، والمحرّكُ يقيس من الجذر — فبدايةٌ نظيفةٌ أسلمُ من
     حالةٍ نصفُها من صيغةٍ ونصفُها من أخرى عند عبور الحدّ. */
  const station = path === "/radio" || path?.startsWith("/radio/")
    // و«دربك خضر» مثلُها: الريشةُ علامةُ النادي، والنادي لا يظهر في اللعبة بأيّ صورة.
    || path === "/games/darbak-khadar" || path?.startsWith("/games/darbak-khadar/");
  /* **وقرصُ التصويب للإذاعة وحدَها:** خارجَها طرفُ الريشة هو النقطةُ الدقيقة،
     فقرصٌ معه شكلٌ ثانٍ بلا فائدة. */
  return station ? <Cursor key="stn" nib="none" point="dot" /> : <Cursor key="site" />;
}
