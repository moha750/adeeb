/**
 * **تبويباتُ صفحة «ركضة وطن» الخمسة** (قرارُ المالك ٢٠٢٦-٠٩-٢٥)، **بترتيبه هو** بعد أن رآها في
 * المعاينة: حسابي، والمسابقة، والصدارة، وكيف تُلعب؟، والدعم. والأوّلُ في أقصى اليمين.
 *
 * **والترتيبُ غيرُ الافتراض:** الصفحةُ بلا `?tab=` تفتح على الصدارة وإن لم تكن أوّلَ الشريط، لأنّ
 * روابطَ اللعبة («لوحة الصدارة» في شاشة النهاية) ورابطَ المنشور `/watan` كلَّها تعني اللوحة.
 *
 * خاليةٌ من React عمدًا، فيقرؤها الخادمُ (`page.tsx`: التبويبُ من `?tab=` يُرسَم من أوّل طلب، فلا
 * تومض الصدارةُ ثمّ تنقلب) والعميلُ (`Board.tsx`: الشريطُ والتبديل) من مصدرٍ واحد.
 *
 * **والتبويبُ في الرابط** لا في الذاكرة: «رمزُ الاسترجاع من حسابي» جملةٌ في الدعم وفي اللعبة،
 * والدخولُ بحساب أدِيب يعود إلى `/watan?tab=me` نفسِه. والصدارةُ بلا مُعامِل، فرابطُ المنشور
 * القديم `/watan` يبقى كما هو.
 */
export const TABS = [
  { key: "me", label: "حسابي" },
  { key: "contest", label: "المسابقة" },
  { key: "board", label: "الصدارة" },
  { key: "how", label: "كيف تُلعب؟" },
  { key: "help", label: "الدعم" },
] as const;

export type TabKey = (typeof TABS)[number]["key"];

const KEYS = new Set<string>(TABS.map((t) => t.key));

/** ما في الرابط إن كان تبويبًا نعرفه، وإلّا فالصدارة. */
export function tabOf(raw: unknown): TabKey {
  return typeof raw === "string" && KEYS.has(raw) ? (raw as TabKey) : "board";
}

/** رابطُ التبويب نفسُه: الصدارةُ `/watan` بلا مُعامِل. */
export const tabHref = (t: TabKey) => (t === "board" ? "/watan" : `/watan?tab=${t}`);
