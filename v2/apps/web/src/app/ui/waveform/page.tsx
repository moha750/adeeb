/**
 * ومقترحٌ رابعٌ عُرض ورُفض: **خطوةُ ٣px** بعمودٍ ٢px و**فجوةٍ ١px**. أكثفُ تفصيلًا،
 * لكنّه يعيد العلّةَ درجةً أسفل: عرضُ العمود كسريّ (‏2.02px) فتقع الفجوةُ الواحدةُ
 * على غير حدّ البكسل وتُدهَن حافّتاها، فتلتحم الأعمدةُ كتلةً. وهو المقترحُ الوحيدُ
 * الذي طلب فجوةً غيرَ ٢px، فلمّا سقط لم يبقَ لمقبض الفجوة مستعمل: نُزع من الورقة
 * وبقي الخبرُ ههنا (٢٠٢٦-٠٨-١٨).
 */

/** يقيس عرضَ عنصرٍ حيًّا. صفرٌ قبل أوّل قياس، فيُرسَم بالحاليّ ثمّ يُصحَّح. */
function useW(): [number, (el: HTMLDivElement | null) => void] {
  const [w, setW] = useState(0);
  const ref = useCallback((el: HTMLDivElement | null) => {
    if (!el) return;
    const apply = () => setW(el.getBoundingClientRect().width);
    apply();
    new ResizeObserver(apply).observe(el);
  }, []);
  return [w, ref];
}

/**
 * موجةٌ بمقترحٍ واحد. والعرضُ المقيسُ يخدم أمرين: اشتقاقَ العدد، وحسابَ غِلَظِ
 * العمود المعروض في الشارة — وكلاهما من المقيس نفسِه فلا يتناقضان.
 */
function Wave({ v, pct, onSeek }: { v: Variant; pct: number; onSeek: (p: number) => void }) {
  const [w, ref] = useW();
  const count = w > 0 ? v.bars(w) : 24;
  const drawn = downsample(PEAKS, count);
  const barW = w > 0 ? (w - (drawn.length - 1) * BAR_GAP) / drawn.length : 0;
  const played = Math.round(drawn.length * (pct / 100));

  return (
    <div className="phdlab-col">
      <div className={"phdlab-tag " + v.tone}>
        <span className="dot" aria-hidden />
        {v.tag}
        <span className="h">
          {w > 0 ? `${drawn.length} × ${barW.toFixed(2)}px` : ""}
        </span>
      </div>
      <div className="phdlab-frame">
        {/* سلسلةُ الحشو الحقيقيّة كما في `/radio/[show]/[episode]`: حاويةٌ ثمّ بطاقةُ المشغّل. */}
        <Container>
          <div className="radp">
            <div
              className="radw"
              ref={ref}
              onClick={(e) => {
                const r = e.currentTarget.getBoundingClientRect();
                // اللوحةُ في سياقٍ من اليمين إلى اليسار، فالبدايةُ حافّتُها اليمنى.
                onSeek(Math.round(((r.right - e.clientX) / r.width) * 100));
              }}
            >
              {drawn.map((h, i) => (
                <span
                  key={i}
                  className={"radw-bar" + (i < played ? " is-played" : "")}
                  style={{ height: `${h}%` }}
                />
              ))}
            </div>
          </div>
        </Container>
        <div className="phdlab-body">{v.note}</div>
      </div>
    </div>
  );
}

