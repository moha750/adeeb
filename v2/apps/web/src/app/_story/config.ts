export const SESSION_KEY = "adeeb-story-seen";

/* «رُئيت في هذه الجلسة» — قراءتها وكتابتها في موضعٍ واحد: القصة تُكتب مرئيّةً
   عند بلوغ الخاتمة أو التخطّي، وتُقرأ عند كل دخولٍ إلى الهبوط. وتخزينٌ محظور
   (تصفّحٌ خاص أو منعٌ من الزائر) ⇒ تُعرض القصة: البوابة تيسيرٌ لا شرط. */
export const storySeen = (): boolean => {
  try {
    return STORY_CONFIG.showOncePerSession && !!sessionStorage.getItem(SESSION_KEY);
  } catch {
    return false;
  }
};

export const markStorySeen = (): void => {
  if (!STORY_CONFIG.showOncePerSession) return;
  try {
    sessionStorage.setItem(SESSION_KEY, "1");
  } catch {
    /* تخزين محظور — لا شيء يعتمد عليه */
  }
};
