/**
 * **نصوصُ الحاوية التي تُقال في بابين** — مصدرٌ واحدٌ لا نسختان.
 *
 * الحذفُ يُؤكَّد من القائمة ومن غرفة الحملة، فلو كُتب نصُّ التبعة في الموضعين حرفًا بحرف
 * لافترقا: يُصحَّح في أحدهما ويبقى في أخيه (درسُ `../copy` ٢٠٢٦-٠٩-٠٥).
 */

/** وحدةُ عدّ الباركودات، تُصرَّف عربيًّا حيث لا ترويسةَ تسمّي العمود. */
export const LINK_UNIT = { one: "باركود", two: "باركودان", few: "باركودات" };

/**
 * تبعةُ حذف الحاوية كما تُقال لصاحبها قبل أن يقرّر.
 *
 * **وهي تبعةٌ هيّنةٌ عن قصد**، بخلاف حذف الباركود: الحاويةُ ورقةُ تنظيمٍ تُمزَّق،
 * والملصقُ المطبوعُ في الشارع يبقى يعمل ويُعَدّ. فالجملةُ تقول ذلك ولا تخوّف بلا سبب.
 */
export const campaignKillText = (name: string, links: number) =>
  links === 0
    ? `ستُحذف «${name}»، وهي فارغةٌ فلا يتبعها شيء.`
    : `ستُحذف «${name}» وحدَها. و${links === 1 ? "باركودُها" : `باركوداتُها الـ${links}`} تخرج منها وتبقى تعمل ومسحاتُها محفوظة، فلا يموت ملصقٌ مطبوع.`;

/** جملةُ إخراج باركودٍ من حاويته، من قائمة الغرفة. */
export const linkOutText = (title: string) =>
  `سيخرج «${title}» من الحملة ويبقى يعمل. ومسحاتُه تبقى له، ويسقط من مجموع الحملة.`;
