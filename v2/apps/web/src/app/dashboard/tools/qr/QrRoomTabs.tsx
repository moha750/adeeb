import Link from "next/link";

/**
 * **بابا الغرفة: الحملاتُ والباركوداتُ المفردة** (اختيارُ المالك ٢٠٢٦-٠٩-٢٤، الشكل ب).
 *
 * **وصفحتان لا حالةٌ في شاشة**، على عُرف `QrTabs` وحجّتِه نفسِها: الصفحةُ عنوانٌ يُربَط به،
 * فمن أرسل رابطَ حملاتِه أرسل ما يقصد، والرجوعُ بالسهم يعود إلى ما كان فيه.
 *
 * **وجذرُ الغرفة يقود إلى قائمة الباركودات** ولم تنتقل الحملاتُ إليه: من لا حملةَ له
 * لا يُستقبَل بغرفةٍ فارغة، بل بقائمته كما عهدها. والقائمةُ نفسُها نزلت إلى `links/`
 * (٢٠٢٦-١٠-٠٣) كي تُسمّى في الفتات كجارتها، والجذرُ يحوّل إليها فلا ينكسر رابطٌ محفوظ.
 *
 * **و«مفردة» لا «كلّ الباركودات»** (قرارُ المالك ٢٠٢٦-٠٩-٢٤): سأل «أمن المنطق أن تتواجد
 * باركوداتُ الحملة في كلّ الباركودات؟» فأمر بإخفاء ما يتبع حملةً. **والتسميةُ تتبع
 * المحتوى ولا تسبقه**: بابٌ لا يحمل إلّا ما لا حاويةَ له لا يصحّ أن يُسمّى «الكلّ»،
 * فيُسمّى بما فيه، ويُقرأ بالتقابل مع جاره: حملاتٌ، ومفردة.
 */
export function QrRoomTabs({ on }: { on: "links" | "campaigns" }) {
  const item = (key: "links" | "campaigns", label: string, href: string) => (
    <Link
      href={href}
      role="tab"
      aria-selected={on === key}
      aria-current={on === key ? "page" : undefined}
      className={"tab" + (on === key ? " on" : "")}
    >
      {label}
    </Link>
  );

  return (
    <div className="tabs tabs-segmented tabs-split" role="tablist" style={{ marginBottom: 18 }}>
      {item("links", "باركودات مفردة", "/dashboard/tools/qr/links")}
      {item("campaigns", "الحملات", "/dashboard/tools/qr/campaigns")}
    </div>
  );
}
