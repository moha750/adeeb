import { notFound } from "next/navigation";

/**
 * المسار الجامع للّوحة — يلتقط كلّ رابطٍ تحت `/dashboard` لا يطابق مسارًا حقيقيًّا.
 *
 * **لماذا يلزم:** حدُّ `not-found.tsx` في مقطعٍ يخدم `notFound()` المرميّة من صفحاته
 * فحسب؛ أمّا الرابط الذي لا يطابق شجرة المسارات فلا يدخل المقطع أصلًا — يسقط إلى حدّ
 * الجذر فتُعرض صفحة الزوّار بهيدرها، وتختفي اللوحة من تحت المدير (شوهد حيًّا).
 * وبهذا الجامع يصير الرابط **داخل** اللوحة أوّلًا (فيمرّ بحارس تخطيطها)، ثمّ يرمي
 * `notFound()` فيلتقطه حدُّها فيبقى الشِّلّ قائمًا.
 *
 * ولا يزاحم المسارات القائمة: المقطع الأخصّ يفوز على الجامع في توجيه Next دائمًا.
 */
export default function DashboardCatchAll(): never {
  notFound();
}
