import { AdRoomDenied } from "@/app/_ad/states";

/**
 * تنبيه «لا صلاحية» لصفحات محتوى الموقع — يُعرض لمن لا يملك قدرة **هذا المجلّد وحده**
 * (ولو ملك بقيّة مجلّدات المحتوى، ولو كان من الإدارة العليا: الرتبة لا تعني الوصول).
 * `section` اسم القسم في العنوان والرسالة (الأعمال، الإحصاءات، الرعاة، الأسئلة الشائعة) —
 * أمّا الفتاتُ فمن المسار الفعليّ: الشاشةُ تُعرَض على المجلّد وعلى `new` و`edit` تحته.
 * **بالقطعة لا بالتنبيه القديم** (٢٠٢٦-١١-١٧، `AdRoomDenied`): لوحُ الغرفة باسمها، وتحته القفلُ وجملتُه نفسُها و«العودة إلى البوّابة».
 */
export function WebsiteDenied({ section }: { section: string }) {
  return (
    <AdRoomDenied title={section} navPath="/dashboard" what={`إدارة «${section}»`}
      desc={`هذه الصفحة لمن مُنحت له قدرة إدارة «${section}» وحدها. إن رأيت أنّها ينبغي أن تكون لك، فراجع مسؤول الصلاحيات.`} />
  );
}
