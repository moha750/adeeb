/* ── النظامان ورقماهما ─────────────────────────────────────────────────── */

/** أيُّ النظامين. */
export type Mode = "stamps" | "points";

/**
 * **رقمُ بطاقة النقاط مشتقٌّ من رقم الأختام** بتبديل كلمةٍ واحدة (`CARD` ← `PTS`).
 *
 * **ولماذا رقمان لا رقم؟** البطاقةُ في المحفظة تُعرَّف برقمها: لو حملت البطاقتان رقمًا
 * واحدًا لَحلّت إحداهما محلّ الأخرى في الجهاز — والمرادُ أن تعيشا معًا فيقارن المالك
 * بالعين لا بالذاكرة.
 *
 * **والاشتقاقُ لا الاختراع**: رقمٌ ثانٍ مستقلٌّ يعني قائمتين تُصانان، وسطرًا يُنسى.
 */
export const pointsSerial = (m: DemoMember): string => m.serial.replace("-CARD-", "-PTS-");

/** أيُّ نظامٍ يخصّ هذا الرقم؟ — `null` لما لا يُشبه رقمًا من عندنا. */
export function modeOfSerial(serial: string): Mode | null {
  if (serial.includes("-CARD-")) return "stamps";
  if (serial.includes("-PTS-")) return "points";
  return null;
}

/**
 * عضوٌ برقم بطاقته — **بأيّ النظامين**، و**`null` إن لم يوجد** بخلاف `memberById`.
 * تسأله خدمةُ التحديث برقمٍ يأتي من الجهاز، فالمجهولُ يُردّ بـ٤٠٤ لا يُبدَّل بأوّل القائمة.
 */
export const memberBySerial = (serial: string): DemoMember | null =>
  MEMBERS.find((m) => m.serial === serial || pointsSerial(m) === serial) ?? null;

/** رقمُ البطاقة لعضوٍ في نظامٍ بعينه — المصدرُ الواحد لكلّ من يبني حزمةً أو رابطًا. */
export const serialFor = (m: DemoMember, mode: Mode): string => (mode === "points" ? pointsSerial(m) : m.serial);

/** هل اكتملت البطاقة فاستحقّت المكافأة؟ */
export const isComplete = (stamps: number): boolean => stamps >= GOAL;

/** حالةُ البطاقة سطرًا واحدًا — تُكتب على البطاقة وفي الصفحة، فلا صياغتان. */
export function statusText(stamps: number): string {
  if (isComplete(stamps)) return "مكافأةٌ جاهزة";
  const left = GOAL - stamps;
  if (left === 1) return "بقيت مشاركةٌ واحدة";
  if (left === 2) return "بقيت مشاركتان";
  return `بقيت ${num(left)} مشاركات`;
}

/* ── الصياغة ────────────────────────────────────────────────────────────── */

/**
 * رقمٌ بأرقامٍ **لاتينيّة** (قرار المالك ٢٠٢٦-٠٨-٠٤) — مصدرٌ واحدٌ لكلّ رقمٍ يظهر:
 * عدّادُ البطاقة، ونصُّ الحالة، ونصُّ الإشعار، والصفحة، وشاشةُ المسح. فلا يفترق رقمٌ
 * في الجيب عن نظيره على الشاشة.
 *
 * (كانت عربيّةً‑هنديّة `٤ / ١٠`؛ وتبديلُها هنا وحده بدّلها في المواضع كلّها.)
 */
export const num = (n: number): string => n.toLocaleString("en-US");

/**
 * العدّاد كما يُعرَض — **مصدرٌ واحدٌ للبطاقة والإشعار والصفحة وشاشة المسح**.
 *
 * **والرقمُ وحده بلا مجموع** (قرار المالك ٢٠٢٦-٠٨-٠٤). وله وجهان:
 *
 * · **تصميمًا**: الأختامُ العشرة **مرسومةٌ على البطاقة**، فالمجموعُ مرئيٌّ بالعين ولا
 *   يحتاج تكرارًا بالرقم. ومعه حقلُ الحالة يقول «بقيت ٧ مشاركات» صراحةً.
 * · **وسلامةً**: `9 / 10` كان يُقرأ عند المالك مقلوبًا. وإلصاقُ الشرطة (`9/10`) يجعل
 *   الكتلةَ رقمًا واحدًا بحكم خوارزميّة الاتّجاه (قاعدة W4)، **ولم يُقنع**. ورقمٌ مفردٌ
 *   لا اتّجاهَ فيه أصلًا — فلا يبقى ما ينقلب.
 *
 * **ولا يُعالَج مثلُ هذا بمحارف تحكّمٍ خفيّة** (LRI/PDI): تلك تُصلح المرئيّ وتُبقي النصّ
 * هشًّا — يُنسَخ فتُنسَخ معه، ويُقصّ فتضيع.
 */
export const score = (stamps: number): string => num(stamps);
