/**
 * **الأوّلُ والأخير** — الاسمُ الرباعيّ يطول على خانةٍ أو سطرٍ في سجلّ، فيُؤخذ منه طرفاه
 * (أمرُ المالك ٢٠٢٦-٠٨-١٤): اسمُه وعائلتُه — وهما ما يُنادى به ويُعرَف، أمّا أسماءُ الآباء
 * بينهما فلا تُميّز أحدًا في قاعةٍ واحدة. والكاملُ يبقى حيث يتّسع له المقام.
 *
 * **والكلمةُ ليست اسمًا دائمًا:** «عبد الله» اسمٌ واحدٌ كُتب كلمتين، وأخذُ الكلمات عدًّا يُخرِج
 * «عبد» وحدَها — نداءٌ لا يُقال. وكذلك «بن» و«بنت» و«أبو» و«آل»: كلماتُ وصلٍ تُضمّ إلى ما بعدها،
 * فآخِرُ «نورة بنت سعد آل سعود» هو «آل سعود» لا «سعود». فالقسمةُ **بالأسماء لا بالكلمات**.
 *
 * ويعيش هنا لا في شاشةٍ بعينها: يقرؤه كرتُ الانتخاب وسجلُّه معًا، فلا نسختان تفترقان.
 */
const NAME_GLUE = ["عبد", "عبدُ", "بن", "ابن", "بنت", "ابنة", "أبو", "أبا", "أبي", "آل", "ذو", "ذي"];

/**
 * **الاسمُ عربيٌّ لا سواه** (أمرُ المالك ٢٠٢٦-٠٨-١٥): كلُّ حقلٍ يحفظ اسم إنسان (عضوًا كان أو
 * صاحبَ حسابٍ أو شاغلَ منصب) لا يقبل إلّا الحروف العربيّة. فالاسمُ يُطبع في شهادةٍ ويُرسَم في
 * خطابٍ ويُنادى به في كشف: حرفٌ لاتينيٌّ فيه يقلب سطرَ السجلّ ويكسر الورقة المطبوعة.
 *
 * ويعيش الحكمُ ههنا مع قسمة الاسم لا في كلّ نموذجٍ نسخةً: **حارسٌ واحدٌ على سبعة أبواب** (التسجيل ·
 * الحجز · بياناتي · إكمال السجلّ · كاتبُ بيانات العضو · نموذجُ اللوحة · اسمُ الشهادة)، ووراءه
 * قيدُ القاعدة نفسِها (`*_arabic_check`) فلا يدخل ما فات الشاشات.
 *
 * والمدى مكتوبٌ بالرموز لا بالحروف عمدًا: مدًى عربيٌّ مكتوبٌ حرفًا يُقرأ في المحرّر مقلوبَ
 * الطرفين فيُظنّ غيرَ ما هو.
 */
const ARABIC_LETTERS = "ء-غف-يٱ";
/** التشكيلُ يُقبَل: «زَهرَاء جَواد» اسمٌ مشكولٌ لا اسمٌ مخالف. */
const ARABIC_MARKS = "ً-ٰٕ";
const ARABIC_NAME_RE = new RegExp(`^[${ARABIC_LETTERS}${ARABIC_MARKS} ]+$`);

export const ARABIC_NAME_HINT = "اكتب الاسم بالحروف العربيّة وحدها";

/**
 * تطبيعُ الاسم قبل حفظه أو وزنه: تُنزع محارفُ الاتّجاه الخفيّة والتطويل (زينةٌ لا حرف)،
 * وتُقلَّص المسافات المتوالية إلى واحدة. فما يُخزَّن اسمٌ نظيفٌ يُقارَن ويُطبع كما كُتب.
 */
export function normalizeName(raw: string): string {
  return raw
    .replace(/[​-‏‪-‮⁦-⁩ـ]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * خطأُ الاسم إن خالف العربيّة، وإلّا `null`.
 *
 * والخلوُّ ليس من شأنه: كلُّ بابٍ يعرف كم يلزمه من الاسم (حرفان ههنا وخمسةٌ هناك)، فلا يُصادَر
 * حكمُه ولا تُزاحَم رسالتُه. وهذا يحكم **جنسَ الحروف** وحدَه.
 */
export function arabicNameError(raw: string | null | undefined): string | null {
  const name = normalizeName(raw ?? "");
  if (!name) return null;
  return ARABIC_NAME_RE.test(name) ? null : ARABIC_NAME_HINT;
}

export function firstAndLastOf(full: string): string {
  const parts = full.trim().split(/\s+/).filter(Boolean);
  const names: string[] = [];
  for (let i = 0; i < parts.length; i++) {
    let name = parts[i];
    // كلمةُ الوصل تبتلع ما بعدها (وقد تتوالى: «أبو عبد الله»)
    while (NAME_GLUE.includes(parts[i]) && i + 1 < parts.length) {
      name = `${name} ${parts[i + 1]}`;
      i += 1;
    }
    names.push(name);
  }
  if (names.length < 2) return names[0] ?? full;
  return `${names[0]} ${names[names.length - 1]}`;
}
