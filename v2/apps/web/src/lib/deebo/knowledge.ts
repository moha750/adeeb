/**
 * معرفة ديبو — المصدر الذي يقرؤه في كلّ سؤال.
 *
 * ديبو لا يتعلّم ولا يتذكّر. فما لم يُكتب هنا (أو يُقرأ من القاعدة لحظة السؤال)
 * لا وجود له عنده. هذا الملفّ هو «التدريب» بالمعنى الوحيد الذي يخصّنا.
 *
 * ## من أين تأتي المعرفة
 *
 * مصدران لا ثالث لهما، وترتيبُهما مقصود:
 *
 *   ١) جدول `faq` في القاعدة — ثلاثة عشر جوابًا بصوت المالك، ويُحرَّر من اللوحة.
 *      هو المصدر الأوّل لأنّه حيٌّ: تصحيحُ جوابٍ فيه يصلح ديبو بلا نشر.
 *   ٢) `STATIC_CHUNKS` أدناه — ما لا يغطّيه الجدول ولا يتغيّر (الجامعة، المدينة،
 *      حدود ما يفعله ديبو نفسه).
 *
 * ## القاعدة الحاكمة: لا رقمًا يتغيّر
 *
 * ممنوع أن يُكتب هنا عددُ أعضاءٍ أو اسمُ قائدٍ حاليّ أو تاريخُ فعاليّةٍ قادمة.
 * كلُّ رقمٍ متغيّرٍ يُكتب هنا وعدٌ بأن يكذب ديبو بعد شهور. المتغيّر يُقرأ من
 * القاعدة لحظة السؤال، والثابت وحده يُكتب.
 *
 * وحارسُ `guard.ts` يمسك ما ندّ: كلّ عددٍ في الجواب لم يرد في هذه المعرفة ولا في
 * سؤال الزائر يُحجَب قبل أن يصل القارئ.
 */

/** مقطعُ معرفةٍ واحد. `slug` معرّفٌ ثابت يُستشهد به ولا يُترجم. */
export type KnowledgeChunk = {
  slug: string;
  title: string;
  body: string;
};

/** صفٌّ من جدول `faq` كما يُقرأ من القاعدة. */
export type FaqRow = { question: string; answer: string };

