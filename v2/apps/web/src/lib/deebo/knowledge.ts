/**
 * معرفة ديبو — المصدر الذي يقرؤه في كلّ سؤال.
 *
 * ديبو لا يتعلّم ولا يتذكّر. فما لم يُقرأ من القاعدة لحظةَ السؤال لا وجود له عنده.
 * هذا الملفّ هو «التدريب» بالمعنى الوحيد الذي يخصّنا: **تركيبُ** المعرفة، لا حفظُها.
 *
 * ## من أين تأتي المعرفة
 *
 * مصدران لا ثالث لهما، وكلاهما **جدولٌ يُحرَّر من اللوحة** (٢٠٢٦-٠٨-٢٢):
 *
 *   ١) جدول `faq` — الأجوبةُ بصوت المالك، من `‎/dashboard/website/faq`‎.
 *   ٢) جدول `deebo_knowledge` — الوقائعُ الثابتة، من `‎/dashboard/deebo/knowledge`‎.
 *
 * وكانت الثانيةُ حتّى اليوم أربعةَ مقاطعَ محفورةً في هذا الملفّ (`STATIC_CHUNKS`)،
 * فكان تصحيحُ حرفٍ فيها نشرًا كاملًا. نُقلت إلى القاعدة بترحيل `deebo_07`، ونصُّها
 * هناك حرفًا بحرف: الترحيلُ نقلَ مسكنَ النصّ ولا يبدّل ما يقوله ديبو.
 *
 * **ولا نسخةَ احتياطيّةً في الكود**: مصدرٌ واحدٌ أو مصدران يفترقان صامتَين. فإن تعذّرت
 * القراءةُ ردَّ المِنفذُ الطلبَ (٥٠٣) كما يفعل مع `faq` سواءً بسواء — ولا يجيب ديبو
 * بنصف معرفةٍ لا يدري أيَّ نصفٍ هو.
 *
 * ## القاعدة الحاكمة: لا رقمًا يتغيّر
 *
 * ممنوع أن يُكتب في المعرفة عددُ أعضاءٍ أو اسمُ قائدٍ حاليّ أو تاريخُ فعاليّةٍ قادمة.
 * كلُّ رقمٍ متغيّرٍ يُكتب وعدٌ بأن يكذب ديبو بعد شهور. والقيدُ في القاعدة يقول ذلك
 * لكاتب الواقعة، وحارسُ `guard.ts` يمسك ما ندّ: كلّ عددٍ في الجواب لم يرد في هذه
 * المعرفة ولا في سؤال الزائر يُحجَب قبل أن يصل القارئ.
 */

/** مقطعُ معرفةٍ واحد. `slug` معرّفٌ ثابت يُستشهد به ولا يُترجم. */
export type KnowledgeChunk = {
  slug: string;
  title: string;
  body: string;
};

/** صفٌّ من جدول `faq` كما يُقرأ من القاعدة. */
export type FaqRow = { question: string; answer: string };

/**
 * معرفةُ ديبو كما تُقرأ من القاعدة في الطلب الواحد — الجدولان معًا.
 * تُمرَّر ككتلةٍ واحدة كي لا يُنسى أحدُهما في مِنفذٍ ويُذكَر في آخر.
 */
export type DeeboKnowledge = {
  faq: readonly FaqRow[];
  facts: readonly KnowledgeChunk[];
};

/** يحوّل صفوف جدول الأسئلة الشائعة إلى مقاطع معرفة. */
export function faqToChunks(rows: readonly FaqRow[]): KnowledgeChunk[] {
  return rows.map((row, i) => ({
    slug: `faq-${i + 1}`,
    title: row.question,
    body: row.answer,
  }));
}

/**
 * يجمع المعرفة كلّها في كتلةٍ واحدة تُحشى في التوجيه.
 *
 * الحشوُ كلُّه في كلّ سؤالٍ مقصود لا كسل: المعرفة كلُّها نحو ستّة آلاف رمز،
 * ونافذةُ النماذج مليون. فالبحثُ الشعاعيّ (pgvector) آلةٌ لا يحتاجها هذا الحجم،
 * ولا تُنصَّب قبل أن يتجاوز الجسمُ خمسين مقطعًا.
 */
export function buildKnowledge(k: DeeboKnowledge): string {
  const chunks = [...faqToChunks(k.faq), ...k.facts];
  return chunks
    .map((c) => `### ${c.title}\n(${c.slug})\n${c.body}`)
    .join("\n\n");
}

/** نصُّ المعرفة خامًا، لتغذية حارس الأرقام بما يُسمح به. */
export function knowledgeText(k: DeeboKnowledge): string {
  return buildKnowledge(k);
}
