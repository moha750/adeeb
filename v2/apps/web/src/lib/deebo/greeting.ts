/**
 * **تحيّةُ ديبو : جملةٌ تُركَّب لا جملةٌ محفورة.**
 *
 * طلب المالك ٢٠٢٦-٠٨-٢٠ ما يفعله GPT وClaude: أن يُرحَّب بك ترحيبًا مختلفًا في كلّ مرّة.
 * وكانت `GREETING` سطرًا واحدًا يُقال لكلّ زائرٍ في كلّ زيارة، فصارت **صدرًا وعجُزًا**
 * يُركَّبان: صدرٌ يعرف ساعتَه ومَن يخاطب، وعجُزٌ يدعوه إلى السؤال.
 *
 * ## والكلماتُ كلماتُه، والصيغةُ صيغتُه
 * عُرضت عليه نبرتان (فصحى ليّنة · لهجةٌ خفيفة) في `/ui/deebo-greeting` فاختار **اللهجة**
 * و**أعدمت الفصحى**، ثمّ **كتب الصباحَ بيده** وقال: «عدّلت على الصيغة لتعتمدها نفسَها لكلّ
 * الأوقات». فما ههنا لم يعد مسوّدةً مقترَحة: صدورُ الصباح وأعجازُه كما كتبها حرفًا بحرف،
 * وصدورُ المساء والليل مصوغةٌ على قالبه. **لا تُبدَّل كلمةٌ منها إلّا بكلمةٍ منه.**
 *
 * ## وفي تعديله ثلاثةُ أحكامٍ في التركيب لا في الذوق
 *  1. **الاسمُ يلتصق بالصدر بلا فاصلةٍ قبله**: «صباح الخير محمّد» لا «صباح الخير، محمّد».
 *  2. **والفاصلةُ بعد الاسم**، فالتحيّةُ **جملةٌ واحدةٌ** تجري لا جملتان تقفان: «صباح الخير
 *     محمّد، وش ودّك تعرف عن أديب؟» وكانت «صباح الخير، محمّد. ...» فقُرئت رسميّةً باردة.
 *  3. **وعلامةُ الختام في العجُز لا في الصدر**: صدرٌ كان يستفهم («ما نمت؟») صار خبرًا
 *     («آخر الليل وما نمت»)، والعجُزُ هو الذي يسأل. فسقط عَلَمُ `ask` وقام مكانه `ya`.
 *  4. **و`ya` لأنّ بعضَ الصدور تنادي**: «صاحي مبكّر اليوم **يا** محمّد» ولا يقال «صاحي
 *     مبكّر اليوم محمّد». وهي صفةُ الصدر نفسِه، فلا تُخمَّن في موضع التركيب.
 *
 * ## والوجهُ يتبدّل بتبدّلها (٢٠٢٦-٠٨-٢٠)
 * «اجعل أيقونة ديبو تتفاعل مع كلّ ترحيبٍ حسب الترحيب» — فصار **لكلّ صدرٍ وجهُه**:
 * «صاحي مبكّر اليوم» يتفاجأ، و«آخر الليل وما نمت» ينعس، و«مسّاك الله بالخير» يضمّ كفّيه.
 * والوجهُ صفةُ **الصدر** لا صفةُ العجُز، لأنّ الصدرَ هو الذي يعرف ساعتَه ويلتفت إلى حالك.
 *
 * **وقرعةٌ واحدةٌ تُخرجهما معًا**: لو سُحب الوجهُ سحبةً ثانيةً لوقع نعسانَ الوجه على
 * «صباح الخير»، فتكذب الصورةُ على الجملة. ولذلك صار خَرْجُ `pickGreeting` **جملةً ووجهًا**
 * لا سطرًا. وأسماءُ الوجوه وقائمتُها في `lib/deebo/mood.ts` وحدَه، فلا كتالوجان.
 *
 * ## والتبدّلُ لا يكذب على القارئ
 * الوقتُ من `clubHour` (الرياض لا ساعةُ الخادم)، والاسمُ لا يُذكر إلّا لمن دخل بحسابه،
 * ولا يُقال «أهلًا بعودتك» لمن لم يعُد. فما يتبدّل يتبدّل عن سبب.
 *
 * ## ومطبُّ الترطيب مسدودٌ بالتصميم
 * الاختيارُ **دالّةٌ صافيةٌ من بذرة** (`seed`) لا `Math.random()` في الرسم: الخادمُ يبذر
 * والمتصفّحُ يستنبت البذرةَ نفسَها، فيتطابق الرسمان. ولو رُميت القرعةُ في المكوّن لاختلف
 * ما رسمه الخادمُ عمّا رسمه المتصفّح، وهو عطبُ ترطيبٍ يصرخ في الطرفيّة ولا يُرى في الشاشة.
 */

import type { Mood } from "./mood";

/** أقسامُ اليوم بتوقيت الرياض. ثلاثةٌ لا أكثر: عربيّةُ التحيّة لا تعرف أدقَّ من هذا. */
export type DayPart = "morning" | "evening" | "late";

/**
 * ساعةٌ إلى قسمٍ من اليوم.
 * والحدُّ الثاني عشر هو حدُّ «صباح الخير» في العربيّة، والليلُ ما بعد الحاديةَ عشرةَ مساءً
 * إلى الرابعة فجرًا : ساعةٌ يُستحسن فيها أن تقول التحيّةُ إنّها تعرف كم الوقت.
 */
export const dayPartOf = (hour: number): DayPart =>
  hour >= 23 || hour < 4 ? "late" : hour < 12 ? "morning" : "evening";

/**
 * صدرُ التحيّة : ما قبل الاسم.
 *
 * `ya`: هل يُنادى الاسمُ بعده بـ«يا»؟ («صاحي مبكّر اليوم يا محمّد» / «صباح الخير محمّد»).
 *
 * **ولا يُذكر «أديب» في صدرٍ ألبتّة**: قاعدةُ تركيبٍ لا ذوق. أخرجت أوّلُ قرعةٍ حيّةٍ
 * «أهلًا بك في أديب. ما الذي تودّ معرفته عن أديب؟» : اسمُ النادي مرّتين في سطرٍ واحد.
 * فالعجُزُ يملك الاسمَ وحدَه، ولا يُرصَّع استثناءٌ لكلّ لقاءٍ سيّئ.
 */
type Opener = { text: string; ya?: boolean; mood: Mood };

/**
 * **صدورُ الصباح بخطّه** (٢٠٢٦-٠٨-٢٠)، وصدورُ المساء والليل على قالبها:
 * تحيّةُ وقتٍ · تحيّةُ وقتٍ ثانية · التفاتٌ إلى حاله في هذه الساعة · ترحيبٌ عامّ.
 * والالتفاتُ هو موضعُ الودّ في الصيغة كلِّها، فلا يُنزع من قسمٍ ليستوي بقسم.
 */
const OPENERS: Record<DayPart, readonly Opener[]> = {
  morning: [
    // الرسمُ نفسُه صباحٌ: فنجانٌ في يده وشمسٌ فوق كتفه، فلا وجهَ أصدقُ لـ«صباح الخير».
    { text: "صباح الخير", mood: "good-morning" },
    { text: "صباح النور", mood: "happy" },
    { text: "صاحي مبكّر اليوم", ya: true, mood: "surprised" },
    { text: "هلا والله", mood: "welcome" },
  ],
  evening: [
    // **ولا رسمَ للمساء في التسعة والثلاثين**، فلا يُستعار له صباحٌ بفنجانه ولا ليلٌ
    // بقمره: تلويحةٌ محايدةٌ أصدقُ من وجهٍ يقول ساعةً غيرَ ساعته.
    { text: "مساء الخير", mood: "waving" },
    { text: "مساء النور", mood: "happy" },
    // دعاءٌ يُقال، فكفّان تُضمّان.
    { text: "مسّاك الله بالخير", mood: "grateful" },
    { text: "هلا والله", mood: "welcome" },
  ],
  late: [
    { text: "آخر الليل وما نمت", ya: true, mood: "sleepy" },
    { text: "ساهر لين الحين", ya: true, mood: "tired" },
    // قمرٌ ووسادة: الرسمُ يقول «بهالوقت» من غير أن يُقرأ حرف.
    { text: "هلا فيك بهالوقت", mood: "good-night" },
    { text: "هلا والله", mood: "welcome" },
  ],
};

/**
 * عجُزُ التحيّة : الدعوةُ إلى السؤال، وهي واحدةٌ في كلّ الأوقات. **ستٌّ بخطّه.**
 *
 * ولا يُذكر «أديب» فيه إلّا مرّةً واحدةً على الأكثر (وآخرُها لا يذكره أصلًا، وهو خطُّه).
 * والمقصودُ حراسةُ ألّا يُقال مرّتين في سطرٍ واحد، لا إلزامُ كلّ عجُزٍ بتسميته.
 */
const INVITES: readonly string[] = [
  "شنو تبغى تعرف عن أديب؟",
  "حاب تسألني عن أديب؟",
  "وش ودّك تعرف عن أديب؟",
  "قل لي وش يهمّك في أديب.",
  "اسألني عن أديب وأنا حاضر.",
  "وش تدوّر فيه؟",
];

/**
 * دورةُ القرعة : كم بذرةً تمرّ قبل أن تعود التحيّةُ نفسُها.
 *
 * **والصدورُ الأربعةُ في الأقسام الثلاثة سواءٌ عددًا عن قصد** (لا صدفة): لو اختلفت
 * لاختلفت الدورةُ بين قسمٍ وقسم، وانكسر ضمانُ `nextSeed` في أحدها وحده. فإن زدتَ صدرًا
 * في قسمٍ فزِده في الثلاثة.
 */
export const GREETING_PERIOD = 4 * INVITES.length;

export type GreetingInput = {
  /** بذرةُ القرعة : عددٌ صحيحٌ يُولَد مرّةً في الخادم ويُمرَّر كما هو. */
  seed: number;
  /** ساعةُ الرياض (٠..٢٣) من `clubHour`. */
  hour: number;
  /** الاسمُ الأوّل لصاحب الجلسة، أو `null` للزائر المجهول. */
  name?: string | null;
};

/** التحيّةُ الواحدة كما تنزل إلى الشاشة: ما يُقرأ وما يُرى، من قرعةٍ واحدة. */
export type Greeting = { text: string; mood: Mood };

/**
 * التحيّةُ الواحدة.
 *
 * والقطعتان تُسحبان **ببذرتين مختلفتين** من البذرة الواحدة: لو أُخذتا بالباقي نفسِه
 * لدارتا معًا، فلا يُرى من أربعٍ وعشرين إلّا أربع.
 *
 * **ومن لا اسمَ له تُطوى «يا» معه**: «صاحي مبكّر اليوم، وش ودّك تعرف عن أديب؟» —
 * فالنداءُ بلا منادًى لَحنٌ يُقرأ عطبًا.
 */
export function pickGreeting({ seed, hour, name }: GreetingInput): Greeting {
  const opens = OPENERS[dayPartOf(hour)];
  const s = Math.abs(Math.trunc(seed));
  const open = opens[s % opens.length];
  const invite = INVITES[Math.floor(s / opens.length) % INVITES.length];
  const who = name?.trim();
  return {
    text: `${open.text}${who ? `${open.ya ? " يا " : " "}${who}` : ""}، ${invite}`,
    mood: open.mood,
  };
}

/**
 * بذرةٌ تالية **مضمونةُ الاختلاف** عمّا قبلها.
 *
 * تُنادى عند «محادثةٍ جديدة»: قرعةٌ حرّةٌ تُعيد التحيّةَ نفسَها مرّةً من كلّ أربعٍ وعشرين،
 * وتكرارُها في الضغطة التالية مباشرةً يُقرأ عطبًا لا صدفة. فالخطوةُ من واحدٍ إلى دون الدورة،
 * فلا تساوي صفرًا ولا تُساوي الدورةَ نفسَها : وكلاهما يعيد التحيّةَ كما هي.
 */
export const nextSeed = (seed: number, roll: number = Math.random()): number =>
  seed + 1 + Math.floor(roll * (GREETING_PERIOD - 1));
