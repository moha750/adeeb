/**
 * **وجهُ ديبو — المصدرُ الواحد.**
 *
 * سلّم المالك ٣٩ تفاعلًا مرسومًا للشخصيّة في ٢٠٢٦-٠٨-٢٠، ومِعملُ `scripts/deebo-art.mjs`
 * يخرجها إلى `public/brand/deebo/<الاسم>.webp`. وهذا الملفّ يجيب عن سؤالٍ واحد:
 * **أيُّ وجهٍ في أيّ حال؟** — فلا تقرّره شاشةٌ بيدها ولا تختلف صفحتان في الجواب.
 *
 * ## والوجهُ واقعةٌ تُقرأ لا زينةٌ تدور
 * لم أوزّع التسعةَ والثلاثين على الأجوبة بالقرعة: وجهٌ يتبدّل بلا سببٍ يصير ضجيجًا،
 * ويتعلّم الزائرُ بعد ثلاث رسائلَ أن لا يقرأه. فالمستعمَلُ **خمسةٌ**، لكلٍّ حالٌ يقولها:
 *
 * | الحال | الوجه | لماذا |
 * | --- | --- | --- |
 * | الصفحةُ قبل أن يُسأل | `waving` | تحيّةٌ لا حالة |
 * | يكتب (قبل أوّل حرف) | `thinking` | الرسمُ يقول ما تقوله النبضة |
 * | جوابٌ عاديّ | `explaining` | هو يشرح، وهذا أكثرُ ما يفعل |
 * | «هذا ما لا أعرفه» | `sorry` | اعتذارٌ يليق بجملةٍ تُقال عشرات المرّات يوميًّا |
 * | انتهى البثُّ ولم يصل حرف | `unsure` | حيرةٌ لا حزن: العطبُ فينا لا فيه |
 *
 * والباقي محفوظٌ في المجلّد لِما يأتي (الأخبار · الحالة الفارغة · صفحةُ ٤٠٤ · التهاني)،
 * ولا يُشحن منه إلى المتصفّح إلّا ما تطلبه صفحةٌ بعينها.
 *
 * ## وكشفُ «لا أعرف» مشتقٌّ لا محفور
 * الجملةُ تُقرأ من `UNKNOWN_ANSWER` في `persona.ts` نفسِه، فإذا بدّلها المالك حين يملأ
 * ورقةَ الهويّة تبعه الكشفُ بلا سطرٍ ثانٍ. وهي مقارنةٌ **بصدر الجملة** لا بها كاملةً،
 * لأنّ النموذج قد يزيد عليها. **وخطؤها لا يضرّ**: أسوأُ ما يقع أن يشرح ديبو بوجهٍ
 * شارحٍ جملةَ اعتذار، وهي زلّةٌ تُرى ولا تكذب على أحد.
 */
import { UNKNOWN_ANSWER } from "./persona";

/** الوجوهُ المستعمَلة. أسماؤها أسماءُ الملفّات في `public/brand/deebo`. */
export type Mood = "waving" | "thinking" | "explaining" | "sorry" | "unsure";

export const moodSrc = (mood: Mood): string => `/brand/deebo/${mood}.webp`;

/** وصفُ الوجه لقارئ الشاشة. الصورةُ خبرٌ ثانٍ عن الجواب، فلا تُترك بلا نصّ ولا تُكرّره. */
export const MOOD_ALT: Record<Mood, string> = {
  waving: "ديبو يلوّح مرحّبًا",
  thinking: "ديبو يفكّر",
  explaining: "ديبو يشرح",
  sorry: "ديبو معتذر",
  unsure: "ديبو حائر",
};

/** صدرُ جملة «لا أعرف» — بقدرٍ يكفي للتمييز ولا يطول فيكسره حرفٌ زائد. */
const UNKNOWN_HEAD = UNKNOWN_ANSWER.slice(0, 14);

/**
 * وجهُ الجواب الواحد.
 * @param content نصُّ الجواب كما وصل (قد يكون فارغًا وهو يُبثّ).
 * @param streaming هل ما زال يُكتب؟
 */
export function moodFor(content: string, streaming?: boolean): Mood {
  if (streaming && !content) return "thinking";
  // انقطع البثُّ ولم يصل حرفٌ واحد: جوابٌ خاوٍ لا خطأَ مُعلَن، فالحيرةُ أصدقُ من الشرح.
  if (!content.trim()) return "unsure";
  if (content.trimStart().startsWith(UNKNOWN_HEAD)) return "sorry";
  return "explaining";
}
