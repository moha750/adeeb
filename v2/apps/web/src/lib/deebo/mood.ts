/**
 * **وجهُ ديبو — المصدرُ الواحد.**
 *
 * سلّم المالك ٣٩ تفاعلًا مرسومًا للشخصيّة في ٢٠٢٦-٠٨-٢٠، ومِعملُ `scripts/deebo-art.mjs`
 * يخرجها إلى `public/brand/deebo/<الاسم>.webp`. وهذا الملفّ يجيب عن سؤالٍ واحد:
 * **أيُّ وجهٍ في أيّ حال؟** — فلا تقرّره شاشةٌ بيدها ولا تختلف صفحتان في الجواب.
 *
 * ## والوجهُ واقعةٌ تُقرأ لا زينةٌ تدور
 * لم أوزّع التسعةَ والثلاثين على الأجوبة بالقرعة: وجهٌ يتبدّل بلا سببٍ يصير ضجيجًا،
 * ويتعلّم الزائرُ بعد ثلاث رسائلَ أن لا يقرأه. فالمستعمَلُ **خمسةٌ**، لكلٍّ حالٌ يقولها:
 *
 * | الحال | الوجه | لماذا |
 * | --- | --- | --- |
 * | الصفحةُ قبل أن يُسأل | `waving` | تحيّةٌ لا حالة |
 * | يكتب (قبل أوّل حرف) | `thinking` | الرسمُ يقول ما تقوله النبضة |
 * | جوابٌ عاديّ | `explaining` | هو يشرح، وهذا أكثرُ ما يفعل |
 * | «هذا ما لا أعرفه» | `sorry` | اعتذارٌ يليق بجملةٍ تُقال عشرات المرّات يوميًّا |
 * | انتهى البثُّ ولم يصل حرف | `unsure` | حيرةٌ لا حزن: العطبُ فينا لا فيه |
 * | شريطُ الغرفة العلويّ | `chatting` | وجهُ الاسم في الشريط، اختاره المالك ٢٠٢٦-٠٨-٢٠ |
 *
 * ## ووجوهُ التحيّة ثمانيةٌ فوقها، وهي **قراءةٌ أيضًا لا قرعة**
 * أمر المالك ٢٠٢٦-٠٨-٢٠: «اجعل أيقونة ديبو تتفاعل مع كلّ ترحيبٍ حسب الترحيب». والقاعدةُ
 * لم تنكسر بها: **الوجهُ يقول ما يقوله الصدر** لا ما تقوله القرعة. فإذا قال «صاحي مبكّر
 * اليوم» تفاجأ وجهُه، وإذا قال «آخر الليل وما نمت» نعس، وإذا قال «مسّاك الله بالخير» ضمّ
 * كفّيه. ولذلك **يحمل كلُّ صدرٍ وجهَه** في `greeting.ts` نفسِه: قرعةٌ واحدةٌ تُخرج الكلمةَ
 * والوجهَ معًا، فلا يقعان في خلافٍ كما يقعان لو سُحبا سحبتين.
 *
 * والجردُ كلُّه معروضٌ في `/ui/deebo-greeting`: أربعٌ وعشرون تحيّةً بوجوهها لكلّ وقت.
 *
 * والباقي محفوظٌ في المجلّد لِما يأتي (الأخبار · الحالة الفارغة · صفحةُ ٤٠٤ · التهاني)،
 * ولا يُشحن منه إلى المتصفّح إلّا ما تطلبه صفحةٌ بعينها.
 *
 * ## وكشفُ «لا أعرف» مشتقٌّ لا محفور
 * الجملةُ تنزل من القاعدة (`deebo_persona.unknown_answer`) خاصّيةً إلى الشاشة، فإذا
 * بدّلها المالك من اللوحة تبعه الكشفُ في اللحظة بلا نشر. وهي مقارنةٌ **بصدر الجملة** لا
 * بها كاملةً، لأنّ النموذج قد يزيد عليها. **وخطؤها لا يضرّ**: أسوأُ ما يقع أن يشرح ديبو
 * بوجهٍ شارحٍ جملةَ اعتذار، وهي زلّةٌ تُرى ولا تكذب على أحد.
 */

