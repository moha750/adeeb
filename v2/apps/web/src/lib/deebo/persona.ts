/**
 * شخصيّة ديبو ونصّ توجيهه — **سقالةٌ ههنا، والطبعُ في القاعدة**.
 *
 * كان هذا الملفّ يحمل كلامَ المالك نصًّا (ملأ ورقةَ `v2/المتطلبات/ديبو-الهويّة.md` في
 * ٢٠٢٦-٠٨-٢٠ فنُقلت قراراتُه إليه حرفًا بحرف). ثمّ سأل ٢٠٢٦-٠٨-٢٢: «هل تغني الواجهةُ
 * عن تدريبه بالمحادثة معك؟» — ولم تكن تُغني ما دام طبعُه نصًّا يُنشَر. فهاجر إلى صفٍّ
 * واحدٍ في `deebo_persona` تملؤه شاشةُ `‎/dashboard/deebo/persona`‎ (ترحيل `deebo_08`)،
 * وبقي ههنا ما هو **بنيةٌ لا ذوق**:
 *
 *   • سطرُ الافتتاح والعناوينُ الخمسة وترتيبُها.
 *   • بندُ «لا تجيب إلّا ممّا في معرفتك» — قاعدةُ منعِ الاختلاق، وليست تفضيلًا يُبدَّل
 *     (وجملةُ «لا أعرف» فيه من الصفّ، فهي كلامُه هو).
 *   • موضعُ سطرِ التعريف بصاحب الجلسة، وموضعُ المعرفة في الذيل.
 *
 * وترتيبُ الأجزاء مقصود: الشخصيّة أوّلًا ثمّ الحدود ثمّ المعرفة. والمعرفةُ آخرًا لأنّها
 * أطولُ الأجزاء وأثبتُها، فتقع في ذيل البادئة المخزَّنة مؤقّتًا (prompt caching) فتُقرأ
 * بعُشر ثمنها في كلّ سؤالٍ بعد الأوّل. و`viewerBrief` يقع **قبل المعرفة وبعد الحدود**:
 * فهو أقصرُ الأجزاء وأكثرُها تبدّلًا (يختلف بكلّ زائر)، فلو سبق الحدودَ لَكسر البادئةَ
 * المشتركة على كلّ الزوّار وضاع التخزينُ المؤقّت كلُّه.
 *
 * **ولا رقمَ يُكتب في هذا النصّ ألبتّة**: حارسُ `guard.ts` يبيح للجواب كلَّ عددٍ ورد في
 * التوجيه، فرقمٌ يُكتب للزينة يصير رقمًا مأذونًا في جواب ديبو ويسقط الحارسُ صامتًا.
 * ولذلك المحظوراتُ شُرَطٌ لا قائمةٌ مرقَّمة، وقيدُ `deebo_persona_no_digits` في القاعدة
 * يمنع ما يفلت من الشاشة.
 */

import { buildKnowledge, type DeeboKnowledge } from "./knowledge";

/**
 * حكمٌ من حدوده. **والعنوانُ للمحرّر لا للنموذج**: يُعرَف به الحكمُ في الشاشة وفي سطر
 * الفرق، ولا يُكتب في التوجيه — كلُّ حرفٍ يُرسَل يُنفَق من انتباه النموذج ومن ثمنه.
 */
export type BoundaryRule = { title?: string; body: string; enabled: boolean };

/** الأحكامُ العاملةُ نصًّا كما تدخل التوجيه. */
export const boundariesText = (rules: readonly BoundaryRule[]): string =>
  rules.filter((r) => r.enabled).map((r) => `- ${r.body.trim()}`).join("\n");

/**
 * طبعُ ديبو كما يُقرأ من صفّه الواحد.
 *
 * **ولا قيمةَ افتراضيّةً ههنا**: نسخةٌ في الكود ونسخةٌ في القاعدة تفترقان صامتتَين، ثمّ
 * يُصحَّح النصُّ في الشاشة فيبقى ديبو يقول ما في الملفّ. فإذا تعذّرت القراءةُ رُدَّ الطلبُ
 * (٥٠٣) ولم يُجَب بطبعٍ مخترَع.
 */
export type DeeboPersona = {
  /** «من أنت» — صيغةُ الحديث عن نفسه، وقصّةُ اسمه، وجوابُ «هل أنت إنسان؟». */
  identity: string;
  tone: string;
  /**
   * «حدودك» — **أحكامٌ مفردةٌ لا جدارُ نصّ** (م١٠): لكلٍّ متنُه ومفتاحُ تعطيله. والمعطَّل
   * لا يدخل التوجيه أصلًا، فيُطفَأ حكمٌ ليُعرَف أثرُه بلا حذفه. وبندُها الأوّل (لا تجيب
   * إلّا ممّا في معرفتك) سقالةٌ أدناه لا حكمٌ يُطفأ.
   */
  boundaryRules: readonly BoundaryRule[];
  prohibitions: readonly string[];
  /** ما يقوله حين لا يعرف. يقرؤه معه `mood.ts` ليختار وجهَ الاعتذار. */
  unknownAnswer: string;
  /** أسئلةُ الشاشة الفارغة — زينةُ عرضٍ لا توجيه، فلا تدخل النصّ. */
  suggestedQuestions: readonly string[];
  /** كم منها يُعرض. قرارُ المالك، لا سطرٌ في الكود. */
  shownQuestions: number;
};

/** ما يُعرَض منها فعلًا في الشاشة الفارغة. */
export function shownQuestionsOf(p: DeeboPersona): readonly string[] {
  return p.suggestedQuestions.slice(0, Math.max(0, p.shownQuestions));
}

/** يركّب نصّ التوجيه كاملًا: طبعُه من الصفّ، ومعرفتُه من جدولَيها، والبنيةُ ههنا. */
export function buildSystemPrompt(
  persona: DeeboPersona,
  knowledge: DeeboKnowledge,
  viewerBrief?: string | null,
): string {
  const never = persona.prohibitions.map((p) => `- ${p}`).join("\n");

  return `أنت «ديبو»، مساعدٌ آليّ في موقع نادي أديب الطلّابيّ بجامعة الملك فيصل.

## من أنت
${persona.identity}

## نبرتك
${persona.tone}

## حدودك
- لا تجيب إلّا ممّا في «معرفتك» أدناه. وما ليس فيها قل: ${persona.unknownAnswer}
${boundariesText(persona.boundaryRules)}

## ما لا تفعله أبدًا
${never}

${viewerBrief ? `\n${viewerBrief}\n` : ""}
## معرفتك
هذا كلّ ما تعرفه عن أديب. لا تتجاوزه.

${buildKnowledge(knowledge)}`;
}
