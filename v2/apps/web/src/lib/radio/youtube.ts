/**
 * صورةُ الحلقة **تُستدعى من يوتيوب ولا تُرفع عندنا.**
 *
 * الفريقُ يصنع مصغّرةً لكلّ حلقةٍ لأجل يوتيوب أصلًا، فطلبُ رفعِها ثانيةً عندنا
 * عملٌ مكرَّر يُنسى مرّةً فتصير القائمةُ نصفَها مزيَّنًا. وباشتقاقها من الرابط:
 *   • لا رفعَ ولا تخزينَ ولا عمودَ في القاعدة.
 *   • وتتبع نفسَها: إن غُيّرت المصغّرةُ على يوتيوب تغيّرت عندنا بلا أن نُخبَر.
 *
 * والنسبةُ ١٦:٩ فلا تُحشَر في مربّع (الشعارُ المربّع يبقى للشريط والرفّ) —
 * وهو عينُ ما قيل يوم أُلغي غلافُ الحلقة: العنوانُ المكتوبُ فيها يُقصّ ويتكرّر.
 *
 * وهنا **المعرّف وحده**؛ أمّا عنوانُ المصغّرة فيبنيه مكوّنُ `YoutubeThumb` (في
 * `app/radio/_player/`) لأنّه وحدَه يملك التراجع: يطلب `maxresdefault` أوّلًا،
 * فإن لم تكن للفيديو دقّةٌ عالية ردّ يوتيوب صورةَ عطبٍ رماديّة، فيهبط بـ`onError`
 * إلى `hqdefault` المضمونةِ لكلّ فيديو. وذاك تراجعٌ لا تقدر عليه دالّةٌ تردّ نصًّا.
 */

/** معرّفُ الفيديو من أشكال الروابط الثلاثة، أو `null` إن لم يكن رابطَ يوتيوب. */
export function youtubeId(url: string | null | undefined): string | null {
  if (!url) return null;
  const m =
    /(?:youtu\.be\/|youtube\.com\/(?:watch\?(?:.*&)?v=|embed\/|live\/|shorts\/))([A-Za-z0-9_-]{11})/.exec(url);
  return m?.[1] ?? null;
}

/**
 * عنوانُ المصغّرة **المضمونة** — `hqdefault` موجودةٌ لكلّ فيديو مهما كانت دقّةُ
 * مصدره، بخلاف `maxresdefault`.
 *
 * ومسكنُها هنا لأنّ لها قارئًا ثانيًا لا يقدر على التراجع: **وسمُ المشاركة**
 * (`openGraph.images`). فالمكوّنُ يجرّب العاليةَ ويهبط بـ`onError` لأنّه في
 * متصفّح، أمّا الوسمُ فيُكتَب مرّةً ويُقرأ في واتساب وإكس بلا فرصةِ تصحيح —
 * فبطاقةٌ صغيرةٌ مضمونةٌ خيرٌ من مربّعٍ فارغٍ في نصف الحلقات.
 */
export const youtubeThumb = (id: string) => `https://i.ytimg.com/vi/${id}/hqdefault.jpg`;
