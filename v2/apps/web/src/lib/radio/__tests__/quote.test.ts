import { describe, it, expect } from "vitest";
import { bestSentence, isEcho, isStandalone, pullQuote } from "../quote";

/**
 * اختباراتُ الجملة الدالّة — النصوصُ أدناه **مقتطَعةٌ من حلقات منعطف الحقيقيّة**
 * كما هي في القاعدة، فما يمرّ هنا هو ما سيُعرَض فعلًا.
 */
describe("isStandalone", () => {
  it("ترفض ما بدأ بإشارةٍ إلى غائبٍ لم يُذكَر", () => {
    expect(isStandalone("ولذلك فإن الفرق بين الحلم والواقع ليس مسافة بل استمرار")).toBe(false);
    expect(isStandalone("وهذا الشيء يذكرني بمقولة قالها أحد الفلاسفة عن معرفة النفس")).toBe(false);
  });

  it("ترفض ما فيه رقمٌ أو اقتباسٌ عن غيرنا", () => {
    expect(isStandalone("قضى الإنسان 20 سنة يبحث عن الأجوبة في الخارج ولم يجدها")).toBe(false);
    expect(isStandalone('قال يونغ: "من ينظر إلى الخارج يحلم ومن ينظر إلى الداخل يستيقظ"')).toBe(false);
  });

  it("ترفض القصيرَ والطويل", () => {
    expect(isStandalone("الحلم لا يكفي")).toBe(false);
    expect(isStandalone("ا".repeat(200))).toBe(false);
  });

  it("تقبل جملةً تامّةً في المدى", () => {
    expect(isStandalone("الفرق بين الحلم والواقع ليس مسافة، بل الاستمرار في السير")).toBe(true);
  });
});

describe("bestSentence", () => {
  it("تنتقي جملةَ الأطروحة من فقرةٍ حقيقيّة", () => {
    const t =
      "ربما يلعب كل ذلك دورًا. لكن هناك شيء أهم من هذا كله وهو الاستمرار.\n" +
      "الفرق بين الحلم والواقع ليس مسافة، بل الاستمرار في السير معه.\n" +
      "ولذلك فإن كل إنجاز عظيم كان في مرحلة ما مجرد خطوات صغيرة لم يلاحظها أحد.";
    expect(bestSentence(t)).toBe("الفرق بين الحلم والواقع ليس مسافة، بل الاستمرار في السير معه");
  });

  it("تتجاوز الأسئلةَ المفتوحة", () => {
    const t = "كيف أكتشف ما بداخلي من مواهب؟ معرفة النفس ليست حدثًا مفاجئًا، ولا إجابة نجدها في يوم واحد.";
    expect(bestSentence(t)).toBe("معرفة النفس ليست حدثًا مفاجئًا، ولا إجابة نجدها في يوم واحد");
  });

  it("ثابتةٌ: النصُّ نفسُه يعطي الجملةَ نفسَها", () => {
    const t = "الالتزام أحيانًا هو السبب في الاستمرار وليس الشغف وحده كما يقال دائمًا. النجاح أحيانًا في أن تعرف كيف تستفيد مما بين يديك.";
    expect(bestSentence(t)).toBe(bestSentence(t));
  });

  it("ترجع null حين لا تصلح جملة", () => {
    expect(bestSentence("قصير. جدا. لا شيء.")).toBeNull();
    expect(bestSentence(null)).toBeNull();
    expect(bestSentence("")).toBeNull();
  });
});

describe("pullQuote", () => {
  it("يدُ المحرّر تسبق كلَّ شيء", () => {
    expect(pullQuote({ pullQuote: "جملةٌ اختارها المحرّر", transcript: "الفرق بين الحلم والواقع ليس مسافة، بل الاستمرار في السير" }))
      .toBe("جملةٌ اختارها المحرّر");
  });

  it("ثمّ التفريغ", () => {
    expect(pullQuote({ transcript: "الفرق بين الحلم والواقع ليس مسافة، بل الاستمرار في السير معه", summary: "ملخّصٌ عن الحلقة" }))
      .toBe("الفرق بين الحلم والواقع ليس مسافة، بل الاستمرار في السير معه");
  });

  it("ثمّ الملخّص، وهو خلَفٌ لا أصل", () => {
    expect(pullQuote({ transcript: "قصير.", summary: "ملخّصٌ عن الحلقة" })).toBe("ملخّصٌ عن الحلقة");
  });

  it("وnull حين لا شيء", () => {
    expect(pullQuote({})).toBeNull();
  });
});

/** حالاتٌ رُصدت على الإنتاج ٢٠٢٦-٠٨-٢٨ فخرجت شظايا. */
describe("ما رُصد حيًّا", () => {
  it("ترفض أداةَ النصب ولو كُتبت بلا همزة", () => {
    expect(isStandalone("لان الموهبة لا تنمو في لحظة إدراكها فقط بل تنمو في كل مرة")).toBe(false);
    expect(isStandalone("أن الموهبة أو الهواية ليست مجرد شيء تستمتع بممارسته في وقتك")).toBe(false);
  });

  it("ترفض ما فيه حذفٌ، فهو يقول إنّ ثمّة ما نُزع", () => {
    expect(isStandalone("الموهبة لا تنمو في لحظة… بل تنمو في كل مرة تستخدم فيها ولو قليلا")).toBe(false);
    expect(isStandalone("الموهبة لا تنمو في لحظة... بل تنمو في كل مرة تستخدم فيها ولو قليلا")).toBe(false);
  });

  it("ترفض ما طال عن لوحٍ يُقرأ", () => {
    expect(isStandalone("ا".repeat(140))).toBe(false);
  });
});

describe("isEcho", () => {
  it("تمسك صياغتين لمعنًى واحد", () => {
    expect(isEcho(
      "سؤال يبدو بسيطًا، لكنه من أصعب الأسئلة التي قد يواجهها الشخص في حياته",
      "سؤال يبدو بسيطًا، لكنه من أصعب ما يواجهه الإنسان في حياته",
    )).toBe(true);
  });

  it("تُفرّق بين فكرتين متجاورتين", () => {
    expect(isEcho(
      "الفرق بين الحلم والواقع ليس مسافة، بل الاستمرار في السير",
      "الحلم وحده لا يكفي، فبين الحلم والواقع طريق طويل من العمل والتعلم والتجربة",
    )).toBe(false);
  });

  it("لا تحكم على القصير ولا على الفارغ", () => {
    expect(isEcho("كلمتان فقط", "كلمتان فقط")).toBe(false);
    expect(isEcho(null, "نص")).toBe(false);
    expect(isEcho("نص", null)).toBe(false);
  });
});
