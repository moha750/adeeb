/**
 * **الجملةُ الدالّة** — أطروحةُ واجهة المحطّة: الحلقةُ تُعرَّف بجملةٍ من كلامها
 * لا بمربّعٍ مصوَّر.
 *
 * ولمَ هذا أصلًا؟ لأنّ كلَّ منصّات البودكاست تعرّف الحلقةَ بغلاف، ونحن نملك ما
 * لا تملكه: **نصَّ كلِّ حلقةٍ مكتوبًا كاملًا** في `radio_episodes.transcript`
 * (قِيس ٢٠٢٦-٠٨-٢٨: ٦٣١٤ و١٢١٦٧ و١٢٤٠٥ حرفًا للحلقات الثلاث). فالجملةُ تولد مع
 * كلّ حلقةٍ مجّانًا، وتحلّ **مئةَ برنامجٍ بلا مئةِ غلافٍ مصمَّم**.
 *
 * ══ ثلاثةُ مصادرَ بترتيبها ══
 *   ١. ما اختاره المحرّرُ بيده (عمودٌ ينتظر ترحيلًا، ويُمرَّر هنا حين ينزل).
 *   ٢. أفضلُ جملةٍ تُنتقى من التفريغ بقواعدَ صريحةٍ أدناه.
 *   ٣. الملخّص، وهو خلَفٌ لا أصل: مكتوبٌ *عن* الحلقة لا *منها*.
 *
 * ══ ولمَ لا تُترَك للمحرّر وحدَه؟ ══
 * لأنّ حقلًا يُملأ يدويًّا في كلّ حلقةٍ يُنسى، ومحطّةٌ بمئة برنامجٍ لا تحتمل
 * سطحًا يسقط كلّما نسي أحدُهم. فالانتقاءُ هو الأصلُ العامل، واليدُ تنقضه.
 *
 * ══ قواعدُ الانتقاء، ولمَ هي هذه ══
 * جملةٌ تُقتطَع من وسط كلامٍ متّصلٍ تحتاج ما قبلها لتُفهَم. فتُرفَض:
 *   • ما بدأ بحرف عطفٍ أو ضميرٍ يشير إلى غائبٍ لم يُذكَر (‏«ولذلك»، «فهو»).
 *   • ما بدأ بأداةِ نصبٍ أو شرطٍ، فهو شقُّ جملةٍ لا جملة (‏«أن…»، «لأنّ…»، «إذا…»).
 *     (رُصد على الإنتاج ٢٠٢٦-٠٨-٢٨: خرجت «أنّ الموهبة… ليست مجرّد شيء» شظيّةً.)
 *   • ما فيه سؤالٌ مفتوحٌ يطلب جوابًا لم يأتِ بعد.
 *   • ما قصُر عن أربعين حرفًا (لا تحمل معنًى) أو طال عن مئةٍ وستّين (لا تُقرأ لوحًا).
 *   • ما فيه رقمٌ أو اقتباسٌ منقولٌ عن غيرنا، فالأوّلُ يهرم والثاني ليس كلامَنا.
 * وتُرجَّح: ما حمل بنيةَ أطروحةٍ («ليس… بل»، «الفرقُ بين»، «لا… إلّا»).
 *
 * **وخالصةٌ عمدًا** — لا شبكةَ ولا قاعدة — فتُختبَر وحدَها (`__tests__/quote.test.ts`).
 */
import { toLatinDigits } from "@adeeb/core";
import { normalizeArabic } from "./arabicSearch";

/** أقصرُ ما يحمل معنًى قائمًا بنفسه، وأطولُ ما يُقرأ لوحًا في الصدر. */
const MIN = 40;
const MAX = 132;

/** فواصلُ الجُمَل: نقطةٌ وعلامتا استفهامٍ وتعجّبٍ ومنقوطة، وسطرٌ جديد. */
const ENDERS = /[.؟?!؛\n]+/;

/**
 * بادئاتٌ تجعل الجملةَ معلَّقةً بما قبلها. والعطفُ وحدَه لا يكفي حكمًا — «والفرقُ
 * بين…» جملةٌ تامّة — فالمرفوضُ ما أشار إلى غائبٍ أو نتيجةٍ لم تُذكَر.
 *
 * **والحدُّ `(?=\s|$)` لا `\b`**: حدودُ الكلمة في جافاسكربت معرَّفةٌ على حروف
 * ASCII وحدَها، فلا حدَّ بين حرفٍ عربيٍّ ومسافة، وكان الشرطُ يسقط صامتًا
 * فتمرّ «ولذلك…» (أمسكه الاختبار ٢٠٢٦-٠٨-٢٨).
 */
const DANGLING = /^(?:ولذلك|فلذلك|لذلك|ولهذا|فلهذا|لهذا|ولكن|لكنه|فهو|فهي|وهو|وهي|وهذا|وهذه|هذا|هذه|فههنا|ثم|اي|بمعني|كذلك|ايضا|ومع ذلك|وبعد|فبدا|فصار|حينها|عندها|بعدها|فيها|منها|عنه|عنها|ان|بان|لان|حتي|كي|لكي|اذا|لو|بينما|حيث|وحين|حين|وقد|فقد|وكان|فكان)(?=\s|$)/u;

/** الرقمُ يهرم، والمقتبَسُ عن غيرنا ليس كلامَ الحلقة، والحذفُ يقول «ثمّة ما نُزع». */
const HAS_DIGIT = /\d/;
const QUOTED = /["“”«»]/;
const ELLIPSIS = /(\.\.\.|…)/;

/** بنيةُ أطروحةٍ تُرجَّح: تقول شيئًا وتنفي نقيضَه في نَفَسٍ واحد. */
const THESIS = [/ليس\s.+\sبل\s/u, /لا\s.+\sإلّا\s/u, /الفرق\s+بين/u, /ليست\s.+\sبل\s/u, /مو\s.+\sبل\s/u];

/**
 * جملةٌ تطلب جوابًا لم يأتِ بعدُ لا تصلح لوحًا. وعلامةُ الاستفهام **ابتُلعت مع
 * الفاصل** حين قُطّع النصّ، فالدليلُ الباقي أداةُ الاستفهام في صدر الجملة.
 */
const ASKS = /^(?:هل|كيف|لماذا|ما|من|متي|اين|اي|ا)\s/u;

/**
 * درجةُ الجملة. الأعلى يفوز، والتعادلُ يُحسَم بالأسبق في النصّ فيبقى الاختيارُ
 * ثابتًا لا يتبدّل بين طلبٍ وطلب.
 */
function score(s: string): number {
  let n = 0;
  if (THESIS.some((re) => re.test(s))) n += 10;
  // الطولُ الأمثل بين ستّين ومئةٍ وعشرين: يملأ اللوحَ ولا يفيض عنه
  if (s.length >= 60 && s.length <= 120) n += 4;
  else if (s.length <= 140) n += 2;
  // فاصلةٌ واحدةٌ تعني جملتين متوازنتين، وأكثرُ من ثلاثٍ تعني سردًا
  const commas = (s.match(/[،,]/g) ?? []).length;
  if (commas >= 1 && commas <= 2) n += 2;
  if (commas > 3) n -= 3;
  return n;
}

/** أهي جملةٌ تصلح أن تقف وحدَها؟ */
export function isStandalone(raw: string): boolean {
  const s = raw.trim();
  if (s.length < MIN || s.length > MAX) return false;
  if (HAS_DIGIT.test(toLatinDigits(s))) return false;
  if (QUOTED.test(s)) return false;
  if (ELLIPSIS.test(s)) return false;
  /* **يُفحَص المطبَّعُ لا الخام**: النصوصُ تُكتب بهمزةٍ وبغيرها («لأن» و«لان»)،
     فكانت القائمةُ تمسك إحدى الصورتين وتُفلت الأخرى (رُصد على الإنتاج
     ٢٠٢٦-٠٨-٢٨). والتطبيعُ من مصدره الواحد `arabicSearch`. */
  const n = normalizeArabic(s);
  if (DANGLING.test(n)) return false;
  if (ASKS.test(n)) return false;
  return true;
}

/**
 * أفضلُ جملةٍ في نصٍّ، أو `null` إن لم تصلح واحدة. **خالصةٌ وثابتة**: النصُّ
 * نفسُه يعطي الجملةَ نفسَها دائمًا.
 */
export function bestSentence(text: string | null | undefined): string | null {
  if (!text) return null;
  const parts = text.split(ENDERS).map((p) => p.replace(/\s+/g, " ").trim());
  let best: string | null = null;
  let bestScore = -Infinity;
  for (const raw of parts) {
    if (!isStandalone(raw)) continue;
    const sc = score(raw);
    if (sc > bestScore) {
      bestScore = sc;
      best = raw;
    }
  }
  return best;
}

/** الحلقةُ كما تحتاجها هذه الوحدة، لا أكثر. */
export type QuoteSource = {
  transcript?: string | null;
  summary?: string | null;
  /** ما اختاره المحرّرُ بيده. عمودٌ ينتظر ترحيلًا، ويُمرَّر هنا يومَ ينزل. */
  pullQuote?: string | null;
};

/** الجملةُ الدالّة للحلقة: يدُ المحرّر، ثمّ التفريغ، ثمّ الملخّص. */
export function pullQuote(e: QuoteSource): string | null {
  const hand = e.pullQuote?.trim();
  if (hand) return hand;
  const picked = bestSentence(e.transcript);
  if (picked) return picked;
  const summary = e.summary?.trim();
  return summary || null;
}
