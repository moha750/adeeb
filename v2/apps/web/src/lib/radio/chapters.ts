/**
 * **محاورُ الحلقة تُنقَر** — وتُشتقّ من `notes` ولا عمودَ لها في القاعدة.
 *
 * ولمَ لا عمود؟ لأنّ المحرّر يكتب قائمةَ المحاور **مرّتين أصلًا**: عندنا في
 * «محاور الحلقة»، وفي وصف الفيديو على يوتيوب حيث يقرؤها يوتيوب فيصنع فصولًا.
 * فطلبُ إدخالٍ ثالثٍ في اللوحة عملٌ يُنسى، وعمودٌ ثالثٌ يفارق أخويه. وباشتقاقها
 * من النصّ الذي يُكتب على كلّ حال: **لا ترحيلَ ولا حقلَ جديد ولا خطوةَ نشرٍ
 * زائدة**، ومن كتب الأوقاتِ ليوتيوب نالها عندنا مجّانًا.
 *
 * وهو عينُ ما تفعله أكبرُ شبكةٍ عربيّة: «فنجان» تضع المحاورَ موقّتةً في وصف
 * يوتيوب وفي خلاصتها، ‏٥٧٪ من حلقاتها معها.
 *
 * ══ وما الذي يُقرأ ══
 * الوقتُ **في أوّل السطر أو في آخره**، لأنّ يوتيوب يقبل الوجهين وشيوخُ الصنعة
 * يكتبون بالوجهين: «فنجان» تقدّم الوقتَ بين قوسين، و«سقراط» تؤخّره بعد العنوان
 * العربيّ (وهو الترتيبُ الطبيعيّ في سطرٍ عربيّ). فلو قُبل وجهٌ واحدٌ لسقط نصفُ
 * ما يُكتب صامتًا.
 *
 * والصيغُ: `m:ss` و`mm:ss` و`h:mm:ss`، بأقواسٍ أو بغيرها، وبأرقامٍ عربيّةٍ أو
 * لاتينيّة (يُحوَّل عربيُّها قبل القراءة، وهو ما تفعله بقيّةُ الحقول).
 *
 * ══ وقاعدةُ الكلّ أو لا شيء ══
 * إن لم يحمل **كلُّ** سطرٍ ذي محتوًى وقتًا فلا محاور، ويُعرَض النصُّ كما كُتب.
 * فقائمةٌ نصفُها أزرارٌ ونصفُها سطورٌ ميّتة تُقرأ عطلًا لا تصميمًا، والمحرّرُ
 * الذي نسي وقتًا واحدًا لا يُعاقَب بواجهةٍ مكسورة.
 *
 * والأوّلُ يجب أن يكون صفرًا أو قريبًا منه، وهو شرطُ يوتيوب نفسُه: قائمةٌ تبدأ
 * من الدقيقة الرابعة تترك أوّلَ الحلقة بلا باب.
 */
import { toLatinDigits } from "@adeeb/core";

export type Chapter = { at: number; title: string };

/** أقلُّ ما يُعَدّ قائمةَ محاور. اثنان محورٌ ومحور، وسطرٌ واحدٌ ليس قائمة. */
const MIN_CHAPTERS = 2;

/** يبدأ من الصفر أو يقاربه، وإلّا فأوّلُ الحلقة بلا باب. */
const MAX_FIRST_START = 30;

/* الوقتُ في الطرفين: بأقواسٍ أو مربّعاتٍ أو عاريًا، ويليه العنوانُ أو يسبقه.
   والفواصلُ بينهما مسافةٌ أو شرطةٌ أو نقطتان، فتُنزَع مع ما حولها. */
const LEAD = /^[[(]?\s*(\d{1,2}(?::\d{1,2}){1,2})\s*[\])]?\s*[-–:—.]?\s*(.+)$/;
const TRAIL = /^(.+?)\s*[-–:—.]?\s*[[(]?\s*(\d{1,2}(?::\d{1,2}){1,2})\s*[\])]?$/;

/** `m:ss` أو `h:mm:ss` إلى ثوانٍ. و`null` لما لا يصحّ (‏`99:99`). */
export function parseTimestamp(raw: string): number | null {
  const parts = raw.split(":").map((p) => Number(p));
  if (parts.some((n) => !Number.isInteger(n) || n < 0)) return null;
  const [h, m, s] = parts.length === 3 ? parts : [0, parts[0]!, parts[1]!];
  if (m! > 59 || s! > 59) return null;
  return h! * 3600 + m! * 60 + s!;
}

/**
 * محاورُ الحلقة من نصّها، أو `null` إن لم تكن قائمةً موقّتة.
 * و`null` لا `[]`: الفرقُ بين «لا محاور» و«محاورُ صفر» هو ما يقرّر أيُعرَض النصّ
 * كما كُتب أم تُرسَم الأزرار.
 */
export function parseChapters(notes: string | null | undefined): Chapter[] | null {
  if (!notes) return null;
  const lines = toLatinDigits(notes)
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean);
  if (lines.length < MIN_CHAPTERS) return null;

  const out: Chapter[] = [];
  for (const line of lines) {
    const m = LEAD.exec(line) ?? TRAIL.exec(line);
    if (!m) return null; // سطرٌ بلا وقت: القائمةُ ليست محاورَ، فتُعرَض نصًّا
    const [rawTime, rawTitle] = LEAD.test(line) ? [m[1]!, m[2]!] : [m[2]!, m[1]!];
    const at = parseTimestamp(rawTime);
    const title = rawTitle.trim();
    if (at === null || !title) return null;
    out.push({ at, title });
  }

  if (out.length < MIN_CHAPTERS) return null;
  if (out[0]!.at > MAX_FIRST_START) return null;
  // تصاعديٌّ صارم: أرقامٌ تتراجع تعني أنّ ما قُرئ وقتًا ليس وقتًا (‏رقمُ آيةٍ مثلًا).
  for (let i = 1; i < out.length; i++) if (out[i]!.at <= out[i - 1]!.at) return null;
  return out;
}
