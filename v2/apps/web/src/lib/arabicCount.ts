/**
 * **المعدودُ بالعربيّة — مصدرٌ واحد.**
 *
 * كانت القاعدةُ محبوسةً في `duration.ts` دالّةً خاصّةً (`ar`)، فلمّا احتاجها عدُّ
 * الكلمات والأسطر كان الخياران: نسخُها (توأمٌ يفترق يومًا) أو رفعُها. ورُفعت —
 * وهي السابقةُ نفسُها التي رُفعت بها `arDuration` من `SurveyStatusLine`.
 */

/**
 * الصيغُ الأربع بترتيبها: **[مفرد · مثنّى · جمع ٣–١٠ · مفرد منصوب ١١+]**.
 *
 * والمفردُ والمثنّى **يحملان لفظَهما بلا رقم** («كلمةٌ واحدة» لا «1 كلمة»)، فالعربيّةُ
 * تُغني بصيغتها عن العدد. وما بعدهما يسبقه الرقم.
 */
export type ArForms = readonly [string, string, string, string];

/**
 * «كلمةٌ واحدة» · «كلمتان» · «٥ كلمات» · «٣٧ كلمةً».
 *
 * **ولا يُلبَس الرقمُ `dir="ltr"` ولا صنفَ `lat`**: أرقامُ اللاتينيّة مُعادٌ تعريفُها
 * داخل عائلة `Lyon Arabic` نفسِها لتُرسَم بـEras (انظر `fonts.css`)، فالرقمُ وسط
 * الجملة العربيّة يخرج بخطّه الصحيح ولا يحتاج عزلًا. والعزلُ هنا يضرّ: يقطع الجملةَ
 * فقرتين ويُدخل فجوةً تُرى.
 */
/**
 * **ما فوق المئة يُحكم بآخر رقمين** (٢٠٢٦-١١-٢٤: كانت «103 متطوّعًا» والصوابُ «103 متطوّعين»): الحكمُ كان بالعدد كلِّه، فكلُّ
 * ما فوق العشرة منصوبٌ مفرد. والعربيّةُ تُعطي المعدودَ صيغةَ آخر رقمين: 3–10 جمعٌ («103 متطوّعين»)، و11–99 مفردٌ منصوب
 * («150 متطوّعًا»)، وما سواهما مفردٌ مجرور بالإضافة («100 متطوّعٍ»، «101 متطوّع») — وهو المنصوبُ بلا تنوينه (`bare`).
 */
const bare = (w: string): string => w.replace(/\u064B\u0627(?=\s|$)/g, "").replace(/\u064B(?=\s|$)/g, "");
/** صيغةُ المعدود بعد رقمٍ فوق الاثنين: من آخر رقمين فيه */
const formOf = (n: number, f: ArForms): string => {
  const m = n >= 100 && Number.isInteger(n) ? n % 100 : n;
  if (n >= 100 && m <= 2) return bare(f[3]);
  return m < 11 ? f[2] : f[3];
};

export const arCount = (n: number, f: ArForms): string =>
  n === 1 ? f[0] : n === 2 ? f[1] : `${n} ${formOf(n, f)}`;

/**
 * **صيغةُ المعدود وحدَها تحت رقمٍ يُكتب مستقلًّا** (كرتُ إحصاء: الرقمُ كبيرٌ وتحته اسمُه): «4» ثمّ «مقاعدُ مشغولة»،
 * «1» ثمّ «مقعدٌ مشغول»، «12» ثمّ «مقعدًا مشغولًا». والصيغُ هنا **بلا لفظ «واحد»** فالرقمُ فوقها يقوله.
 * والصفرُ والكسورُ دون العشرة تأخذ الجمع («0 ساعات»، «7.5 ساعات») كما يُقال.
 */
export const arCounted = (n: number, f: ArForms): string =>
  n === 1 ? f[0] : n === 2 ? f[1] : formOf(n, f);

