/**
 * **المعدودُ بالعربيّة — مصدرٌ واحد.**
 *
 * كانت القاعدةُ محبوسةً في `duration.ts` دالّةً خاصّةً (`ar`)، فلمّا احتاجها عدُّ
 * الكلمات والأسطر كان الخياران: نسخُها (توأمٌ يفترق يومًا) أو رفعُها. ورُفعت —
 * وهي السابقةُ نفسُها التي رُفعت بها `arDuration` من `SurveyStatusLine`.
 */

/**
 * الصيغُ الأربع بترتيبها: **[مفرد · مثنّى · جمع ٣–١٠ · مفرد منصوب ١١+]**.
 *
 * والمفردُ والمثنّى **يحملان لفظَهما بلا رقم** («كلمةٌ واحدة» لا «1 كلمة»)، فالعربيّةُ
 * تُغني بصيغتها عن العدد. وما بعدهما يسبقه الرقم.
 */
export type ArForms = readonly [string, string, string, string];

/**
 * «كلمةٌ واحدة» · «كلمتان» · «٥ كلمات» · «٣٧ كلمةً».
 *
 * **ولا يُلبَس الرقمُ `dir="ltr"` ولا صنفَ `lat`**: أرقامُ اللاتينيّة مُعادٌ تعريفُها
 * داخل عائلة `Lyon Arabic` نفسِها لتُرسَم بـEras (انظر `fonts.css`)، فالرقمُ وسط
 * الجملة العربيّة يخرج بخطّه الصحيح ولا يحتاج عزلًا. والعزلُ هنا يضرّ: يقطع الجملةَ
 * فقرتين ويُدخل فجوةً تُرى.
 */
export const arCount = (n: number, f: ArForms): string =>
  n === 1 ? f[0] : n === 2 ? f[1] : n >= 3 && n <= 10 ? `${n} ${f[2]}` : `${n} ${f[3]}`;

/* ── صيغٌ متكرّرةٌ تُعلَن مرّةً ─────────────────────────────────────────────── */

export const AR_WORD: ArForms = ["كلمةٌ واحدة", "كلمتان", "كلمات", "كلمةً"];
export const AR_LINE: ArForms = ["سطرٌ واحد", "سطران", "أسطرٍ", "سطرًا"];
export const AR_CATEGORY: ArForms = ["تصنيفٌ واحد", "تصنيفان", "تصنيفات", "تصنيفًا"];
