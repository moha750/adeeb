/**
 * **حارسُ إعادة التوجيه — المصدر الواحد.**
 *
 * `?next=` يأتي من الرابط، أيْ من أيّ أحد. فلو أُخذ كما هو لَصار الرابطُ يقول لبوّابتنا
 * «بعد الدخول اذهب إلى موقعي» — وهي حيلةُ التصيّد المعروفة: يرى الضحيّةُ نطاقَ أديب في
 * شريط العنوان ثمّ يجد نفسَه في صفحةٍ ليست منه، وقد وثق بها لأنّها جاءته من عندنا.
 *
 * فلا يُقبل إلّا **مسارٌ داخليّ**: يبدأ بشرطةٍ مائلة واحدة لا اثنتين — و`//evil.com` مسارٌ
 * في عين القراءة السريعة، وعنوانٌ كاملٌ في عين المتصفّح (بروتوكولٌ ضمنيّ). هذا هو الفخّ.
 *
 * وكان مكتوبًا **مرّتين** (شاشةُ الدخول وعودةُ المزوّد) — ولو صُلّب أحدُهما يومًا وبقي الآخر
 * لَظنّ القارئُ البابَ محروسًا وله بابٌ ثانٍ مفتوح. فوُحّد ههنا: نقيٌّ من الخادم والعميل معًا.
 *
 * **والوجهةُ الافتراضيّة `/dashboard` قرارٌ لا كسل**: هي مفترقُ الطرق — تسوق العضوَ إلى لوحته،
 * وصاحبَ الحساب إلى بيته `/me`، وناقصَ السجلّ إلى `/complete`. فمن لا وجهةَ له تُختار له.
 */
export function safeNext(raw: string | null | undefined): string {
  if (raw && raw.startsWith("/") && !raw.startsWith("//")) return raw;
  return "/dashboard";
}
