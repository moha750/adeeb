/**
 * **تحيّةُ الساعة — مصدرٌ واحد** لرئيسيّة البوّابة (`PortalHome`) وبابها (`/login`) — وحّدهما
 * المالك ٢٠٢٦-١٠-١٩ بعد أن قال البابُ «صباح الخير» ظهرًا والبوّابةُ «مساء الخير».
 * صباحًا من الرابعة إلى الظهر، وما سواه مساء. **ساعةُ الجهاز لا الخادم**: تُستدعى في المتصفّح.
 */
export function greetNow(now: Date = new Date()): "صباح الخير" | "مساء الخير" {
  const h = now.getHours();
  return h >= 4 && h < 12 ? "صباح الخير" : "مساء الخير";
}
