/**
 * **مفرداتُ الجهاز — مصدرٌ واحد، ولغةُ العرض خيار.**
 *
 * القاعدة تخزّن رمزًا آليًّا يكتبه **كودُنا نحن** (`track-pageview` وحفظُ الاستبيان): `mobile` ·
 * `tablet` · `desktop` · `bot` · `unknown`. فهي مجموعةٌ **مغلقةٌ معروفة**، لا اسمًا يرسله مزوّدٌ
 * خارجيّ كأسماء المدن. ولذلك تسميتُها لا تحتاج جدولًا يُصان، بل ترجمةَ خمس كلمات.
 *
 * وكان الرمزُ يُعرض خامًا في موضعين (حلقةُ الأجهزة في التحليلات، وحلقةُ أجهزة المجيبين في نتائج
 * الاستبيانات)، ويُترجَم في موضعٍ ثالث **بثلاثيّةٍ مكتوبةٍ في الشاشة** (عمود «الجهاز» في جدول
 * المشاركات) — وكانت تلك الثلاثيّة تكذب: كلُّ ما ليس جوّالًا ولا لوحيًّا يخرج «حاسوب»، فالمجهولُ
 * يُعرض حاسوبًا. فجُمعت الثلاثة هنا.
 *
 * ومثلُ `lib/geo.tsx`: `locale` افتراضُه العربيّة، فيوم تُضاف الإنجليزيّة للموقع يُمرَّر وسيطٌ
 * ولا يُعاد بناء. وما ليس في الجدول يُعرَض كما هو (نقصٌ ظاهرٌ لا كذبٌ صامت).
 */

export type DeviceLocale = "ar" | "en";

const DEVICES: Record<string, { ar: string; en: string }> = {
  mobile: { ar: "جوّال", en: "Mobile" },
  tablet: { ar: "لوحيّ", en: "Tablet" },
  desktop: { ar: "حاسوب", en: "Desktop" },
  bot: { ar: "روبوت", en: "Bot" },
  unknown: { ar: "غير معروف", en: "Unknown" },
};

/** اسمُ الجهاز باللغة المطلوبة — ورمزٌ لا نعرفه يُعرض كما هو. */
export function deviceName(raw: string | null | undefined, locale: DeviceLocale = "ar"): string {
  const key = (raw ?? "").trim().toLowerCase();
  const hit = DEVICES[key];
  if (hit) return locale === "ar" ? hit.ar : hit.en;
  return (raw ?? "").trim() || (locale === "ar" ? "غير معروف" : "Unknown");
}
