/**
 * **عميلُ المتصفّح عند الحاجة، لا مع الصفحة** (٢٠٢٦-١٠-٢٧، قياسُ جوّالٍ على 4G).
 *
 * مكتبةُ Supabase في المتصفّح ~225KB (~60KB مضغوطة)، وكانت تُحمَّل لكلّ زائرٍ في كلّ صفحةٍ
 * عامّة لأنّ رأسَ الموقع وعدّادَ الزيارات يستوردانها مباشرةً. والزائرُ بلا حساب لا يحتاجها
 * أصلًا: لا جلسةَ تُقرأ ولا جرسَ يُسمَع. فالرأسُ والعدّادُ والجرسُ يطلبونها من هنا، وتُنزَّل
 * حين يُطلب العميلُ أوّلَ مرّة، ولا يُطلب إلّا حيث يدلّ الكوكيُّ على جلسة.
 *
 * ونماذجُ الدخول والتسجيل تبقى تستورد `./client` مباشرةً: هناك العميلُ عملُ الصفحة نفسُه.
 */

/**
 * أثرُ جلسةٍ في الكوكيز — `sb-<ref>-auth-token` (وقد تُشظّى إلى `.0`/`.1` حين تطول).
 * حدسٌ لا حكم: كوكيٌّ بقي بعد انتهاء الجلسة يقول «نعم» والخادمُ يقول «لا»، فالجوابُ
 * الأخير لِمن يسأل الخادم. وفي الخادم لا كوكيز تُقرأ هنا فالجوابُ «لا».
 */
export function hasSessionCookie(): boolean {
  if (typeof document === "undefined") return false;
  return /(?:^|;\s*)sb-[^=;]+-auth-token/.test(document.cookie);
}

/** عميلُ المتصفّح نفسُه (`./client`)، مُحمَّلًا عند أوّل طلب. */
export async function loadClient() {
  const { createClient } = await import("./client");
  return createClient();
}
