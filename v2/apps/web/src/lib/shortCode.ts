/**
 * **أبجديّةُ الرابط** — صغيرةٌ، للرموز التي تُكتَب في عنوانٍ ولا يقرؤها أحدٌ بعينه:
 * لا `0` ولا `o`، ولا `1` ولا `l` ولا `i`. إحدى وثلاثون محرفًا.
 */
export const LINK_ALPHABET = "23456789abcdefghjkmnpqrstuvwxyz";

/**
 * رمزٌ جديد من عشوائيّةِ التعمية لا من `Math.random`: الأخيرةُ تُتوقَّع من مخرجاتها،
 * ورمزٌ متوقَّعٌ يعني أنّ الغريب يقرأ وجهاتِ ملصقاتنا قبل نشرها.
 *
 * ⚠️ **القسمةُ الباقيةُ تُميل الاحتمال** حين لا تقبل ٢٥٦ القسمةَ على طول الأبجديّة
 * (وهي حالُ الإحدى والثلاثين). والميلُ هنا مقبولٌ ومقصود: الرمزُ **معرّفٌ لا مفتاحٌ تعمويّ**،
 * والانحيازُ لا يُقصّر مساحةَ التخمين عمليًّا. فلا تنقل هذه الدالّةَ إلى توليد سرّ.
 */
export function randomCode(len: number, alphabet: string): string {
  const bytes = new Uint8Array(len);
  crypto.getRandomValues(bytes);
  let out = "";
  for (const b of bytes) out += alphabet[b % alphabet.length];
  return out;
}

/**
 * حارسُ شكلٍ لأبجديّةٍ وطولٍ معلومَين. يُبنى التعبيرُ **مرّةً** عند الوحدة لا عند كلّ
 * نداء: الحارسُ يُنادى في طريق كلّ زائرٍ إلى رمز، وبناءُ RegExp هناك ضريبةٌ
 * تُدفع بلا مقابل.
 */
export function codeShapeGuard(len: number, alphabet: string): (code: string) => boolean {
  const re = new RegExp(`^[${alphabet}]{${len}}$`);
  return (code: string) => re.test(code);
}
