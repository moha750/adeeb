export const LINK_ALPHABET = "23456789abcdefghjkmnpqrstuvwxyz";

/**
 * **أبجديّةُ القاعة** — كبيرةٌ، للرموز التي تُقرأ عن بُعدٍ على بروجكتر وتُملى بالصوت
 * وتُكتَب بلوحة مفاتيح هاتف. اثنان وثلاثون محرفًا، **بلا زوجٍ ملتبِس**: تسقط `0` و`O`
 * معًا، وتسقط `1` و`I` معًا. و`L` **باقيةٌ عمدًا** — التباسُها إنّما هو بـ`1` وقد سقطت
 * الأرقامُ دون الاثنين، فلا يبقى لها شبيه. (والنفيُ يقع على الزوج لا على الحرف: حرفٌ
 * لا نظيرَ له لا يلتبس بشيء، ونفيُه يُقصّر مساحةَ الرموز بلا مقابل.)
 *
 * ⚠️ **هذه الأبجديّةُ حيّةٌ في القاعدة** (`guess_word_sessions_code_shape`) وعليها رموزٌ
 * مطبوعة. تبديلُ محرفٍ منها يقتضي ترحيلًا.
 *
 * والكبيرُ هنا ليس ذوقًا: الحرفُ الكبير أوضحُ من بعيدٍ ولا يلتبس ذيلُه بذيل جاره،
 * ولوحةُ مفاتيح الهاتف تفتح على الكبير حين يكون الحقلُ رمزًا.
 */
export const ROOM_ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789";

/**
 * رمزٌ جديد من عشوائيّةِ التعمية لا من `Math.random`: الأخيرةُ تُتوقَّع من مخرجاتها،
 * ورمزٌ متوقَّعٌ يعني أنّ الغريب يقرأ وجهاتِ ملصقاتنا قبل نشرها، ويدخل غرفةً لم يُدعَ إليها.
 *
 * ⚠️ **القسمةُ الباقيةُ تُميل الاحتمال** حين لا تقبل ٢٥٦ القسمةَ على طول الأبجديّة
 * (٣١ نعم، ٣٢ لا). والميلُ هنا مقبولٌ ومقصود: الرمزُ **معرّفٌ لا مفتاحٌ تعمويّ**،
 * والانحيازُ لا يُقصّر مساحةَ التخمين عمليًّا. فلا تنقل هذه الدالّةَ إلى توليد سرّ.
 */
export function randomCode(len: number, alphabet: string): string {
  const bytes = new Uint8Array(len);
  crypto.getRandomValues(bytes);
  let out = "";
  for (const b of bytes) out += alphabet[b % alphabet.length];
  return out;
}

/**
 * حارسُ شكلٍ لأبجديّةٍ وطولٍ معلومَين. يُبنى التعبيرُ **مرّةً** عند الوحدة لا عند كلّ
 * نداء: الحارسُ يُنادى في طريق كلّ زائرٍ إلى غرفةٍ أو رمز، وبناءُ RegExp هناك ضريبةٌ
 * تُدفع بلا مقابل.
 */
export function codeShapeGuard(len: number, alphabet: string): (code: string) => boolean {
  const re = new RegExp(`^[${alphabet}]{${len}}$`);
  return (code: string) => re.test(code);
}
