// نسبةُ الخبر إلى كاتبه — **مصدرٌ واحد** يقرأه الخادمُ والعميلُ معًا (بلا "server-only").
//
// **ولِمَ دالّةٌ لا وصلٌ بفاصلة؟** لأنّ «بريشة» مضافٌ، والمضافُ يتبع عددَ ما أُضيف إليه.
// فكان العارضُ يصل الأسماءَ بفاصلةٍ ويسبقها بالمفرد دائمًا — «بريشة فلان، فلان» —
// وهي جملةٌ لا تصحّ. وفي الأخبار المنشورة خبرٌ بأربعة كتّاب، فالحالةُ واقعةٌ لا مفترضة.
//
// والصيغُ ثلاث:
//   واحدٌ  → «بريشة فلان»
//   اثنان  → «بريشتَي فلان وفلان»      (مثنًّى مضافٌ تسقط نونُه)
//   أكثرُ  → «بِرِيَش فلان وفلان وفلان»  (جمعُ تكسيرٍ مضاف)
//
// **والوصلُ بـ«و» لا بفاصلة:** هذه جملةُ نسبةٍ تُقرأ، لا قائمةَ حقائقَ متجاورة —
// وقاعدةُ الفاصلة عندنا لخبرَين متجاورَين، والأسماءُ ههنا خبرٌ واحد.

const NAMES = { one: "بريشة", two: "بريشتَي", many: "بِرِيَش" } as const;

/**
 * يردّ جملةَ النسبة، أو `null` إن لم يُسمَّ كاتب (فلا يُرسَم الصفُّ أصلًا).
 *
 * والأسماءُ تُنقّى من الفارغ قبل العدّ: مصفوفةٌ فيها سلسلةٌ خاوية كانت تُصيّر
 * الواحدَ اثنين فتخرج «بريشتَي فلان و».
 */
export function bylineOf(authors: readonly (string | null | undefined)[]): string | null {
  const names = authors.map((a) => (a ?? "").trim()).filter(Boolean);
  if (!names.length) return null;

  const word = names.length === 1 ? NAMES.one : names.length === 2 ? NAMES.two : NAMES.many;
  return `${word} ${names.join(" و")}`;
}
