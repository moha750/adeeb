/**
 * **إطاراتُ المنضدة** (قالبُ «مساحة العمل»، ٢٠٢٦-١١-١٣): صفحاتٌ تُحمَّل داخل محرّرٍ في البوّابة لتعرض ما يُحرَّر كما سيُرى —
 * الاستبيانُ كما يراه المشارك (`/frame/survey`)، والخبرُ كما سيُنشر (`/frame/news`). المحرّرُ يرسل إليها مسوّدتَه برسالةٍ من الأصل نفسه.
 *
 * **بادئةٌ واحدة** يسأل عنها كلُّ ما لا مكانَ له داخل إطار: شاشةُ الافتتاح، وعدّادُ الزيارات، ومؤشّرُ الموقع، وحفظُ اشتراك الإشعارات.
 * كان كلٌّ منها يسأل عن `/survey-frame` باسمه، فكان كلُّ إطارٍ جديدٍ أربعةَ مواضعَ تُنسى.
 */
export const STAGE_FRAME_PREFIX = "/frame/";

export const isStageFrame = (path: string | null | undefined) => !!path && path.startsWith(STAGE_FRAME_PREFIX);

/** أسماءُ الرسائل بين المحرّر وإطاره: «أجاهز؟» و«جاهز» و«المسوّدة» — لكلّ إطارٍ اسمُه فلا تلتقي رسائلُ إطارين */
export const stageMsg = (kind: string) => ({
  ping: `${kind}-frame-ping`,
  ready: `${kind}-frame-ready`,
  draft: `${kind}-draft`,
});
