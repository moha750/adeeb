/** تطبيعُ العربيّة للمطابقة: بلا تشكيلٍ ولا تطويل، والهمزاتُ ألفًا، والتاءُ المربوطةُ هاءً، والألفُ المقصورةُ ياءً. */
export function normalizeArabic(s: string): string {
  return s
    .replace(/[ً-ْٰـ]/g, "")
    .replace(/[أإآٱ]/g, "ا").replace(/ة/g, "ه").replace(/ى/g, "ي").replace(/ؤ/g, "و").replace(/ئ/g, "ي")
    .replace(/[^ء-ي\s]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

const DICT = new Map<string, readonly string[]>();
for (const [ar, en] of ENTRIES) for (const w of ar) DICT.set(normalizeArabic(w), en);

/** صيغُ الكلمة المحتملة في القاموس: كما هي، وبلا «ال» وأخواتها، وبلا جمع «ات». */
function forms(w: string): string[] {
  const out = [w];
  const bare = w.replace(/^(وال|بال|فال|كال|لل|ال)(?=.{2,})/, "");
  if (bare !== w) out.push(bare);
  for (const x of [...out]) if (/..ات$/.test(x)) out.push(x.slice(0, -2));
  return out;
}

export const hasArabic = (s: string) => /[؀-ۿ]/.test(s);

/**
 * كلماتُ البحث الإنجليزيّة لاستعلامٍ عربيّ من القاموس، و`missing` إن بقيت فيه كلمةٌ لا يعرفها (فيُسأل عنها
 * الذكاءُ الاصطناعيّ). والعبارةُ كاملةً تُجرَّب قبل كلماتها («كرة قدم»، «ذكاء اصطناعي»).
 */
export function arabicKeywords(query: string): { keywords: string[]; missing: boolean } {
  const q = normalizeArabic(query);
  if (!q) return { keywords: [], missing: false };
  const whole = forms(q).map((f) => DICT.get(f)).find(Boolean);
  if (whole) return { keywords: [...whole], missing: false };
  const keywords: string[] = [];
  let missing = false;
  for (const w of q.split(" ")) {
    const hit = forms(w).map((f) => DICT.get(f)).find(Boolean);
    if (hit) keywords.push(...hit);
    else missing = true;
  }
  return { keywords: [...new Set(keywords)], missing };
}
