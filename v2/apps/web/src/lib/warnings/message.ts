/**
 * نصّ الإنذار — **مصدرٌ واحد** لوجهيه: الخطاب المطبوع على القالب (`letter.ts`) ورسالة
 * واتساب. فما يُقرأ في الورقة هو ما يُقرأ في المحادثة، ولا نصّ ثانٍ ينحرف عن الأوّل.
 *
 * وأصلُه **بوست كانفا** الذي كان يُكتب يدويًّا، أقرّه المالك نبرةً ولفظًا (20260802)، وزِيد
 * عليه ما يعرفه السجلّ ولا تعرفه الورقة القديمة: التاريخ، ونصّ السبب كما كُتب، **والعدّ
 * والعاقبة** — لأنّ العضو صار يرى إنذاراته في «عضويتي»، فسكوتُ الرسالة عمّا يراه بعينه نقص.
 *
 * والنداء **من لقطة الإنذار** لا من حاله اليوم: منصبُه يومَ صدوره (`role_at_issue`) — فالخطاب
 * يبقى صادقًا ولو انتقل صاحبه بعده. **واللجنة لا تُذكر في النصّ** (قرار المالك): تبقى في السجلّ.
 */
import { fmtDate } from "@/lib/date";
import { CHARTER, countWord, observationSentence, ordinalWord } from "./vocab";

export type Gender = "male" | "female" | null;

export type WarningLetter = {
  name: string;
  gender: Gender;
  /**
   * منصبُه ولجنتُه **يوم صدور الإنذار** — لقطةٌ لا حالٌ راهنة. ومنهما يُبنى **سطر النداء وحده**
   * («قائدة لجنة التصميم/ زهراء العريفي»)؛ أمّا متن الخطاب فلا يذكر اللجنة البتّة (قرار المالك).
   */
  role?: string | null;
  committee?: string | null;
  /** رتبةُ الإنذار بين سواري صاحبه — لحظةَ التوليد (البوّابة هي الحقّ، والورقة أثرُ لحظتها). */
  ordinal: number;
  category: string;
  reason: string;
  /** تاريخ الإصدار (ISO). */
  issuedAt: string;
  /** عدد السواري والحدّ — منهما تُقال العاقبة. */
  activeCount: number;
  limit: number;
};

/** اختيارٌ بالجنس — والمجهولُ يأخذ صيغة المذكّر (لا نخترع له جنسًا، ولا نُثقل الجملة بالوجهين). */
const g = (gender: Gender, male: string, female: string): string => (gender === "female" ? female : male);

/** تأنيث الرتبة في النداء: «قائد» ← «قائدة». والرتبةُ أوّلُ كلمةٍ في اسم المنصب. */
const FEMININE: Record<string, string> = {
  "قائد": "قائدة", "نائب": "نائبة", "عضو": "عضوة",
  "منسّق": "منسّقة", "منسق": "منسقة", "رئيس": "رئيسة", "مستشار": "مستشارة",
};

/**
 * سطر النداء — **المسمّى كاملًا بلا فاصل** (قرار المالك): «قائدة لجنة التصميم زهراء العريفي» ·
 * «عضو لجنة الفعاليات حمد السبيعي». وبلا منصبٍ: «الأدِيب فلان» و«الأدِيبة فلانة».
 *
 * واللجنة تُلحَق **إن لم يحملها المسمّى أصلًا**: أدوارُ الإدارات تحمل وحدتها في اسمها
 * («قائد إدارة الموارد البشرية»)، فإلحاقُها ثانيةً تكرار. وأدوارُ اللجان رتبةٌ مجرّدة،
 * فتُلحَق بها لجنتُها — فيطّرد النداء في الحالين.
 */
export function salutation(l: Pick<WarningLetter, "name" | "gender" | "role" | "committee">): string {
  const role = l.role?.trim();
  // بلا منصب: «الأدِيب» و«الأدِيبة» — نسبةٌ إلى النادي لا نداءٌ عامّ (قرار المالك)
  if (!role) return `${g(l.gender, "الأدِيب", "الأدِيبة")} ${l.name}`;
  const [head, ...rest] = role.split(" ");
  const rank = l.gender === "female" ? [FEMININE[head] ?? head, ...rest].join(" ") : role;
  const unit = l.committee?.trim();
  const title = unit && !role.includes(unit) ? `${rank} ${unit}` : rank;
  return `${title} ${l.name}`;
}

/** التحيّة — سطرٌ قائمٌ بذاته يعلو النداء (كما في البوست). */
export const greeting = "السلام عليكم ورحمة الله وبركاته";

/** التوقيع — يُكتب في الرسالة، وأمّا الورقة فتوقيعُها وختمُها مطبوعان في القالب. */
export const signature = "إدارة الموارد البشرية | نادي أديب";

/** هل بلغ هذا الإنذارُ الحدَّ فسُحبت به العضويّة؟ */
const isFinal = (l: WarningLetter): boolean => l.activeCount >= l.limit;

/** «إنذارٌ واحد» · «إنذاران» · «٣ إنذارات» — تمييزٌ عربيّ لِما بقي قبل الحدّ. */
function leftPhrase(l: WarningLetter): string {
  const left = Math.max(0, l.limit - l.activeCount);
  return left === 1 ? "إنذارٌ واحد" : left === 2 ? "إنذاران" : `${left} إنذارات`;
}

/**
 * متنُ الخطاب — فقراتٌ يرسمها القالب سطرًا سطرًا، وتُبنى منها رسالةُ واتساب كما هي.
 * لا تحيّةَ فيه ولا نداء ولا توقيع: تلك أسطرٌ لها مواضعُها في الورقة وفي الرسالة.
 */
export function letterParagraphs(l: WarningLetter): string[] {
  const out = [
    // لكلّ تصنيفٍ جملتُه (`observationSentence`) — ولا تُذكر اللجنة في النصّ
    `نودّ إشعارك بأنّه ${observationSentence(l.category)}.`,
    `وتفصيل ذلك: ${l.reason.trim()}`,
    "ونقدّر ظروف الجميع، ونأمل منك التفاعل خلال الفترة القادمة. وفي حال وجود أيّ عائقٍ أو ظرفٍ يمنعك من المشاركة نرجو إبلاغنا به.",
  ];

  if (isFinal(l)) {
    out.push(
      `ونحيطك علمًا بأنّه تمّ إصدار الإنذار ${ordinalWord(l.ordinal)} لك بتاريخ ${fmtDate(l.issuedAt)}، وبه ${
        g(l.gender, "بلغتَ", "بلغتِ")
      } الحدّ المقرّر (${countWord(l.limit)} إنذارات) وفقًا ل${CHARTER}، وعليه سُحبت عضويّتك من نادي أديب اعتبارًا من تاريخه.`,
      `ونشكر لك ما ${g(l.gender, "بذلتَ", "بذلتِ")}، ويبقى بابُ الإدارة مفتوحًا لأيّ توضيح.`,
    );
  } else {
    out.push(
      `ونحيطك علمًا بأنّه تمّ إصدار الإنذار ${ordinalWord(l.ordinal)} لك بتاريخ ${fmtDate(l.issuedAt)} وفقًا ل${CHARTER}، وأنّ بلوغ ${countWord(l.limit)} إنذارات يوجب سحب العضويّة، وقد بقي لك ${leftPhrase(l)}. ونأمل عدم تكرار ذلك مستقبلًا.`,
      "كما نتطلّع إلى رؤية إبداعك وشغفك في العمل بما يليق باللجنة.",
    );
  }

  out.push("مع تمنياتنا لك بالتوفيق.");
  return out;
}

/**
 * رسالة واتساب — **وجيزةٌ تُحيل إلى الورقة** (قرار المالك): الخطاب مرفقٌ مع الرسالة، فإعادةُ
 * متنِه في المحادثة تكرارٌ يُقرأ مرّتين ويُملّ قبل أن يبلغ خبرَه.
 *
 * وليست نصًّا ثانيًا ينحرف عن الأوّل: **لا جملةَ فيها من عند نفسها** — النداءُ والرتبةُ والتاريخ
 * والعاقبة كلُّها من `WarningLetter` نفسها التي رُسمت منها الورقة، والتفصيلُ (جملةُ التصنيف
 * والسبب) لا يُنسَخ بل يُحال إليه. فما يتغيّر في الخطاب يتغيّر معه هنا، ولا يفترقان.
 *
 * **والتوقيع يلتصق بالخاتمة** (تحت «مع تمنياتنا لك بالتوفيق» بلا سطرٍ فارغ) — قرار المالك.
 */
export function warningWhatsappMessage(l: WarningLetter): string {
  const notice = `نودّ إشعارك بصدور الإنذار ${ordinalWord(l.ordinal)} بحقّك بتاريخ ${
    fmtDate(l.issuedAt)
  }، وتجد${g(l.gender, "", "ين")} تفاصيله وأسبابه في الخطاب المرفق.`;

  const consequence = isFinal(l)
    ? `وبه ${g(l.gender, "بلغتَ", "بلغتِ")} الحدّ المقرّر (${
      countWord(l.limit)
    } إنذارات) وفقًا ل${CHARTER}، وعليه سُحبت عضويّتك من نادي أديب اعتبارًا من تاريخه.`
    : `وقد بقي لك ${leftPhrase(l)} قبل بلوغ الحدّ المقرّر في ${CHARTER}.`;

  const closing = isFinal(l)
    ? `ونشكر لك ما ${g(l.gender, "بذلتَ", "بذلتِ")}، ويبقى بابُ الإدارة مفتوحًا لأيّ توضيح.`
    : "وفي حال وجود أيّ عائقٍ أو ظرفٍ نرجو إبلاغنا به.";

  return [
    greeting,
    salutation(l),
    "",
    notice,
    consequence,
    closing,
    "",
    "مع تمنياتنا لك بالتوفيق.",
    signature,
  ].join("\n");
}
