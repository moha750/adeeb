/**
 * نصّ شهادة الخبرة — **مصدرٌ واحد**، وأصلُه ورقةُ المالك في الفوتوشوب حرفًا بحرف
 * (العيّنة المعتمدة: «الجازي محمد الغوينم — عضو لجنة السفراء والتصوير»).
 *
 * والورقةُ ستّة أسطر: بيتان، ثمّ الشهادة بالمسمّى، ثمّ الاسم، ثمّ الفترة، ثمّ الدعاء.
 * ثلاثةٌ منها ثابتةٌ لا تتغيّر إلّا بجنس صاحبها، وثلاثةٌ تحمل البيانات.
 *
 * **والمسمّى لا يُؤنَّث** (نصُّ قالبك: «تشهد عائلة أديب بخبرة وكفاءة **عضو** لجنة السفراء
 * والتصوير» — لأنثى). وهذا يفارق نداءَ خطاب الإنذار عمدًا: هناك خطابٌ لصاحبه، وهنا وصفُ
 * مقعدٍ في الهيكل.
 */

export type Gender = "male" | "female" | null;

export type Certificate = {
  /** الاسم كما يُرسَم — الثلاثيّ إن وُجد، وللمُصدِر تصحيحُه قبل الإصدار. */
  name: string;
  /**
   * الرقم المرجعيّ — يُطبع في زاوية الورقة مع رابط التحقّق. وغيابُه يُسقط السطر كلَّه
   * (المعاينة عيّنةٌ لا سجلّ، فلا رقمَ لها ولا تحقّق).
   */
  serial?: string | null;
  /** المسمّى كاملًا: «عضو لجنة السفراء والتصوير» · «قائد إدارة الموارد البشرية». */
  position: string;
  gender: Gender;
  /** تاريخ الانضمام (ISO) — من `profiles.joined_date`. */
  from: string;
  /** تاريخ الإصدار (ISO). */
  to: string;
};

const g = (gender: Gender, male: string, female: string) => (gender === "female" ? female : male);

/**
 * التاريخ كما في ورقتك: `[2024/10/17]` — سنةٌ فشهرٌ فيوم، **بلا تصفير** (8/29 لا 08/29)،
 * بين معقوفتين. ونقرؤه من نصّ ISO لا من `Date` المحلّيّ، فلا تزحف المنطقةُ الزمنيّة بيوم.
 */
export function certDate(iso: string): string {
  const [y, m, d] = iso.slice(0, 10).split("-");
  return `[${y}/${Number(m)}/${Number(d)}]`;
}

/**
 * البيتان — ثابتان إلّا من ضمير المخاطَب. **ومطبوعان في القالبين** (ذكر/أنثى) لا يرسمهما
 * البرنامج، لأنّ مدَّهما بالكشيدة تنسيقُ فوتوشوب. ويبقيان هنا **مصدرَ لفظِهما**: من أعاد
 * تصدير القالب نقلَ النصّ من هذا الموضع، ولا يُكتب اللفظ في مكانين.
 */
export const verses = (gender: Gender): [string, string] => [
  `ما من مهمةٍ في أديب إلا وحملت${g(gender, "َ", "ِ")} فيها أمانةً وأثرًا`,
  `ولا من تجربةٍ مررت${g(gender, "َ", "ِ")} بها إلا وأضافت إلى خبرتك${g(gender, "َ", "ِ")} نضجًا وقدرًا`,
];

/** سطر الشهادة — وفيه المسمّى، وهو أطولُ ما قد يطول فيُضغط مقاسُه عند الرسم. */
export const testimony = (c: Certificate): string =>
  `تشهد عائلة أديب بخبرة وكفاءة ${c.position}`;

/** سطر الفترة — من الانضمام إلى الإصدار. */
export const period = (c: Certificate): string =>
  `خبرةٌ صُقلت بالإتقان طوال الفترة من ${certDate(c.from)} إلى ${certDate(c.to)}`;

/** موضع التحقّق العلنيّ — نطاقُ النادي، ويُقرأ في الورقة وفي شاشة التحقّق سواء. */
export const VERIFY_HOST = "adeeb.club";

/**
 * ما يحمله الباركود: عنوانٌ يفتح صفحة التحقّق **بالرقم مملوءًا** — فمن مسحه رأى الجواب
 * بلا كتابة. (والرابط لا يُطبع نصًّا: شكلُ العنوان في وثيقةٍ رسميّة قبيح — قرار المالك.)
 */
export const verifyUrl = (serial: string): string =>
  `https://${VERIFY_HOST}/verify?code=${encodeURIComponent(serial)}`;

/** سطرُ الوثيقة الصغير: رقمُها المرجعيّ وحده — يُقرأ بالعين ويُكتب باليد إن تعذّر المسح. */
export const verifyLine = (serial: string): string => `الرقم المرجعيّ ${serial}`;

/** تسميةُ الباركود تحته — كلمتان تقولان ما هو، فلا يبقى مربّعًا غامضًا. */
export const QR_CAPTION = "امسح للتحقّق";

/** الدعاء — خاتمةُ الورقة، وضميرُها يتبع صاحبها. **مطبوعٌ في القالبين** كالبيتين. */
export const closing = (gender: Gender): string =>
  gender === "female"
    ? "نفخر بأنّكِ كنتِ منّا، ونتمنّى لكِ التوفيق في مسيرتكِ القادمة"
    : "نفخر بأنّكَ كنتَ منّا، ونتمنّى لكَ التوفيق في مسيرتكَ القادمة";
