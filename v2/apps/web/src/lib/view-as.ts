import "server-only";
import { cookies } from "next/headers";

/**
 * «المعاينة كـ» — استعارةُ هويّةٍ كاملة لرؤية اللوحة كما يراها صاحبُ منصبٍ **والتنفيذُ بصلاحيّته**.
 *
 * لماذا هويّةٌ كاملة لا قدراتٌ مُعارة: نصف تبويبات اللوحة **نطاقُها هويّة لا قدرة** —
 * «إدارتي» و«قسمي» و«لجنتي» تُشتقّ من صفّك الحيّ (`lib/myScope.ts`)، و`can_assign_role` في
 * القاعدة تفحص الشرط نفسه. فمنحُ القدرة وحدها يفتح غرفةً فارغة والقاعدة ترفض الكتابة. واستعارةُ الهويّة
 * تسري على الاثنين معًا **بلا لمس أيّ إجراء**: كلّ كتابةٍ في اللوحة تمرّ بـ`p_actor: admin.id`،
 * فالقاعدة تحكم بالهويّة المستعارة كما تحكم بصاحبها.
 *
 * **الحارس ليس الكوكي بل قدرة صاحب الجلسة** — تُفحَص في كلّ طلب (`lib/auth.ts`). فمن زوّر
 * الكوكي بلا `manage_permissions` لم يستعر شيئًا.
 *
 * **تحفّظ صادق:** ما يُكتب أثناء المعاينة يُنسَب في سجلّ النشاط إلى **المُعايَن** لا إليك —
 * لأنّ الهويّة هي المستعارة. لذلك الشريط ظاهرٌ فوق كلّ صفحة ولا يُخفى.
 */
export const VIEW_AS_COOKIE = "adeeb_view_as";

/** مفتاح المعاينة — قدرة الصلاحيات نفسها: من يملك منحَ القدرات يملك رؤيتها مُطبَّقة. */
export const VIEW_AS_CAP = "manage_permissions";

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/** معرّف المُعايَن من الكوكي — شكلًا فقط؛ الإذن يُفحَص عند القارئ لا هنا. */
export async function readViewAsTarget(): Promise<string | null> {
  const raw = (await cookies()).get(VIEW_AS_COOKIE)?.value?.trim();
  return raw && UUID.test(raw) ? raw : null;
}
