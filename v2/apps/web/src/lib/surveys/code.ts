/**
 * **رمزُ الاستبيان القصير — مصدرٌ واحد** (قرار المالك ٢٠٢٦-١٠-١٩).
 *
 * رابطُ الاستبيان العلنيّ `adeeb.club/s/<code>` لا `‎/surveys/<id>`: الرقمُ المتسلسل يُجرَّب
 * بالعدّ فيوصِل إلى كلّ استبيانٍ عامّ ويكشف عددَها، والرمزُ ستّةُ أحرفٍ عشوائيّة لا تُخمَّن.
 * يولده الزنادُ في القاعدة (`surveys_code_guard`) ولا يتبدّل، والرقمُ باقٍ مفتاحًا داخليًّا
 * لكلّ ما سوى الرابط. والروابطُ القديمة يحوّلها `app/surveys/[id]/route.ts`.
 *
 * والشكلُ هنا مرآةُ قيد القاعدة `surveys_code_shape` — يتغيّران معًا أو لا يتغيّران:
 * أبجديّةٌ صغيرةٌ بلا ما يلتبس (لا `0/o` ولا `1/l/i`). وحدةٌ نقيّة يستوردها الخادمُ والعميل.
 */
const SURVEY_CODE_SHAPE = /^[a-hjkmnp-z2-9]{6}$/;

/** شكلُ الرمز يُفحَص قبل أيّ استعلام: الخُردةُ تُردّ بلا أن تلمس القاعدة. */
export const isSurveyCode = (code: string): boolean => SURVEY_CODE_SHAPE.test(code);

/** مسارُ صفحة التعبئة. */
export const surveyPath = (code: string): string => `/s/${code}`;

