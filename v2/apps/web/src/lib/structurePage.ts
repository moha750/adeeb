import "server-only";
import { revalidatePath } from "next/cache";

/**
 * **صفحةُ «هيكلة أدِيب» العلنيّة** — مسارُها وإنعاشُها من مصدرٍ واحد.
 *
 * تُبنى الصفحةُ مرّةً كلَّ خمس دقائق (`revalidate = 300`)، وهذا شبكةُ أمانٍ لا أكثر: كلُّ إجراءٍ
 * يغيّر ما تعرضه (إسنادٌ وإزالةٌ وتكليف، وإنهاءُ عضويّةٍ وإعادتُها، وفوزٌ في انتخاب، وتعديلُ وحدة،
 * واسمُ العضو وصورتُه وجنسُه) يستدعي `refreshStructurePage` فيظهر التغييرُ لحظةَ الحفظ
 * (المالك ٢٠٢٦-١٠-١٨: «أريد ظهور المتغيّرات مباشرة»). وما يتغيّر في القاعدة بلا إجراءٍ من الموقع
 * (مهمّةٌ مجدولة تُنهي تكليفًا) يلحقه البناءُ الدوريّ.
 */
export const STRUCTURE_PATH = "/structure";

export function refreshStructurePage() {
  revalidatePath(STRUCTURE_PATH);
}
