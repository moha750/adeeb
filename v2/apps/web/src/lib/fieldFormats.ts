// صيغُ الحقول المشتركة — **المصدر الواحد** لما يُعدّ بريدًا صحيحًا وما يُعدّ جوّالًا صحيحًا،
// في كلّ باب من أبواب الموقع: الدخول والتسجيل واستعادة كلمة المرور ورسائل التواصل وحجز
// الفعاليّات وإكمال السجلّ وملفّ العضو وبيانات الدخول وأسئلة الاستبيانات.
//
// **ولمَ مِلفٌّ مستقلٌّ عن `membershipFields`؟** لأنّ البريد والجوّال يُكتبان في أبوابٍ لا علاقة
// لها بالعضويّة (شاشة الدخول · نموذج التواصل · إجابة استبيان)، فاستيرادُ «حقول العضويّة» فيها
// كذبٌ على القارئ. و`membershipFields` يعيد تصدير قواعد الجوّال من هنا فلا يُكسَر أيّ مستورد.
//
// لا يعتمد على شيء خادميّ، فيستوردها الخادم والعميل معًا بأمان.

/* ══ البريد الإلكترونيّ ═══════════════════════════════════════════════════════════
 * كان هذا التعبير مكتوبًا **أربع مرّات** في أربعة ملفّات، ونسختان منه تختلفان فعلًا
 * (`{2,}` مقابل `+` في آخر مقطع) — أي أنّ البريد الواحد كان يُقبل في بابٍ ويُردّ في آخر.
 *
 * والصيغة متعمَّدةُ التساهل: لا تدّعي تطبيق RFC 5322 (وهو أوسع ممّا يُتخيَّل ولا يُكتب في سطر)،
 * وإنّما تردّ ما لا يمكن أن يكون بريدًا أصلًا — بلا `@`، أو بلا نطاقٍ بعده، أو بلا لاحقةٍ من
 * حرفين فأكثر، أو فيه مسافة. وما جاوزها فحَكَمُه رسالةُ التأكيد لا التعبير.
 */
export const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/;
export const EMAIL_HINT = "صيغة البريد الإلكترونيّ غير صحيحة";

/* ══ رقم الجوّال ══════════════════════════════════════════════════════════════════
 * صيغة الجوّال السعوديّ — مصدر واحد للطبقات الثلاث: مخطّط النموذج · الفعل الخادميّ ·
 * قيد القاعدة `profiles_phone_check` (وهو `^05[0-9]{8}$` حرفًا بحرف). غيّرها هنا ⇐ عدّل
 * القيد بترحيلٍ مقابل، ولا تُبقِ الطبقتين تفترقان.
 */
export const PHONE_RE = /^05[0-9]{8}$/;
export const PHONE_HINT = "صيغة رقم الجوّال غير صحيحة";
/** الطول الملزِم — لا أكثر ولا أقلّ. يخدم `maxLength` على المُدخَل والتعبيرَ أعلاه معًا. */
export const PHONE_LEN = 10;

/**
 * **اللصيقة الثابتة** التي تُعرَض قبل حقل الجوّال (قرار المالك ٢٠٢٦-٠٨-١٥).
 *
 * عرضٌ لا بيانات: المحفوظ يبقى `05xxxxxxxx` عشرةَ أرقامٍ كما يحرسه قيد القاعدة، واللصيقة
 * تقول البلد وحدها. ولم يُفتح خطُّ الدولة اختيارًا لأنّ النظام سعوديٌّ بتصميمه (رقم الهويّة ·
 * الرقم الأكاديميّ · `saudiIntl` في `lib/whatsapp`)، ولأنّ أطوال الأرقام بحسب الدولة مدًى
 * لا رقم فيسقط بها حدُّ «عشرةٌ لا غير».
 */
export const PHONE_PREFIX = "+966";

/* ══ رسائلُ الحقول عند الكتابة ════════════════════════════════════════════════════
 * دالّتان تُغنيان عن تكرار الشرط في كلّ نموذج، وتضمنان أنّ اللفظ واحدٌ في كلّ باب.
 *
 * و`touched` شرطٌ مقصود: **لا يُخطَّأ المستخدم وهو يكتب** — أوّلُ محرفٍ من البريد ليس بريدًا
 * صالحًا بعدُ، فإظهارُ الخطأ عنده إزعاجٌ لا إرشاد. فتُرفَع الرايةُ عند مغادرة الحقل (`onBlur`)
 * أو عند محاولة الإرسال، لا قبلهما.
 */

/** خطأُ البريد إن وجب إظهاره، وإلّا `undefined`. الفارغُ لا يُخطَّأ ههنا: إلزامُه شأنُ `required`. */
export const emailError = (value: string, touched: boolean): string | undefined => {
  if (!touched) return undefined;
  const v = value.trim();
  if (!v) return undefined;
  return EMAIL_RE.test(v) ? undefined : EMAIL_HINT;
};

/** خطأُ الجوّال إن وجب إظهاره، وإلّا `undefined`. */
export const phoneError = (value: string, touched: boolean): string | undefined => {
  if (!touched) return undefined;
  const v = value.trim();
  if (!v) return undefined;
  return PHONE_RE.test(v) ? undefined : PHONE_HINT;
};

/** هل القيمة بريدٌ صالح؟ — تُسأل عند الإرسال حيث لا معنى لـ`touched`. */
export const isEmail = (value: string): boolean => EMAIL_RE.test(value.trim());
/** هل القيمة جوّالٌ صالح؟ */
export const isPhone = (value: string): boolean => PHONE_RE.test(value.trim());
