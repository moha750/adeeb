/**
 * اشتقاق السلاگ — **المصدر الواحد** لكلّ من يحتاجه (المكتبة · الإذاعة · ما يأتي).
 * آمنٌ للعميل والخادم معًا (لا يعتمد على شيء خادميّ).
 *
 * يحوّل نصًّا حرًّا إلى سلاگ لاتينيّ: أحرف/أرقام صغيرة وشُرَط. يعيد "" إن لم يبقَ محرف صالح.
 * والصيغة نفسها يحرسها قيدٌ في القاعدة (`*_slug_format`) — فما يمرّ هنا يمرّ هناك.
 */
export function slugify(raw: string): string {
  return raw
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}
