import { describe, expect, it } from "vitest";
import { ARABIC_NAME_HINT, arabicNameError, firstAndLastOf, normalizeName } from "@/lib/personName";

/**
 * حارسُ الاسم — أخطرُ ملفٍّ نقيٍّ في المستودع: يُقرأ في سبعة أبواب، ويُطبع في شهادةٍ
 * ويُرسَم في خطابٍ ويُنادى به في كشف. فكلُّ حالةٍ ههنا واقعةٌ يمنعها الملفُّ بنصّ تعليقه،
 * لا حالةٌ اخترعناها لنملأ بها عدّادًا.
 */

describe("normalizeName", () => {
  it("يُبقي الاسم النظيف كما هو", () => {
    expect(normalizeName("أحمد سالم")).toBe("أحمد سالم");
  });

  it("يقصّ الطرفين ويقلّص المسافات المتوالية إلى واحدة", () => {
    expect(normalizeName("   أحمد    بن   سالم   ")).toBe("أحمد بن سالم");
  });

  // اللصقُ العربيّ يجرّ معه محارفَ اتّجاهٍ خفيّة، فيُخزَّن اسمٌ يبدو صحيحًا ولا يُطابَق
  it("ينزع محارف الاتّجاه الخفيّة U+200B إلى U+200F", () => {
    expect(normalizeName("​أحمد‌‍‎‏سالم")).toBe("أحمدسالم");
  });

  it("ينزع محارف التضمين U+202A إلى U+202E", () => {
    expect(normalizeName("‪نورة‫‬‭‮")).toBe("نورة");
  });

  it("ينزع محارف العزل U+2066 إلى U+2069", () => {
    expect(normalizeName("⁦خالد⁧⁨⁩")).toBe("خالد");
  });

  // التطويلُ زينةٌ لا حرف: «محـــمد» و«محمد» اسمٌ واحدٌ لا اسمان في السجلّ
  it("ينزع التطويل U+0640", () => {
    expect(normalizeName("محـــمد")).toBe("محمد");
  });

  it("السطرُ الجديد والجدولة مسافةٌ واحدة", () => {
    expect(normalizeName("أحمد\n\tسالم")).toBe("أحمد سالم");
  });

  it("الفارغُ يبقى فارغًا", () => {
    expect(normalizeName("")).toBe("");
    expect(normalizeName("   ")).toBe("");
  });
});

describe("arabicNameError", () => {
  it("يقبل الاسم العربيّ", () => {
    expect(arabicNameError("أحمد بن سالم الغامدي")).toBeNull();
  });

  // «زَهراء» اسمٌ مشكولٌ لا اسمٌ مخالف — التشكيلُ مقبولٌ بنصّ التعليق
  it("يقبل الاسم المشكول", () => {
    expect(arabicNameError("زَهرَاء جَواد")).toBeNull();
  });

  it("يقبل الهمزات والمدّة والتاء المربوطة والألف المقصورة", () => {
    expect(arabicNameError("آلاء إسراء أُميّة عائشة ليلى")).toBeNull();
  });

  it("يقبل ما فيه تطويلٌ أو محرفُ اتّجاهٍ لأنّه يُطبَّع قبل الوزن", () => {
    expect(arabicNameError("محـــمد‏العتيبي")).toBeNull();
  });

  // حرفٌ لاتينيٌّ يقلب سطرَ السجلّ ويكسر الورقة المطبوعة (علّةُ الحارس بنصّها)
  it("يردّ الحرف اللاتينيّ", () => {
    expect(arabicNameError("Ahmad")).toBe(ARABIC_NAME_HINT);
    expect(arabicNameError("أحمد Ali")).toBe(ARABIC_NAME_HINT);
  });

  it("يردّ الأرقام اللاتينيّة", () => {
    expect(arabicNameError("أحمد5")).toBe(ARABIC_NAME_HINT);
  });

  it("يردّ علامات الترقيم والرموز", () => {
    expect(arabicNameError("أحمد.")).toBe(ARABIC_NAME_HINT);
    expect(arabicNameError("أحمد-سالم")).toBe(ARABIC_NAME_HINT);
    expect(arabicNameError("أحمد_سالم")).toBe(ARABIC_NAME_HINT);
    expect(arabicNameError("أحمد@")).toBe(ARABIC_NAME_HINT);
  });

  /**
   * **حدُّ مدى التشكيل — أدقُّ سطرٍ في الملفّ.**
   *
   * `ARABIC_MARKS` مدًى من U+064B إلى U+0655 ومعه U+0670 مفردًا. ولو كُتب المدى إلى U+0670
   * وصلًا (وهو خطأٌ سهلٌ في نظرة العين، إذ يبدو المحرفان متجاورين) لابتلع أرقامَ العربيّة
   * الهنديّة U+0660–U+0669 وفواصلَها U+066A–U+066D — فجاز «أحمد٥» و«محمد٪» على حارسٍ
   * عنوانُه «الحروف العربيّة وحدها». هذان الاختباران يقفان على ذلك الحدّ.
   */
  it("يردّ أرقام العربيّة الهنديّة", () => {
    expect(arabicNameError("أحمد٥")).toBe(ARABIC_NAME_HINT);
    expect(arabicNameError("٠١٢٣")).toBe(ARABIC_NAME_HINT);
  });

  it("يردّ علامة النسبة العربيّة ٪ وفواصلَها", () => {
    expect(arabicNameError("محمد٪")).toBe(ARABIC_NAME_HINT);
    expect(arabicNameError("محمد٫")).toBe(ARABIC_NAME_HINT);
  });

  // طرفا المدى نفسُهما: همزةٌ تحت (U+0655) وألفٌ خنجريّة (U+0670) حرفان مقبولان
  it("يقبل طرفَي مدى التشكيل: U+0655 و U+0670", () => {
    expect(arabicNameError("عبد الرحمٰن")).toBeNull();
    expect(arabicNameError("إٕيمان")).toBeNull();
  });

  it("يردّ الأرقام الفارسيّة أيضًا", () => {
    expect(arabicNameError("احمد۵")).toBe(ARABIC_NAME_HINT);
  });

  // الخلوُّ ليس من شأنه: كلُّ بابٍ يعرف كم يلزمه من الاسم، فلا تُصادَر رسالتُه
  it("لا يحكم على الفارغ ولا على العدم", () => {
    expect(arabicNameError("")).toBeNull();
    expect(arabicNameError("   ")).toBeNull();
    expect(arabicNameError(null)).toBeNull();
    expect(arabicNameError(undefined)).toBeNull();
  });
});

describe("firstAndLastOf", () => {
  it("الاسم المفرد يعود كما هو", () => {
    expect(firstAndLastOf("أحمد")).toBe("أحمد");
  });

  it("الاسمان يعودان كما هما", () => {
    expect(firstAndLastOf("أحمد الغامدي")).toBe("أحمد الغامدي");
  });

  it("الرباعيّ يُختصَر إلى طرفيه", () => {
    expect(firstAndLastOf("أحمد سالم فهد الغامدي")).toBe("أحمد الغامدي");
  });

  // «عبد الله» اسمٌ واحدٌ كُتب كلمتين، وأخذُ الكلمات عدًّا يُخرِج «عبد» وحدَها: نداءٌ لا يُقال
  it("«عبد» تبتلع ما بعدها فلا يُنادى أحدٌ بـ«عبد»", () => {
    expect(firstAndLastOf("عبد الله سالم الحربي")).toBe("عبد الله الحربي");
  });

  // آخِرُ «نورة بنت سعد آل سعود» هو «آل سعود» لا «سعود» (المثالُ من تعليق الملفّ نفسه)
  it("«آل» تبتلع ما بعدها فلا تنقطع العائلة عن اسمها", () => {
    expect(firstAndLastOf("نورة بنت سعد آل سعود")).toBe("نورة آل سعود");
  });

  it("«بن» و«بنت» و«ابن» و«ابنة» كلماتُ وصلٍ لا أسماء", () => {
    expect(firstAndLastOf("محمد بن سالم بن فهد القحطاني")).toBe("محمد القحطاني");
    expect(firstAndLastOf("سارة ابنة عمر الدوسري")).toBe("سارة الدوسري");
    expect(firstAndLastOf("خالد ابن سعد المطيري")).toBe("خالد المطيري");
  });

  it("«ذو» و«ذي» و«أبا» و«أبي» في القائمة كسائر كلمات الوصل", () => {
    expect(firstAndLastOf("مالك ذو الفقار الشمري")).toBe("مالك الشمري");
    expect(firstAndLastOf("عمر أبا الخيل العنزي")).toBe("عمر العنزي");
    expect(firstAndLastOf("سعد أبي بكر الزهراني")).toBe("سعد الزهراني");
  });

  // **حلقةُ التوالي** — «أبو عبد الله» ثلاثُ كلماتٍ واسمٌ واحد. ولولا الحلقة (لو كان الابتلاع
  // مرّةً واحدة) لخرج «أبو عبد» ثمّ «الله» اسمين، فيُنادى المرءُ بـ«الله».
  it("كلماتُ الوصل تتوالى فتصير «أبو عبد الله» اسمًا واحدًا", () => {
    expect(firstAndLastOf("أبو عبد الله")).toBe("أبو عبد الله");
  });

  it("سلسلةُ وصلٍ في الأوّل واسمُ عائلةٍ بعدها", () => {
    expect(firstAndLastOf("أبو عبد الله الشهري")).toBe("أبو عبد الله الشهري");
  });

  // الحلقةُ تعمل في آخر الاسم كما تعمل في أوّله
  it("سلسلةُ وصلٍ في آخر الاسم تُؤخَذ كاملةً", () => {
    expect(firstAndLastOf("سعد فهد آل عبد الله")).toBe("سعد آل عبد الله");
  });

  it("لا يقع «عبد» وحدَها طرفًا حتّى لو كانت الاسم الأوّل والاسم قبل الأخير", () => {
    expect(firstAndLastOf("عبد الرحمن عبد العزيز السبيعي")).toBe("عبد الرحمن السبيعي");
  });

  it("المسافات الزائدة في الطرفين وبين الأسماء لا تُنشئ اسمًا فارغًا", () => {
    expect(firstAndLastOf("   أحمد    سالم    الغامدي   ")).toBe("أحمد الغامدي");
    expect(firstAndLastOf("أحمد\n\tسالم\tالغامدي")).toBe("أحمد الغامدي");
  });

  // ولا اسمَ يُقسَم: تعود المُدخَلة كما جاءت (`names[0] ?? full`) ولا تُرمى استثناءً.
  // والمسافاتُ تعود بمسافاتها لأنّ القسمة لا تُطبِّع — وهو العقدُ المثبَّت في آخر هذا الملفّ.
  it("الفارغُ يعود فارغًا ولا يرمي", () => {
    expect(firstAndLastOf("")).toBe("");
    expect(firstAndLastOf("   ")).toBe("   ");
    expect(firstAndLastOf(normalizeName("   "))).toBe("");
  });

  // كلمةُ وصلٍ في آخر الاسم لا تجد ما تبتلعه، فتبقى اسمًا بنفسها ولا تُسقِط الاسمَ كلَّه
  it("كلمةُ وصلٍ معلّقةٌ في الآخر تبقى ولا تكسر القسمة", () => {
    expect(firstAndLastOf("أحمد بن")).toBe("أحمد بن");
  });

  /**
   * **`firstAndLastOf` ليست مُطبِّعًا**: تقسم ما يُعطى كما يُعطى. فمحرفُ اتّجاهٍ ملتصقٌ
   * بكلمة وصلٍ يمنع مطابقتها فتنقطع «عبد» عن «الله». والعقدُ أن يُنادى `normalizeName`
   * قبلها (وهو ما تفعله أبوابُ الحفظ)، وهذا الاختبارُ يثبّت العقدَ صراحةً كي لا يُنسى.
   */
  it("المحرفُ الخفيّ يكسر مطابقةَ كلمة الوصل، فالتطبيعُ قبلها عقدٌ لا تحسين", () => {
    expect(firstAndLastOf("عبد‏ الله سالم الحربي")).not.toBe("عبد الله الحربي");
    expect(firstAndLastOf(normalizeName("عبد‏ الله سالم الحربي"))).toBe("عبد الله الحربي");
  });
});
