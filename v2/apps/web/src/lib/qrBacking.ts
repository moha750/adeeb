/**
 * **على أيّ ورقةٍ يُعرض الباركود**: الشفّافُ (بلا خلفيّة) يُعرض على مربّعات الشفافيّة المعروفة في برامج التصميم، وما له خلفيّةٌ فهي ورقتُه
 * والفاتحةُ حولها لا تضرّ. كانت (٢٠٢٦-١١-١٦) ورقةً كحليّةً تُقرأ من الحبر حين يكون فاتحًا، فسأل محمد (٢٠٢٦-١١-١٧): «هل أنا اخترت أن تكون
 * الخلفيّة كحليّة؟» — لم يخترها، وتحتها «ما تراه هو ما يُطبع» والكحليُّ لا يُطبع. فاختار المربّعات: تقول «شفّاف» ولا تدّعي لونًا.
 */
import type { QrSpec } from "@/lib/qr";

/** `clear` حين تكون الخلفيّةُ شفّافة */
export function qrBacking(spec: QrSpec | null | undefined): "light" | "clear" {
  return spec && !spec.bg ? "clear" : "light";
}
